    //   함수 = 특정 작업을 하는 코드 묶음에 이름을 붙인 것
    //
    //   비유: 자판기처럼 생각해보세요!
    //         ┌─────────────────────────────────┐
    //         │           자판기                 │
    //         │   입력: 동전 + 버튼              │
    //         │   처리: 내부에서 알아서 함       │
    //         │   출력: 음료수                   │
    //         └─────────────────────────────────┘
    //
    //   함수도 똑같아요:
    //         ┌─────────────────────────────────┐
    //         │           add 함수               │
    //         │   입력(매개변수): a=3, b=4       │
    //         │   처리: a + b 계산               │
    //         │   출력(반환값): 7                │
    //         └─────────────────────────────────┘
    //
    //   함수를 쓰는 이유:
    //   1. 재사용성: 한 번 만들면 여러 곳에서 사용
    //   2. 가독성: 코드가 깔끔해짐
    //   3. 유지보수: 수정할 때 한 곳만 바꾸면 됨
    //   4. 분업: 여러 사람이 각자 함수를 만들어 합칠 수 있음
    //

    printf("==============================================\n");
    printf("   03단계: 함수\n");
    printf("==============================================\n\n");

    // 함수 호출하기
