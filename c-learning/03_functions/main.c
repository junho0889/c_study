    // ─────────────────────────────────────────────────────────────────────
    // 4. 재귀 함수 (Recursive Function)
    // ─────────────────────────────────────────────────────────────────────
    //
    //   재귀 = 함수가 자기 자신을 호출하는 것
    //
    //   비유: 거울 두 개를 마주 보게 세우면 안에 작은 거울이 계속 나타나죠?
    //         그것처럼 함수 안에서 같은 함수를 계속 부르는 것입니다.
    //
    //   팩토리얼(!) 수학적 정의:
    //       0! = 1
    //       n! = n × (n-1)!
    //       5! = 5 × 4! = 5 × 4 × 3! = 5 × 4 × 3 × 2 × 1 = 120
    //
    //   ⚠️ 중요: 재귀는 반드시 종료 조건이 있어야 합니다!
    //            종료 조건 없이 자기 자신을 계속 부르면
    //            "스택 오버플로우" 오류가 납니다.
    //            비유: 화장실 거울 안에 또 화장실이 생기면 끝이 없죠?
    //

    printf("\n─────────────────────────────────────\n");
    printf("  재귀 함수: 팩토리얼\n");
    printf("─────────────────────────────────────\n");

    for (int i = 0; i <= 10; i++) {
        printf("%d! = %d\n", i, factorial(i));
    }

    printf("\n[재귀 함수: 피보나치 수열]\n");
    printf("피보나치: ");
    for (int i = 0; i < 10; i++) {
        printf("%d ", fibonacci(i));
    }
    printf("\n");
    printf("(주의: 재귀 피보나치는 큰 수에서 매우 느려집니다!)\n");

