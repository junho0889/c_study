// ─────────────────────────────────────────────────────────────────────────────
// ■ 함수 정의 (구현부)
// ─────────────────────────────────────────────────────────────────────────────
//
//   함수 구조:
//   ┌──────────────────────────────────────────────────────────────────────┐
//   │  반환타입  함수이름 (매개변수1타입 매개변수1이름, ...) {              │
//   │      // 함수 몸체 (Body): 실제로 할 일                              │
//   │      return 반환값;  // (void 함수면 return 없어도 됨)              │
//   │  }                                                                   │
//   └──────────────────────────────────────────────────────────────────────┘
//

// ── 인사 출력 함수 ────────────────────────────────────────────────────────────
//   반환값 없으므로 void, 매개변수도 없으므로 void
void print_greeting(void) {
    // 비유: 버튼 누르면 자동으로 나오는 인사말 기계
    printf("안녕하세요! 03단계 함수를 배워봅시다!\n");
    global_count++;  // 전역 변수 증가
}

// ── 선 그리기 함수 ────────────────────────────────────────────────────────────
//   매개변수: ch (선의 문자), count (몇 개)
//   반환값: 없음 (void)
void print_line(char ch, int count) {
    for (int i = 0; i < count; i++) {
        printf("%c", ch);
    }
    printf("\n");
}

// ── 덧셈 함수 ────────────────────────────────────────────────────────────────
//   매개변수: a (첫 번째 수), b (두 번째 수)
//   반환값: 두 수의 합 (int)
int add(int a, int b) {
    global_count++;  // 호출할 때마다 전역 카운터 증가
    return a + b;   // a + b 값을 호출한 곳으로 돌려보냄
}

// ── 곱셈 함수 ────────────────────────────────────────────────────────────────
int multiply(int a, int b) {
    return a * b;
}

// ── 원의 넓이 계산 ────────────────────────────────────────────────────────────
double circle_area(double radius) {
    const double pi = 3.14159265358979;
    return pi * radius * radius;
}

// ── 두 수 중 큰 값 반환 ───────────────────────────────────────────────────────
int max_of_two(int a, int b) {
    // 삼항 연산자 사용 (간결하게!)
    return (a > b) ? a : b;

    // 아래와 동일:
    // if (a > b) return a;
    // else       return b;
}

// ── 값에 의한 전달 시연 ───────────────────────────────────────────────────────
//   안에서 a, b 를 바꿔봤자 원본 변수는 변하지 않음!
//   비유: 복사본에 낙서해도 원본은 그대로인 것처럼
void swap_attempt(int a, int b) {
    printf("swap 함수 안 (변경 전): a=%d, b=%d\n", a, b);
    int temp = a;
    a = b;
    b = temp;
    printf("swap 함수 안 (변경 후): a=%d, b=%d\n", a, b);
    // 이 a, b 는 main의 x, y 의 복사본!
    // 함수가 끝나면 사라짐
}

// ── 팩토리얼 (재귀) ───────────────────────────────────────────────────────────
//
//   재귀 함수의 두 가지 필수 요소:
//   1. 기저 조건 (Base Case): 재귀 멈추는 조건
//      → n == 0 이면 1 반환 (더 이상 재귀 안 함)
//   2. 재귀 단계 (Recursive Case): 자기 자신을 호출
//      → n * factorial(n-1)
//
//   factorial(4) 호출 과정:
//   factorial(4)
//     └→ 4 * factorial(3)
//              └→ 3 * factorial(2)
//                       └→ 2 * factorial(1)
//                                └→ 1 * factorial(0)
//                                         └→ 1  ← 기저 조건!
//                                = 1 * 1 = 1
//                         = 2 * 1 = 2
//                  = 3 * 2 = 6
//         = 4 * 6 = 24
//
int factorial(int n) {
    // 기저 조건: n이 0이면 1을 반환 (0! = 1)
    if (n == 0) {
        return 1;
    }
    // 재귀 단계: n * (n-1)!
    return n * factorial(n - 1);
}

// ── 피보나치 수열 (재귀) ──────────────────────────────────────────────────────
//
//   피보나치 수열: 0, 1, 1, 2, 3, 5, 8, 13, 21, ...
//   다음 수 = 앞의 두 수의 합
//
//   fibonacci(n) 정의:
//   - n == 0 → 0
//   - n == 1 → 1
//   - 그 외  → fibonacci(n-1) + fibonacci(n-2)
//
//   ⚠️ 이 재귀 방식은 같은 계산을 여러 번 반복해서 매우 비효율적!
//      큰 수(40 이상)에서는 매우 느림
//      → 동적 프로그래밍(DP)으로 해결 가능 (고급 주제)
//
int fibonacci(int n) {
    if (n == 0) return 0;  // 기저 조건 1
    if (n == 1) return 1;  // 기저 조건 2
    return fibonacci(n - 1) + fibonacci(n - 2);  // 재귀
}
