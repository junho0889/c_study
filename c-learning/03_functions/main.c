#include <stdio.h>

// ─────────────────────────────────────────────────────────────────────────────
// ■ 함수 프로토타입 (Function Prototype)
// ─────────────────────────────────────────────────────────────────────────────
//
//   프로토타입 = "이런 함수가 나중에 나올 거예요!" 라는 예고
//
//   비유: 책의 목차와 같아요. 목차에는 "10페이지에 이런 내용이 있다" 고
//         미리 알려주죠. 프로토타입도 "이런 함수가 있다" 고 미리 알립니다.
//
//   왜 필요할까요?
//   C는 위에서 아래로 코드를 읽습니다.
