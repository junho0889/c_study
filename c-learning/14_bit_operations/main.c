/* ── 2진수 출력 유틸리티 ── */
void print_binary(const char* label, unsigned int val, int bits) {
    printf("    %-12s %3u = ", label, val);
    for (int i = bits - 1; i >= 0; i--) {
        printf("%d", (val >> i) & 1);
        if (i % 4 == 0 && i > 0) printf(" ");
    }
    printf("\n");
}

