/* 비트 수 세기 (population count) */
int count_bits(unsigned int n) {
    int count = 0;
    while (n) {
        count += n & 1;
        n >>= 1;
    }
    return count;
}

/* 2의 거듭제곱 확인 */
int is_power_of_two(unsigned int n) {
    return n > 0 && (n & (n - 1)) == 0;
}

/* 홀수/짝수 확인 */
int is_odd(int n) {
    return n & 1;
}

void lesson6_practical(void) {
    printf("┌──────────────────────────────────────┐\n");
    printf("│  레슨 6 : 실전 — 비트 연산 트릭      │\n");
    printf("└──────────────────────────────────────┘\n\n");

    /* ── XOR 로 swap (임시변수 없이) ── */
    printf("  ■ XOR swap (임시 변수 없이 교환)\n");
    int a = 5, b = 3;
    printf("    교환 전: a=%d, b=%d\n", a, b);
    a ^= b;
    b ^= a;
    a ^= b;
    printf("    교환 후: a=%d, b=%d\n", a, b);

    /* ── 홀수/짝수 판별 ── */
    printf("\n  ■ 홀수/짝수 (비트로 판별)\n");
    for (int i = 0; i < 6; i++) {
        printf("    %d: %s\n", i, is_odd(i) ? "홀수" : "짝수");
    }

    /* ── 2의 거듭제곱 확인 ── */
    printf("\n  ■ 2의 거듭제곱 확인\n");
    int nums[] = {1, 2, 3, 4, 8, 10, 16, 32, 100, 128};
    for (int i = 0; i < 10; i++) {
        printf("    %3d: %s\n", nums[i],
               is_power_of_two(nums[i]) ? "2의 거듭제곱" : "아님");
    }
    /*
    ★ n & (n-1) == 0 의 원리:
      2의 거듭제곱: 100...0 (1이 하나만)
      n - 1:        011...1
      n & (n-1):    000...0  → 0!

      예: 8  = 1000
          7  = 0111
          8&7 = 0000  → 2의 거듭제곱!
    */

    /* ── 비트 수 세기 ── */
    printf("\n  ■ 비트 수 세기 (1의 개수)\n");
    unsigned int test_vals[] = {0, 1, 7, 15, 255};
    for (int i = 0; i < 5; i++) {
        printf("    %3u: 1이 %d개\n", test_vals[i], count_bits(test_vals[i]));
    }

    /*
    ★ 비트 연산 체크리스트
    ─────────────────────────────────────
    □ unsigned 타입을 사용했는가? (부호비트 문제 방지)
    □ 시프트 양이 타입 크기를 넘지 않는가?
    □ 비트 플래그에 1 << n 패턴을 사용했는가?
    □ ~(부정) 연산의 타입 크기에 주의했는가?
    □ 가독성을 위해 매크로로 이름을 붙였는가?
    ─────────────────────────────────────
    */

    printf("\n");
}
