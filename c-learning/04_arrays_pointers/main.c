#include <stdio.h>
#include <string.h>

// 함수 프로토타입
void print_array(int arr[], int size);
void fill_array(int arr[], int size, int value);
int sum_array(int arr[], int size);
void print_matrix(int rows, int cols, int mat[rows][cols]);

int main(void) {

    printf("==============================================\n");
    printf("   04단계: 배열과 포인터\n");
    printf("==============================================\n\n");

    // ─────────────────────────────────────────────────────────────────────
    // 1. 배열 (Array) - 같은 타입의 값을 여러 개 저장
    // ─────────────────────────────────────────────────────────────────────
    //
    //   배열 = 같은 종류의 값을 여러 개 담을 수 있는 기차
    //
    //   비유: 달걀 한 판(30구)을 생각해보세요!
    //         - 판 = 배열 (담는 그릇)
    //         - 각 칸 = 배열의 원소
    //         - 칸 번호 = 인덱스 (0번부터 시작!)
    //
    //   달걀판의 첫 번째 칸 = eggs[0]  (0번 인덱스!)
    //   달걀판의 두 번째 칸 = eggs[1]
    //   ...
    //
    //   선언: 타입 배열이름[크기];
    //         int numbers[5];  // 정수 5개 담는 배열
    //
    //   ⚠️ 인덱스는 0부터 시작! 크기가 5이면 0,1,2,3,4 까지
    //      numbers[5] 는 없음! 접근하면 오류! (배열 범위 초과)
    //

    printf("─────────────────────────────────────\n");
    printf("  1차원 배열\n");
    printf("─────────────────────────────────────\n");

    // 배열 선언과 초기화
    int scores[5] = {90, 85, 78, 92, 88};  // 선언하면서 바로 초기화
    int ages[3];  // 선언만 (쓰레기값이 들어있음!)
    ages[0] = 10;
    ages[1] = 12;
    ages[2] = 14;

    // 배열 크기 자동 결정
    int primes[] = {2, 3, 5, 7, 11, 13};  // 컴파일러가 크기(6)를 알아서 계산
    int prime_count = sizeof(primes) / sizeof(primes[0]);  // 배열 크기 계산법
    // sizeof(배열전체) / sizeof(원소하나) = 원소 개수

    printf("점수 배열: ");
    for (int i = 0; i < 5; i++) {
        printf("scores[%d]=%d ", i, scores[i]);
    }
    printf("\n");

    printf("소수 배열 (총 %d개): ", prime_count);
    for (int i = 0; i < prime_count; i++) {
        printf("%d ", primes[i]);
    }
    printf("\n");

    // 배열 함수 사용
    printf("\n합계: %d\n", sum_array(scores, 5));
    fill_array(ages, 3, 0);  // 모두 0으로 채우기
    printf("fill 후 ages: ");
    print_array(ages, 3);

    // ─────────────────────────────────────────────────────────────────────
    // 2. 2차원 배열 - 표(Table) 형태
    // ─────────────────────────────────────────────────────────────────────
    //
    //   2차원 배열 = 행(row)과 열(column)이 있는 표
    //
    //   비유: 교실 자리 배치도!
    //         앞줄/뒷줄(행), 왼쪽/오른쪽(열)
    //
    //   matrix[행번호][열번호]
    //   matrix[0][0] = 왼쪽 위 첫 번째 칸
    //
    //   메모리 배치 (행 우선):
    //   [0][0] [0][1] [0][2] [1][0] [1][1] [1][2]
    //   ←────── 1행 ──────→ ←────── 2행 ──────→
    //

    printf("\n─────────────────────────────────────\n");
    printf("  2차원 배열 (행렬)\n");
    printf("─────────────────────────────────────\n");

    // 3행 4열 성적표
    int grade_table[3][4] = {
        {90, 85, 78, 92},   // 1번 학생 (국어, 영어, 수학, 과학)
        {75, 88, 95, 80},   // 2번 학생
        {88, 76, 82, 91}    // 3번 학생
    };

    printf("학생 성적표 (행=학생, 열=과목):\n");
    printf("%-10s%-6s%-6s%-6s%-6s\n", "학생", "국어", "영어", "수학", "과학");
    printf("─────────────────────────────────\n");
    for (int i = 0; i < 3; i++) {
        printf("학생 %d:    ", i + 1);
        for (int j = 0; j < 4; j++) {
            printf("%-6d", grade_table[i][j]);
        }
        printf("\n");
    }

    // ─────────────────────────────────────────────────────────────────────
    // 3. 포인터 (Pointer) - C 언어의 핵심!
    // ─────────────────────────────────────────────────────────────────────
    //
    //   포인터 = 메모리 주소를 저장하는 변수
    //
    //   비유: 집 주소와 같아요!
    //         - 집(집 자체) = 변수에 저장된 값
    //         - 집 주소(도로명 주소) = 포인터 (메모리 주소)
    //
    //   택배를 보낼 때 "직접 집을 들고 가는 것" 이 아니라
    //   "주소를 메모지에 적어서" 전달하죠?
    //   포인터도 값을 직접 갖는 게 아니라 "주소"를 담는 것입니다.
    //
    //   두 가지 연산자:
    //   & (앤퍼샌드, address-of): "이 변수의 주소를 알려줘"
    //   * (별표, dereference):    "이 주소에 있는 값을 알려줘" 또는
    //                             "포인터 변수 선언할 때 사용"
    //
    //   메모리 그림:
    //   ┌──────────────────────────────────────────────────────┐
    //   │ 주소: 1000   │ 1001   │ 1002   │ 1003               │
    //   │ 값:  42      │ ...    │ ...    │ ...                 │
    //   └──────────────────────────────────────────────────────┘
    //        ↑
    //   int x = 42; 가 주소 1000에 있다면
    //   &x = 1000 (x의 주소)
    //   *p = 42   (p가 1000을 가리킨다면, 그 주소의 값)
    //

    printf("\n─────────────────────────────────────\n");
    printf("  포인터 기초\n");
    printf("─────────────────────────────────────\n");

    int num = 42;       // 정수 변수
    int *ptr = &num;    // ptr = num의 주소를 저장하는 포인터

    // 포인터 변수 선언:
    // int *ptr;  → "ptr 은 int 를 가리키는 포인터"
    //               (int 주소를 담는 변수)

    printf("num의 값: %d\n", num);
    printf("num의 주소: %p\n", (void*)&num);     // %p = 주소 출력
    printf("ptr이 저장한 주소: %p\n", (void*)ptr);
    printf("ptr이 가리키는 값(*ptr): %d\n", *ptr);  // 역참조

    // 포인터로 값 변경하기
    *ptr = 99;  // ptr이 가리키는 곳(num)의 값을 99로 변경
    printf("\n*ptr = 99 로 바꾼 후:\n");
    printf("num = %d (포인터로 바꿨는데 원본이 변했어요!)\n", num);

    // 포인터를 이용한 실제 swap 함수
    printf("\n[포인터로 진짜 swap]\n");
    int a = 10, b = 20;
    printf("swap 전: a=%d, b=%d\n", a, b);

    // 직접 swap (포인터 사용)
    {
        int *pa = &a, *pb = &b;
        int temp = *pa;
        *pa = *pb;
        *pb = temp;
    }
    printf("swap 후: a=%d, b=%d\n", a, b);  // 실제로 바뀜!

    // ─────────────────────────────────────────────────────────────────────
    // 4. 포인터 연산 (Pointer Arithmetic)
    // ─────────────────────────────────────────────────────────────────────
    //
    //   포인터 + 1 = 다음 원소의 주소로 이동
    //
    //   비유: 아파트 호수!
    //         101호 → 102호 → 103호
    //         포인터도 마찬가지로 "다음 칸"으로 이동합니다.
    //
    //   int *p; 일 때:
    //   p + 1 = p의 주소 + sizeof(int) = p의 주소 + 4 바이트
    //
    //   그래서 int 배열에서 ptr++ 하면 4바이트(int 크기)씩 이동!
    //

    printf("\n─────────────────────────────────────\n");
    printf("  포인터 연산\n");
    printf("─────────────────────────────────────\n");

    int arr[5] = {10, 20, 30, 40, 50};
    int *p = arr;  // 배열의 첫 번째 원소를 가리킴 (arr = &arr[0])

    printf("배열 원소 포인터로 접근:\n");
    for (int i = 0; i < 5; i++) {
        printf("  arr[%d] = %d, 주소: %p\n", i, *(p + i), (void*)(p + i));
        // *(p + i) 는 arr[i] 와 완전히 동일!
    }

    // 포인터 증가로 배열 탐색
    printf("\n포인터 ++ 로 탐색:\n");
    p = arr;  // 다시 처음으로
    for (int i = 0; i < 5; i++) {
        printf("%d ", *p);  // 현재 포인터가 가리키는 값
        p++;                // 다음 원소로 이동
    }
    printf("\n");

    // ─────────────────────────────────────────────────────────────────────
    // 5. 배열과 포인터의 관계
    // ─────────────────────────────────────────────────────────────────────
    //
    //   배열 이름 = 첫 번째 원소의 주소!
    //
    //   int arr[5];
    //   arr == &arr[0]  (완전히 같음!)
    //
    //   그러므로:
    //   arr[i]   == *(arr + i)  (완전히 동일한 표현!)
    //   &arr[i]  == arr + i
    //
    //   비유: "서울시 종로구 1번지" 라는 주소에서
    //         "서울시 종로구" = 배열 이름 (시작 주소)
    //         "1번지" = 인덱스 (몇 번째 원소?)
    //

    printf("\n─────────────────────────────────────\n");
    printf("  배열 = 포인터 증명\n");
    printf("─────────────────────────────────────\n");

    int nums[4] = {1, 2, 3, 4};
    printf("nums    주소: %p\n", (void*)nums);
    printf("&nums[0] 주소: %p (같아요!)\n", (void*)&nums[0]);
    printf("\nnums[2] = %d\n", nums[2]);
    printf("*(nums+2) = %d (완전히 동일!)\n", *(nums + 2));

    // ─────────────────────────────────────────────────────────────────────
    // 6. 문자 배열과 C 스타일 문자열
    // ─────────────────────────────────────────────────────────────────────
    //
    //   C에서 문자열 = char 배열 + 맨 끝에 '\0' (널 문자)
    //
    //   '\0' = null terminator (문자열의 끝 표시)
    //   비유: 문장 끝의 마침표(.)처럼, '\0' 이 "문자열 끝이에요!" 라고 알려줌
    //
    //   "Hello" 를 메모리에 저장하면:
    //   ┌─────┬─────┬─────┬─────┬─────┬─────┐
    //   │ 'H' │ 'e' │ 'l' │ 'l' │ 'o' │'\0' │
    //   └─────┴─────┴─────┴─────┴─────┴─────┘
    //      [0]   [1]   [2]   [3]   [4]   [5]
    //
    //   따라서 "Hello"(5글자)를 저장하려면 크기 6 배열이 필요!
    //   (문자 5개 + '\0' 1개)
    //

    printf("\n─────────────────────────────────────\n");
    printf("  C 스타일 문자열 (char 배열)\n");
    printf("─────────────────────────────────────\n");

    char name[20] = "홍길동";         // 문자열 초기화
    char greeting[] = "안녕하세요!"; // 크기 자동

    printf("이름: %s\n", name);
    printf("인사: %s\n", greeting);
    printf("이름 길이: %zu\n", strlen(name));  // '\0' 제외한 길이

    // 문자 하나씩 접근
    printf("이름 첫 글자: %c\n", name[0]);

    // 문자열 포인터
    char *str_ptr = name;
    printf("포인터로 이름: %s\n", str_ptr);

    // 문자열 리터럴 (상수 문자열)
    // 비유: 돌에 새긴 글자처럼 변경 불가!
    const char *fixed_str = "변경불가 문자열";
    printf("고정 문자열: %s\n", fixed_str);
    // fixed_str[0] = 'X';  // ← 이건 미정의 동작(위험)!

    // ─────────────────────────────────────────────────────────────────────
    // 7. NULL 포인터
    // ─────────────────────────────────────────────────────────────────────
    //
    //   NULL = 아무것도 가리키지 않는 포인터
    //   값: 0 또는 (void*)0
    //
    //   비유: "주소를 아직 모른다" 거나 "아무 집도 없다" 는 표시
    //         택배 주소란에 아무것도 안 쓴 것과 같아요.
    //
    //   포인터를 선언하면 항상 NULL로 초기화하는 것이 좋습니다!
    //   NULL 포인터를 역참조하면 프로그램이 충돌합니다. (세그멘테이션 오류)
    //

    printf("\n─────────────────────────────────────\n");
    printf("  NULL 포인터\n");
    printf("─────────────────────────────────────\n");

    int *null_ptr = NULL;  // 초기화: 아무것도 가리키지 않음
    printf("null_ptr = %p\n", (void*)null_ptr);  // 0x0 출력

    // NULL 확인 후 사용 (안전한 코드!)
    if (null_ptr != NULL) {
        printf("포인터가 유효함: %d\n", *null_ptr);
    } else {
        printf("포인터가 NULL입니다. 역참조하면 충돌!\n");
    }

    // ─────────────────────────────────────────────────────────────────────
    // 8. 흔한 실수
    // ─────────────────────────────────────────────────────────────────────
    //
    //   ❌ 실수 1: 배열 범위 초과 (Buffer Overflow)
    //      int arr[5];
    //      arr[5] = 10;   // arr[4] 까지만 있는데 arr[5] 접근!
    //                     // 컴파일은 되지만 실행 중 문제 발생
    //
    //   ❌ 실수 2: 초기화 안 된 포인터 사용
    //      int *p;     // 쓰레기 주소가 들어있음
    //      *p = 5;     // 위험! 랜덤 주소에 쓰기
    //      → 항상 초기화: int *p = NULL; 또는 int *p = &변수;
    //
    //   ❌ 실수 3: NULL 포인터 역참조
    //      int *p = NULL;
    //      *p = 5;    // 충돌! (Segmentation Fault)
    //
    //   ❌ 실수 4: 문자열 배열 크기 부족
    //      char name[5] = "Hello";  // '\0' 까지 6칸 필요한데 5칸만!
    //      → char name[6] = "Hello"; 이어야 함
    //

    // ─────────────────────────────────────────────────────────────────────
    // 9. 연습 문제
    // ─────────────────────────────────────────────────────────────────────
    //
    //   🎯 직접 해보기:
    //
    //   1. 10개의 정수를 배열에 입력받아 최솟값, 최댓값, 평균을 구하기
    //
    //   2. 배열을 뒤집는 함수 reverse(arr, size) 만들기
    //      예: {1, 2, 3, 4, 5} → {5, 4, 3, 2, 1}
    //
    //   3. 포인터를 이용해서 배열의 모든 원소를 2배로 만들기
    //
    //   4. 2차원 배열에서 각 행의 합계를 구하기
    //

    printf("\n==============================================\n");
    printf("  04단계 학습 완료!\n");
    printf("  다음 단계: 05_structs (구조체)\n");
    printf("==============================================\n");

    return 0;
}

// ── 배열 출력 ─────────────────────────────────────────────────────────────────
void print_array(int arr[], int size) {
    // 함수 안에서 arr은 포인터처럼 동작
    // sizeof(arr) 은 배열 전체 크기가 아니라 포인터 크기를 반환!
    // 그래서 size를 따로 매개변수로 받아야 합니다.
    printf("[");
    for (int i = 0; i < size; i++) {
        printf("%d", arr[i]);
        if (i < size - 1) printf(", ");
    }
    printf("]\n");
}

// ── 배열 채우기 ───────────────────────────────────────────────────────────────
void fill_array(int arr[], int size, int value) {
    for (int i = 0; i < size; i++) {
        arr[i] = value;
    }
    // 배열은 포인터로 전달되므로 원본이 변경됩니다!
    // (값에 의한 전달의 예외 - 배열은 주소가 전달됨)
}

// ── 배열 합계 ─────────────────────────────────────────────────────────────────
int sum_array(int arr[], int size) {
    int total = 0;
    for (int i = 0; i < size; i++) {
        total += arr[i];
    }
    return total;
}

// ── 2차원 배열 출력 ───────────────────────────────────────────────────────────
void print_matrix(int rows, int cols, int mat[rows][cols]) {
    for (int i = 0; i < rows; i++) {
        for (int j = 0; j < cols; j++) {
            printf("%4d", mat[i][j]);
        }
        printf("\n");
    }
}
