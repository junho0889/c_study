--
-- 인덱스란?
-- 도서관에서 책을 찾을 때, 책장을 처음부터 끝까지 다 훑는 대신
-- "가나다순 목록카드"를 먼저 보면 빨리 찾을 수 있죠?
-- 인덱스는 데이터베이스의 "목록카드"입니다.
--
-- 없으면: 10만 권을 하나하나 확인 (Full Table Scan)
-- 있으면: 목록카드에서 "ㅎ"으로 가서 바로 찾기 (Index Seek)
-- ============================================================================

-- ┌─────────────────────────────────────────────┐
-- │  준비: 서점 도서 카탈로그 만들기              │
-- └─────────────────────────────────────────────┘

DROP TABLE IF EXISTS order_items;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS books;

CREATE TABLE books (
    id         INTEGER PRIMARY KEY,
    title      TEXT    NOT NULL,       -- 책 제목
    author     TEXT    NOT NULL,       -- 저자
    genre      TEXT    NOT NULL,       -- 장르 ('소설', '과학', '역사', '만화')
    price      INTEGER NOT NULL,       -- 가격 (원)
    stock      INTEGER NOT NULL,       -- 재고 수량
    published  TEXT    NOT NULL        -- 출판일 (YYYY-MM-DD)
);

