-- ┌─────────────────────────────────────────────┐
-- │  레슨 1: 인덱스 없이 검색 — 처음부터 끝까지  │
-- └─────────────────────────────────────────────┘
-- 아직 인덱스가 없으니, DB는 책 10권을 처음부터 끝까지 다 봅니다.
-- 10권이야 금방이지만, 100만 권이면 매우 느려질 거예요.
-- ═══════════════════════════════════════════════

-- EXPLAIN은 "DB가 이 질문을 어떻게 풀 건지 계획을 보여 달라"는 뜻입니다.
-- 비유: 선생님이 "이 문제를 어떻게 풀 건지 풀이 과정을 먼저 써 봐" 하는 것.
EXPLAIN QUERY PLAN
SELECT * FROM books WHERE author = '김작가';
-- 결과에 "SCAN books"라고 나오면 → 전체를 다 훑고 있다는 뜻


-- ┌─────────────────────────────────────────────┐
-- │  레슨 2: 단일 컬럼 인덱스 만들기              │
-- └─────────────────────────────────────────────┘
-- CREATE INDEX는 "이 칸에 대한 목록카드를 만들어 줘"라는 뜻입니다.
-- 서점의 '저자별 색인' 페이지를 만드는 것과 같아요.
-- ═══════════════════════════════════════════════

CREATE INDEX idx_books_author ON books(author);
-- 이제 author 칸에 대한 정리된 목록이 생겼습니다.

-- 같은 쿼리를 다시 실행 계획으로 확인해 봅시다.
EXPLAIN QUERY PLAN
SELECT * FROM books WHERE author = '김작가';
-- 이제 "SEARCH books USING INDEX idx_books_author"라고 바뀝니다!
-- 목록카드를 먼저 찾아서 해당 책만 골라보는 것이죠.

-- 실제 결과 확인
SELECT id, title, author, genre FROM books WHERE author = '김작가';


-- ┌─────────────────────────────────────────────┐
-- │  레슨 3: 복합 인덱스 (Composite Index)        │
-- └─────────────────────────────────────────────┘
-- "장르가 '과학'이면서 가격이 15000원 이하"처럼 조건이 2개일 때,
-- 두 칸을 묶은 인덱스를 만들면 더 빠릅니다.
--
-- 비유: 서점에서 '장르별 → 가격순' 목록을 만드는 것.
--   과학 코너에서 가격이 싼 책부터 찾는 식이에요.
-- ═══════════════════════════════════════════════

CREATE INDEX idx_books_genre_price ON books(genre, price);

EXPLAIN QUERY PLAN
SELECT title, genre, price
FROM books
WHERE genre = '과학' AND price <= 15000;
-- 복합 인덱스를 사용해서 장르와 가격 조건을 한 번에 처리합니다.

-- 결과 확인
SELECT title, genre, price
FROM books
WHERE genre = '과학' AND price <= 15000
ORDER BY price;


-- ┌─────────────────────────────────────────────┐
-- │  레슨 4: 인덱스 순서가 중요합니다!            │
-- └─────────────────────────────────────────────┘
-- 복합 인덱스 (genre, price)에서:
--   ✅ WHERE genre = '과학'                → 인덱스 사용 O (왼쪽부터 일치)
--   ✅ WHERE genre = '과학' AND price > 10000 → 인덱스 사용 O
--   ❌ WHERE price > 10000                 → 인덱스 사용 X (왼쪽이 빠져 있음!)
--
-- 비유: 전화번호부가 "성 → 이름" 순서로 되어 있으면
--   "김씨 중에 민수"는 빨리 찾지만
--   "이름이 민수인 사람"은 전부 다 뒤져야 해요.
-- ═══════════════════════════════════════════════

-- 이 쿼리는 genre 없이 price만 조건으로 씁니다.
EXPLAIN QUERY PLAN
SELECT title, price FROM books WHERE price > 10000;
-- genre_price 인덱스를 못 쓰고 SCAN이 나올 수 있습니다.

-- price만으로 자주 검색한다면 별도 인덱스가 필요합니다.
CREATE INDEX idx_books_price ON books(price);

EXPLAIN QUERY PLAN
SELECT title, price FROM books WHERE price > 10000;
-- 이제 idx_books_price를 사용합니다.


-- ┌─────────────────────────────────────────────┐
-- │  레슨 5: 인덱스를 쓰면 안 좋은 경우들         │
-- └─────────────────────────────────────────────┘
-- 인덱스도 "공짜"가 아닙니다. 단점도 있어요:
--
-- 1) INSERT/UPDATE/DELETE가 느려짐
--    → 책을 새로 입고할 때마다 목록카드도 같이 고쳐야 하니까요.
--    → 인덱스가 10개면 10개 목록카드를 전부 수정해야 합니다.
--
-- 2) 저장 공간을 더 씀
--    → 목록카드 자체도 종이(디스크)를 차지합니다.
--
-- 3) 데이터가 적으면 효과 없음
--    → 책이 10권밖에 없는데 목록카드를 만드는 건 오히려 번거로워요.
--    → 그냥 눈으로 10권 보는 게 더 빠릅니다.
--
-- 4) 값의 종류가 너무 적을 때 (낮은 카디널리티)
--    → 예: 성별(남/여)에 인덱스를 만들면, 전체의 50%를 읽어야 해서
--      차라리 다 읽는 게 나을 수 있습니다.
-- ═══════════════════════════════════════════════

-- 나쁜 예: stock(재고)에 함수를 씌우면 인덱스를 못 씁니다.
-- WHERE stock + 10 > 30  ← 이렇게 하면 인덱스 무효!
-- WHERE stock > 20       ← 이렇게 해야 인덱스 사용 가능

-- 좋은 습관: 칸 이름을 왼쪽에 "그대로" 두세요.
SELECT title, stock FROM books WHERE stock > 20;


-- ┌─────────────────────────────────────────────┐
-- │  레슨 6: UNIQUE 인덱스                       │
-- └─────────────────────────────────────────────┘
-- UNIQUE 인덱스는 "같은 값이 두 번 들어오면 막아 주는" 인덱스입니다.
-- 비유: 학교에서 학번은 절대 겹치면 안 되죠? 그런 규칙을 강제합니다.
-- ═══════════════════════════════════════════════

DROP TABLE IF EXISTS members;
CREATE TABLE members (
    id    INTEGER PRIMARY KEY,
    email TEXT NOT NULL
);

CREATE UNIQUE INDEX idx_members_email ON members(email);

INSERT INTO members (id, email) VALUES (1, 'minsu@school.com');
INSERT INTO members (id, email) VALUES (2, 'jiwoo@school.com');

