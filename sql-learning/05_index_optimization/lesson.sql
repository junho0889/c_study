-- ═══════════════════════════════════════════════
-- ✅ 인덱스 만들어야 할 때:
--    - WHERE, JOIN, ORDER BY에 자주 쓰는 칸
--    - 값의 종류가 다양한 칸 (이름, 이메일 등)
--    - 데이터가 수천 건 이상일 때
--
-- ❌ 인덱스 안 만드는 게 나을 때:
--    - 데이터가 아주 적을 때 (100건 이하)
--    - INSERT/UPDATE가 매우 자주 일어나는 테이블
--    - 값의 종류가 2~3개뿐일 때 (성별, 참/거짓 등)
--    - 거의 조회하지 않는 칸
--
-- 비유 정리:
--   인덱스 = 서점 목록카드
--   단일 인덱스 = "저자별" 목록
--   복합 인덱스 = "장르별 → 가격순" 목록
--   UNIQUE 인덱스 = "같은 학번 금지" 규칙이 붙은 목록
--   EXPLAIN = "어떻게 찾을 건지 풀이 과정 보여 줘"
-- ═══════════════════════════════════════════════
