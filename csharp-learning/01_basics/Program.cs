// ┌─────────────────────────────────────────────────────────┐
// │  using 지시문 - "도구 상자 열기"                         │
// │                                                         │
// │  마치 학교에 갈 때 가방에 연필, 지우개, 책을 넣는 것처럼 │
// │  C#도 필요한 도구들을 미리 가져와야 해요.               │
// │  "System"은 기본 도구 상자 이름이에요.                  │
// └─────────────────────────────────────────────────────────┘
using System;

// ┌─────────────────────────────────────────────────────────┐
// │  namespace - "우리 집 주소"                              │
// │                                                         │
// │  나라 > 도시 > 동네 > 집 처럼                           │
// │  코드도 폴더처럼 묶어서 정리할 수 있어요.               │
// │  같은 이름의 코드가 있어도 주소가 다르면 구분 가능!     │
// └─────────────────────────────────────────────────────────┘
namespace CSharpBasics
{
    // ┌─────────────────────────────────────────────────────┐
    // │  class - "설계도" 또는 "레고 블록 설명서"            │
    // │                                                     │
    // │  집을 짓기 전에 설계도를 그리듯이,                  │
    // │  C#에서는 class 안에 코드를 작성해요.               │
    // └─────────────────────────────────────────────────────┘
    class Program
    {
        // ┌───────────────────────────────────────────────────┐
        // │  Main 메서드 - "프로그램의 현관문"                 │
        // │                                                   │
        // │  집에 들어갈 때 항상 현관문으로 들어가듯이,       │
        // │  C# 프로그램은 항상 Main 에서 시작해요!           │
        // │  args = 프로그램 실행할 때 주는 추가 정보         │
        // └───────────────────────────────────────────────────┘
        static void Main(string[] args)
        {
            // ════════════════════════════════════════════════
            //  1. 화면에 출력하기 - Console.WriteLine vs Write
            // ════════════════════════════════════════════════

            // Console.WriteLine = "줄 바꿈과 함께 출력"
            // 마치 편지 쓸 때 문장 끝에 엔터 누르는 것과 같아요
            Console.WriteLine("안녕하세요! C# 세계에 오신 걸 환영합니다!");
            Console.WriteLine("이것은 첫 번째 줄이에요.");
            Console.WriteLine("이것은 두 번째 줄이에요.");

            // Console.Write = "줄 바꿈 없이 출력"
            // 마치 편지 쓸 때 엔터 없이 계속 이어 쓰는 것과 같아요
            Console.Write("이 글자 뒤에 ");
            Console.Write("바로 이어서 출력돼요! ");
            Console.WriteLine(); // 빈 줄 출력 (엔터만 치는 효과)

            // \n = 줄 바꿈 문자 (Escape 문자)
            // \ 뒤에 특별한 문자를 쓰면 특별한 기능을 해요
            Console.WriteLine("첫째 줄\n둘째 줄\n셋째 줄");

            // \t = 탭 (여러 칸 띄우기)
            Console.WriteLine("이름\t나이\t점수");
            Console.WriteLine("김철수\t10살\t100점");

            Console.WriteLine("\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");

            // ════════════════════════════════════════════════
            //  2. 변수 - "이름 붙은 상자"
            // ════════════════════════════════════════════════

            /*
             * 변수란 무엇인가요?
             * ─────────────────
             * 변수는 컴퓨터 메모리에 있는 "이름 붙은 상자"예요.
             *
             * 예를 들어:
             *   [나이 상자] = 10
             *   [이름 상자] = "김민준"
             *   [키 상자]   = 145.5
             *
             * 상자마다 담을 수 있는 것이 정해져 있어요!
             * 과자 상자에 신발을 넣을 수 없듯이 말이죠.
             */

            // ┌────────────────────────────────────────────┐
            // │  정수형 (int) - "자연수와 음수 상자"         │
            // │  -2,147,483,648 ~ 2,147,483,647 까지 저장  │
            // │  소수점 없는 숫자들! (1, 2, -5, 100 등)    │
            // └────────────────────────────────────────────┘
            int 나이 = 10;
            int 점수 = 100;
            int 온도 = -5;  // 음수도 저장 가능!

            Console.WriteLine($"나이: {나이}살");
            Console.WriteLine($"점수: {점수}점");
            Console.WriteLine($"오늘 온도: {온도}도");

            // ┌────────────────────────────────────────────┐
            // │  실수형 (double) - "소수점 숫자 상자"        │
            // │  아주 크고 아주 작은 소수도 저장 가능!      │
            // └────────────────────────────────────────────┘
            double 키 = 145.5;
            double 몸무게 = 38.7;
            double 원주율 = 3.14159265;

            Console.WriteLine($"키: {키}cm");
            Console.WriteLine($"몸무게: {몸무게}kg");
            Console.WriteLine($"원주율: {원주율}");

            // float = double보다 정밀도가 낮지만 메모리를 절반만 사용
            // 숫자 뒤에 f를 붙여야 해요!
            float 작은소수 = 3.14f;
            Console.WriteLine($"float 원주율: {작은소수}");

            // ┌────────────────────────────────────────────┐
            // │  문자열 (string) - "글자들의 줄 상자"        │
            // │  "" 큰따옴표 안에 원하는 글자를 쓰세요!     │
            // └────────────────────────────────────────────┘
            string 이름 = "김민준";
            string 학교 = "행복 초등학교";
            string 빈문자열 = "";  // 아무것도 없는 문자열도 가능!

            Console.WriteLine($"이름: {이름}");
            Console.WriteLine($"학교: {학교}");

            // ┌────────────────────────────────────────────┐
            // │  논리형 (bool) - "참/거짓 상자"              │
            // │  오직 true (참) 또는 false (거짓) 만 가능!  │
            // │  마치 전등 스위치: 켜짐/꺼짐 처럼요         │
            // └────────────────────────────────────────────┘
            bool 비가오나요 = false;
            bool 배고픈가요 = true;
            bool 숙제했나요 = true;

            Console.WriteLine($"비가 오나요? {비가오나요}");
            Console.WriteLine($"배고픈가요? {배고픈가요}");

            // ┌────────────────────────────────────────────┐
            // │  문자형 (char) - "딱 한 글자 상자"           │
            // │  '' 작은따옴표 안에 한 글자만 쓸 수 있어요! │
            // └────────────────────────────────────────────┘
            char 첫글자 = '김';
            char 등급 = 'A';
            char 특수문자 = '!';

            Console.WriteLine($"이름 첫 글자: {첫글자}");
            Console.WriteLine($"성적 등급: {등급}");

            Console.WriteLine("\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");

            // ════════════════════════════════════════════════
            //  3. var - "영리한 자동 타입 추론"
            // ════════════════════════════════════════════════

            /*
             * var 란 무엇인가요?
             * ──────────────────
             * C#이 "아, 이 값은 숫자구나! 알아서 int로 할게!"
             * 하고 자동으로 타입을 결정해 줘요.
             *
             * 마치 선생님이 "이건 뭐예요?" 하면
             * 내용물을 보고 "아, 사과구나!" 하는 것처럼요.
             *
             * 주의: var는 처음 값을 꼭 줘야 해요!
             * var x;  ← 이건 안 돼요! (뭔지 알 수 없으니까요)
             */
            var 자동숫자 = 42;           // 자동으로 int
            var 자동소수 = 3.14;         // 자동으로 double
            var 자동문자열 = "안녕";     // 자동으로 string
            var 자동참거짓 = true;       // 자동으로 bool

            Console.WriteLine($"var 숫자: {자동숫자} (타입: {자동숫자.GetType().Name})");
            Console.WriteLine($"var 소수: {자동소수} (타입: {자동소수.GetType().Name})");
            Console.WriteLine($"var 문자열: {자동문자열} (타입: {자동문자열.GetType().Name})");

            Console.WriteLine("\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");

            // ════════════════════════════════════════════════
            //  4. 상수 (const) - "절대 바꿀 수 없는 상자"
            // ════════════════════════════════════════════════

            /*
             * const 란 무엇인가요?
             * ────────────────────
             * 한 번 정하면 절대 바꿀 수 없는 값이에요.
             *
             * 예시:
             * - 원주율 = 3.14159... (바뀌지 않죠!)
             * - 지구의 중력 = 9.8m/s²
             * - 학교 이름 = "행복 초등학교" (바꾸면 이상하죠)
             *
             * const로 선언하면 나중에 실수로 바꾸려 해도
             * 컴퓨터가 "안 돼!" 하고 막아줘요. 안전해요!
             */
            const double PI = 3.14159265358979;
            const int 학년수 = 6;
            const string 나라이름 = "대한민국";

            Console.WriteLine($"원주율 π = {PI}");
            Console.WriteLine($"초등학교 학년 수: {학년수}");
            Console.WriteLine($"나라 이름: {나라이름}");

            // PI = 3.14;  ← 이렇게 하면 오류! const는 바꿀 수 없어요!

            Console.WriteLine("\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");

            // ════════════════════════════════════════════════
            //  5. 산술 연산자 - "수학 계산 도구"
            // ════════════════════════════════════════════════

            /*
             * 수학 시간과 똑같아요!
             * + 더하기, - 빼기, * 곱하기, / 나누기
             * % 나머지 (이건 좀 특별해요!)
             */

            int a = 20;
            int b = 7;

            Console.WriteLine($"a = {a}, b = {b}");
            Console.WriteLine($"더하기: {a} + {b} = {a + b}");
            Console.WriteLine($"빼기:   {a} - {b} = {a - b}");
            Console.WriteLine($"곱하기: {a} * {b} = {a * b}");
            Console.WriteLine($"나누기: {a} / {b} = {a / b}");  // 정수끼리 나누면 소수 버려짐!
            Console.WriteLine($"나머지: {a} % {b} = {a % b}");  // 20 ÷ 7 = 2 나머지 6

            // 나머지(%) 활용 예시
            // 짝수인지 홀수인지 확인!
            int 숫자 = 15;
            Console.WriteLine($"\n{숫자}는 짝수인가요? {숫자 % 2 == 0}");  // false = 홀수

            // 실수 나누기
            double x = 20.0;
            double y = 7.0;
            Console.WriteLine($"\n실수 나누기: {x} / {y} = {x / y:F4}");  // :F4 = 소수점 4자리

            // 증가/감소 연산자
            int 카운터 = 0;
            카운터++;  // 1 증가 (카운터 = 카운터 + 1)
            카운터++;  // 또 1 증가
            Console.WriteLine($"\n카운터: {카운터}");

            카운터--;  // 1 감소
            Console.WriteLine($"카운터 감소: {카운터}");

            // 복합 대입 연산자
            int 점수2 = 50;
            점수2 += 10;  // 점수2 = 점수2 + 10 → 60
            점수2 -= 5;   // 점수2 = 점수2 - 5  → 55
            점수2 *= 2;   // 점수2 = 점수2 * 2  → 110
            Console.WriteLine($"복합 연산 후 점수: {점수2}");

            Console.WriteLine("\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");

            // ════════════════════════════════════════════════
            //  6. 문자열 보간 ($"...") - "이름표 달린 틀"
            // ════════════════════════════════════════════════

            /*
             * $ 기호를 문자열 앞에 붙이면
             * {} 중괄호 안에 변수나 식을 넣을 수 있어요!
             *
             * 마치 편지 양식에 이름 칸, 날짜 칸이 있는 것처럼요.
             * "안녕하세요, [이름]님! 오늘은 [날짜]입니다."
             */
            string 학생이름 = "이수진";
            int 학생나이 = 11;
            double 평균점수 = 95.5;

            // 기본 보간
            Console.WriteLine($"안녕하세요, {학생이름}님!");
            Console.WriteLine($"{학생이름}은 {학생나이}살이에요.");

            // 식도 넣을 수 있어요!
            Console.WriteLine($"5년 후 나이: {학생나이 + 5}살");

            // 형식 지정자로 예쁘게 출력
            Console.WriteLine($"평균 점수: {평균점수:F1}점");     // 소수점 1자리
            Console.WriteLine($"큰 숫자: {1234567:N0}");          // 천 단위 콤마
            Console.WriteLine($"퍼센트: {0.875:P1}");             // 퍼센트로

            // 예전 방식 (지금도 사용 가능하지만 $ 방식이 더 편리해요)
            Console.WriteLine(string.Format("안녕, {0}! 나이는 {1}살", 학생이름, 학생나이));

            Console.WriteLine("\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");

            // ════════════════════════════════════════════════
            //  7. 키보드 입력 받기 - Console.ReadLine()
            // ════════════════════════════════════════════════

            /*
             * Console.ReadLine() = "사용자가 엔터 누를 때까지 기다리기"
             *
             * 마치 선생님이 "이름이 뭐예요?" 하고 물어보면
             * 학생이 대답할 때까지 기다리는 것과 같아요.
             *
             * 주의: ReadLine()은 항상 string(문자열)로 돌려줘요!
             * 숫자로 쓰고 싶으면 변환이 필요해요.
             */

            Console.Write("\n이름을 입력하세요: ");
            string 입력이름 = Console.ReadLine() ?? "이름없음";
            Console.WriteLine($"안녕하세요, {입력이름}님! 반가워요!");

            Console.Write("좋아하는 숫자를 입력하세요: ");
            string 숫자입력 = Console.ReadLine() ?? "0";

            Console.WriteLine("\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");

            // ════════════════════════════════════════════════
            //  8. 타입 변환 - "박스 옮기기"
            // ════════════════════════════════════════════════

            /*
             * 문자열 → 숫자 변환 방법들:
             *
             * Convert.ToInt32("10")   → 10 (int)
             * int.Parse("10")         → 10 (int)
             * int.TryParse(...)       → 안전한 변환 (실패해도 괜찮아요!)
             *
             * 마치 한국 돈을 미국 달러로 바꾸는 환전처럼요!
             * 단, 숫자가 아닌 문자 (예: "abc")는 변환 안 돼요!
             */

            // Convert 클래스 사용
            string 나이문자 = "12";
            int 나이숫자 = Convert.ToInt32(나이문자);
            Console.WriteLine($"문자 '{나이문자}' → 숫자 {나이숫자}");
            Console.WriteLine($"내년에는 {나이숫자 + 1}살이 돼요!");

            // 숫자 → 문자열 변환
            int 점수3 = 95;
            string 점수문자 = 점수3.ToString();
            Console.WriteLine($"숫자 {점수3} → 문자 '{점수문자}'");

            // 안전한 변환 (TryParse)
            // 변환 실패해도 프로그램이 안 죽어요!
            string 이상한입력 = "abc123";
            bool 변환성공 = int.TryParse(이상한입력, out int 변환결과);
            if (변환성공)
                Console.WriteLine($"변환 성공: {변환결과}");
            else
                Console.WriteLine($"'{이상한입력}'은 숫자로 변환할 수 없어요!");

            // 방금 입력 받은 숫자 변환
            if (int.TryParse(숫자입력, out int 좋아하는숫자))
            {
                Console.WriteLine($"좋아하는 숫자 {좋아하는숫자}의 두 배는 {좋아하는숫자 * 2}예요!");
            }

            Console.WriteLine("\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");

            // ════════════════════════════════════════════════
            //  9. Math 클래스 - "수학 선생님 도우미"
            // ════════════════════════════════════════════════

            /*
             * Math 클래스에는 다양한 수학 함수들이 들어있어요!
             * 마치 공학용 계산기처럼요.
             */

            Console.WriteLine("── Math 클래스 활용 ──");

            // 절댓값 (음수를 양수로)
            Console.WriteLine($"|-15| = {Math.Abs(-15)}");

            // 반올림, 올림, 내림
            double 소수 = 3.7;
            Console.WriteLine($"{소수} 반올림: {Math.Round(소수)}");
            Console.WriteLine($"{소수} 올림:   {Math.Ceiling(소수)}");
            Console.WriteLine($"{소수} 내림:   {Math.Floor(소수)}");

            // 최댓값, 최솟값
            Console.WriteLine($"Max(10, 20) = {Math.Max(10, 20)}");
            Console.WriteLine($"Min(10, 20) = {Math.Min(10, 20)}");

            // 거듭제곱
            Console.WriteLine($"2^10 = {Math.Pow(2, 10)}");  // 2의 10승 = 1024

            // 제곱근
            Console.WriteLine($"√144 = {Math.Sqrt(144)}");   // 144의 제곱근 = 12

            // 원의 넓이 계산!
            double 반지름 = 5.0;
            double 넓이 = Math.PI * Math.Pow(반지름, 2);
            Console.WriteLine($"반지름 {반지름}인 원의 넓이: {넓이:F2}");

            Console.WriteLine("\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");

            // ════════════════════════════════════════════════
            //  10. 문자열 다루기 - 유용한 메서드들
            // ════════════════════════════════════════════════

            string 문장 = "  안녕하세요, 저는 C#을 배우고 있어요!  ";

            Console.WriteLine("── 문자열 메서드 ──");
            Console.WriteLine($"원본: '{문장}'");
            Console.WriteLine($"앞뒤 공백 제거: '{문장.Trim()}'");
            Console.WriteLine($"대문자로: '{"hello".ToUpper()}'");
            Console.WriteLine($"소문자로: '{"WORLD".ToLower()}'");
            Console.WriteLine($"길이: {문장.Length}글자");
            Console.WriteLine($"포함 여부: {"C#" 포함됨? }{문장.Contains("C#")}");
            Console.WriteLine($"시작 여부: {문장.Trim().StartsWith("안녕")}");
            Console.WriteLine($"교체: {문장.Replace("안녕하세요", "Hello")}");

            // 문자열 자르기
            string 이름자르기 = "김민준";
            Console.WriteLine($"첫 번째 글자: {이름자르기[0]}");  // 인덱스로 접근
            Console.WriteLine($"substring: {이름자르기.Substring(1)}");  // 1번 인덱스부터

            // 문자열 나누기
            string 과목들 = "수학,과학,영어,국어";
            string[] 과목배열 = 과목들.Split(',');
            Console.WriteLine("\n과목 목록:");
            foreach (string 과목 in 과목배열)
            {
                Console.WriteLine($"  - {과목}");
            }

            // ════════════════════════════════════════════════
            //  마지막: 자주 하는 실수들!
            // ════════════════════════════════════════════════

            Console.WriteLine("\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");
            Console.WriteLine("⚠ 자주 하는 실수들:");
            Console.WriteLine();
            Console.WriteLine("1. 정수 나누기 → 소수 버려짐!");
            Console.WriteLine($"   7 / 2 = {7 / 2}  (소수 버려짐)");
            Console.WriteLine($"   7.0 / 2 = {7.0 / 2}  (제대로 나눠짐)");
            Console.WriteLine();
            Console.WriteLine("2. string과 char 혼동!");
            Console.WriteLine("   char c = 'A';   ← 작은따옴표");
            Console.WriteLine("   string s = \"A\"; ← 큰따옴표");
            Console.WriteLine();
            Console.WriteLine("3. = 와 == 의 차이!");
            Console.WriteLine("   x = 5;    ← 값 대입 (넣기)");
            Console.WriteLine("   x == 5;   ← 같은지 비교 (물어보기)");

            Console.WriteLine("\n프로그램 종료. 아무 키나 누르세요...");
            Console.ReadKey();
        }
