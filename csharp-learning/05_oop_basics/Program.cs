            은행계좌 계좌2 = new 은행계좌("이수진", 50000);
            은행계좌 계좌3 = new 은행계좌("박철수", 200000);

            Console.WriteLine();
            계좌1.입금(30000);
            계좌2.출금(20000);
            계좌3.입금(100000);

            Console.WriteLine();
            은행계좌.은행정보출력();  // static 메서드 - 클래스 이름으로 호출

            // static 프로퍼티도 클래스 이름으로
            Console.WriteLine($"  현재 이자율: {은행계좌.기본이자율:P0}");

            Console.WriteLine("\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");
            Console.WriteLine("══ 4. 온도계 클래스 (캡슐화) ══\n");

