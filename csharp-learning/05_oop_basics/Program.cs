    // ════════════════════════════════════════════════════════
    //  클래스(Class)란 무엇인가요?
    // ════════════════════════════════════════════════════════
    /*
     * 클래스 = "설계도" 또는 "쿠키 틀"
     * ────────────────────────────────
     * 마치 붕어빵 틀처럼요!
     * - 붕어빵 틀 = 클래스 (설계도)
     * - 실제 붕어빵 = 객체 (실제 만들어진 것)
     *
     * 틀 하나로 붕어빵을 여러 개 만들 수 있듯이,
     * 클래스 하나로 객체를 여러 개 만들 수 있어요!
     *
     * 클래스 안에는:
     * - 필드(Field): 데이터를 저장 (예: 이름, 나이)
     * - 프로퍼티(Property): 필드에 안전하게 접근
     * - 메서드(Method): 동작/기능 (예: 걷기, 말하기)
     * - 생성자(Constructor): 객체를 만들 때 초기화
     */

    // ════════════════════════════════════════════════════════
    //  1. 기본 클래스 - 강아지 클래스
    // ════════════════════════════════════════════════════════

    class 강아지
    {
        // ┌─────────────────────────────────────────────────┐
        // │  필드 (Field) - "클래스의 변수들"                │
        // │                                                 │
        // │  private = 이 클래스 안에서만 접근 가능         │
        // │  마치 일기장처럼 나만 볼 수 있어요!             │
        // └─────────────────────────────────────────────────┘
        private string _이름;
        private string _품종;
        private int _나이;
        private double _몸무게;

        // ┌─────────────────────────────────────────────────┐
        // │  생성자 (Constructor) - "태어날 때 하는 일"      │
        // │                                                 │
        // │  클래스 이름과 같은 메서드예요.                 │
        // │  객체를 new 로 만들 때 자동으로 실행돼요!       │
        // │  마치 아기가 태어날 때 이름 짓는 것처럼요.      │
        // └─────────────────────────────────────────────────┘
        public 강아지(string 이름, string 품종, int 나이, double 몸무게)
        {
            _이름 = 이름;
            _품종 = 품종;
            _나이 = 나이;
            _몸무게 = 몸무게;
            Console.WriteLine($"  [{이름}]이(가) 태어났어요!");
        }

        // 매개변수 없는 기본 생성자
        public 강아지()
        {
            _이름 = "이름없음";
            _품종 = "믹스";
            _나이 = 0;
            _몸무게 = 0.5;
        }

        // ┌─────────────────────────────────────────────────┐
        // │  프로퍼티 (Property) - "문지기"                  │
        // │                                                 │
        // │  private 필드에 접근할 수 있는 특별한 문이에요. │
        // │  get: 값 읽기 (문 열고 안 보기)                 │
        // │  set: 값 쓰기 (문 열고 안에 넣기)               │
        // │                                                 │
        // │  마치 은행 창구처럼요!                          │
        // │  직접 금고에 접근 못하고 창구 직원을 통해야 해요 │
        // └─────────────────────────────────────────────────┘
        public string 이름
        {
            get { return _이름; }
            set
            {
                if (string.IsNullOrEmpty(value))
                    throw new ArgumentException("이름은 비어있을 수 없어요!");
                _이름 = value;
            }
        }

        public string 품종 => _품종;  // 읽기 전용 (get만)

        public int 나이
        {
            get { return _나이; }
            set
            {
                if (value < 0) 나이를검사해요("나이는 0 이상이어야 해요!");
                _나이 = value;
            }
        }

        public double 몸무게
        {
            get { return _몸무게; }
            set
            {
                if (value <= 0) throw new ArgumentException("몸무게는 0보다 커야 해요!");
                _몸무게 = value;
            }
        }

        // ┌─────────────────────────────────────────────────┐
        // │  메서드 (Method) - "할 수 있는 것들"              │
        // └─────────────────────────────────────────────────┘
        public void 짖기()
        {
            Console.WriteLine($"  [{_이름}]: 멍멍! 🐕");
        }

        public void 먹기(string 음식)
        {
            Console.WriteLine($"  [{_이름}]이(가) {음식}을(를) 먹어요! 냠냠~");
        }

        // this 키워드 = "나 자신"
        // 마치 자기 자신을 가리키는 손가락 같아요
        public bool 같은강아지인가(강아지 다른강아지)
        {
            return this._이름 == 다른강아지._이름;  // this = 나 자신
        }

        public void 정보출력()
        {
            Console.WriteLine($"  ┌─ {_이름} ────────────────┐");
            Console.WriteLine($"  │ 품종: {_품종,-12}       │");
            Console.WriteLine($"  │ 나이: {_나이}살            │");
            Console.WriteLine($"  │ 몸무게: {_몸무게}kg        │");
            Console.WriteLine($"  └──────────────────────────┘");
        }

        // private 메서드 - 클래스 내부에서만 사용
        private void 나이를검사해요(string 메시지)
        {
            Console.WriteLine($"  [경고] {메시지}");
        }
    }

    // ════════════════════════════════════════════════════════
    //  2. 자동 프로퍼티가 있는 클래스
    // ════════════════════════════════════════════════════════

    /*
     * 자동 프로퍼티란?
     * ─────────────────
     * 컴파일러가 자동으로 필드를 만들어줘요.
     * 짧고 간단하게 쓸 수 있어요!
     *
     * public string 이름 { get; set; }
     * ↓ 이것과 같아요 ↓
     * private string _이름;
     * public string 이름 { get => _이름; set => _이름 = value; }
     */

    class 학생
    {
        // 자동 프로퍼티 (Auto-property)
        public string 이름 { get; set; } = "";
        public int 학번 { get; set; }
        public int 나이 { get; set; }
        public string 반 { get; set; } = "";

        // 읽기 전용 자동 프로퍼티 (생성자에서만 설정 가능)
        public DateTime 입학일 { get; init; }

        // 계산 프로퍼티 (저장 없이 계산만)
        public int 졸업예정학년 => DateTime.Now.Year + (6 - 나이 + 8);
        public string 소개 => $"{이름}({나이}살, {반}반)";

        // ┌─────────────────────────────────────────────────┐
        // │  생성자 오버로딩                                 │
        // │  여러 방법으로 학생을 만들 수 있어요!            │
        // └─────────────────────────────────────────────────┘
        public 학생()  // 기본 생성자
        {
            입학일 = DateTime.Now;
        }

        public 학생(string 이름, int 학번, int 나이, string 반) : this()  // this() = 기본 생성자 먼저 호출
        {
            this.이름 = 이름;
            this.학번 = 학번;
            this.나이 = 나이;
            this.반 = 반;
        }

        public void 자기소개()
        {
            Console.WriteLine($"  안녕하세요! 저는 {이름}이에요.");
            Console.WriteLine($"  {나이}살이고, {반}반입니다.");
            Console.WriteLine($"  학번은 {학번}번이에요.");
        }
    }

    // ════════════════════════════════════════════════════════
    //  3. static 멤버 - "공유하는 것들"
    // ════════════════════════════════════════════════════════

    /*
     * static이란 무엇인가요?
     * ─────────────────────
     * 모든 객체가 공유하는 멤버예요.
     * 객체를 만들지 않아도 사용할 수 있어요!
     *
     * 마치 학교 운동장처럼요.
     * 학생 개인 것이 아니라 모든 학생이 함께 쓰죠.
     *
     * 또는 학생 수 카운터처럼요.
     * 학생이 한 명 더 생길 때마다 +1 하는 공유 숫자예요.
     */

    class 은행계좌
    {
        // static 필드 - 모든 계좌가 공유
        private static int _총계좌수 = 0;
        private static double _은행총자산 = 0;
        public static double 기본이자율 = 0.02;  // 2%

        // 인스턴스 필드 - 각 계좌마다 따로 있음
        private string _계좌번호;
        private string _소유자;
        private double _잔액;

        // static 프로퍼티 - 모든 계좌가 공유
        public static int 총계좌수 => _총계좌수;
        public static double 은행총자산 => _은행총자산;

        // 인스턴스 프로퍼티
        public string 계좌번호 => _계좌번호;
        public string 소유자 => _소유자;
        public double 잔액 => _잔액;

        public 은행계좌(string 소유자, double 초기잔액)
        {
            _총계좌수++;
            _계좌번호 = $"ACC-{_총계좌수:D4}";
            _소유자 = 소유자;
            _잔액 = 초기잔액;
            _은행총자산 += 초기잔액;
            Console.WriteLine($"  계좌 생성: {_계좌번호} ({소유자}, {초기잔액:N0}원)");
        }

        public void 입금(double 금액)
        {
            if (금액 <= 0) { Console.WriteLine("  입금액은 0보다 커야 해요!"); return; }
            _잔액 += 금액;
            _은행총자산 += 금액;
            Console.WriteLine($"  {_소유자} 계좌 입금: +{금액:N0}원 (잔액: {_잔액:N0}원)");
        }

        public void 출금(double 금액)
        {
            if (금액 > _잔액) { Console.WriteLine("  잔액이 부족해요!"); return; }
            _잔액 -= 금액;
            _은행총자산 -= 금액;
            Console.WriteLine($"  {_소유자} 계좌 출금: -{금액:N0}원 (잔액: {_잔액:N0}원)");
        }

        // static 메서드 - 객체 없이 호출 가능
        public static void 은행정보출력()
        {
            Console.WriteLine($"  ── 은행 현황 ──");
            Console.WriteLine($"  총 계좌 수: {_총계좌수}개");
            Console.WriteLine($"  은행 총 자산: {_은행총자산:N0}원");
            Console.WriteLine($"  기본 이자율: {기본이자율:P0}");
        }
    }

    // ════════════════════════════════════════════════════════
    //  4. 접근 제어자 정리
    // ════════════════════════════════════════════════════════

    /*
     * 접근 제어자란?
     * ──────────────
     * "누가 접근할 수 있나요?" 를 정하는 키워드예요.
     *
     * ┌────────────┬──────────────────────────────────────┐
     * │ public     │ 어디서든 접근 가능 (공개)            │
     * │ private    │ 이 클래스 안에서만 (비공개, 기본값)  │
     * │ protected  │ 이 클래스 + 자식 클래스              │
     * │ internal   │ 같은 프로젝트 안에서만               │
     * └────────────┴──────────────────────────────────────┘
     *
     * 왜 private을 쓰나요?
     * 마치 일기장에 자물쇠를 채우는 것처럼요.
     * 외부에서 마음대로 바꾸지 못하게 보호해요!
     *
     * "캡슐화" = 데이터를 안전하게 보호하기
     */

    class 온도계
    {
        private double _온도셀시우스;  // 내부에서만 관리

        public double 섭씨
        {
            get => _온도셀시우스;
            set
            {
                if (value < -273.15)  // 절대 영도보다 낮을 수 없어요!
                    throw new ArgumentException("절대 영도보다 낮을 수 없어요!");
                _온도셀시우스 = value;
            }
        }

        // 계산 프로퍼티 (섭씨 ↔ 화씨 변환)
        public double 화씨
        {
            get => _온도셀시우스 * 9 / 5 + 32;
            set => _온도셀시우스 = (value - 32) * 5 / 9;
        }

        public double 켈빈 => _온도셀시우스 + 273.15;

        public string 설명
        {
            get
            {
                if (_온도셀시우스 < 0) return "영하예요! 꽁꽁 얼어요 🥶";
                if (_온도셀시우스 < 10) return "매우 추워요 🧥";
                if (_온도셀시우스 < 20) return "쌀쌀해요 👕";
                if (_온도셀시우스 < 30) return "따뜻해요 😊";
                return "더워요! 시원하게 해요 🌊";
            }
        }
    }

