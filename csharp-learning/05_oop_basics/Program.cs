            Console.WriteLine("══ 2. 학생 클래스 (자동 프로퍼티) ══\n");

            // 생성자로 만들기
            학생 학생1 = new 학생("김민준", 1, 12, "3");
            학생 학생2 = new 학생("이수진", 2, 11, "2");

