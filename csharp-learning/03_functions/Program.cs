using System;

namespace FunctionsDemo
{
    class Program
    {
        // ════════════════════════════════════════════════════
        //  메서드(함수)란 무엇인가요?
        // ════════════════════════════════════════════════════
        /*
         * 메서드 = "재사용 가능한 일 묶음"
         * ────────────────────────────────
         * 마치 레시피 카드처럼요!
         *
         * "볶음밥 만들기" 레시피:
         *   1. 재료 준비 (매개변수)
         *   2. 요리하기 (본문)
         *   3. 완성된 볶음밥 내놓기 (반환값)
         *
         * 장점:
         * - 같은 코드를 여러 번 쓰지 않아도 돼요
         * - 코드가 깔끔하게 정리돼요
         * - 나중에 고칠 때 한 곳만 고치면 돼요
         *
         * 형식:
         * [접근제어자] [반환타입] 메서드이름([매개변수]) {
         *     // 메서드 본문
         *     return 반환값;  // 반환타입이 void면 없어도 돼요
         * }
         */

        // ════════════════════════════════════════════════════
        //  1. 반환값이 없는 메서드 (void)
        // ════════════════════════════════════════════════════

        // void = "아무것도 반환하지 않는다"
        // 마치 청소부 아저씨가 청소하고 끝내는 것처럼
        // 결과물을 주지 않고 그냥 일만 해요.
        static void 인사하기()
        {
            Console.WriteLine("안녕하세요! 반갑습니다!");
        }

        // 매개변수가 있는 void 메서드
        // 재료를 받아서 일을 하지만 결과를 돌려주지 않아요
        static void 이름으로인사하기(string 이름)
        {
            Console.WriteLine($"안녕하세요, {이름}님! 반갑습니다!");
        }

        // 여러 매개변수
        static void 자기소개(string 이름, int 나이, string 학교)
        {
            Console.WriteLine($"저는 {이름}이고, {나이}살이며, {학교}에 다닙니다.");
        }

        // ════════════════════════════════════════════════════
        //  2. 반환값이 있는 메서드
        // ════════════════════════════════════════════════════

        // 두 수를 더해서 결과를 돌려주는 메서드
        // 마치 자판기처럼: 돈(매개변수)을 넣으면 음료(반환값)가 나와요!
        static int 더하기(int a, int b)
        {
            int 결과 = a + b;
            return 결과;  // return = "이 값을 돌려줘!"
        }

        // 짧게 쓸 수도 있어요 (식 본문 메서드)
        static int 빼기(int a, int b) => a - b;
        static int 곱하기(int a, int b) => a * b;
        static double 나누기(double a, double b) => b != 0 ? a / b : 0;

        // 원의 넓이 계산
        static double 원넓이(double 반지름)
        {
            return Math.PI * 반지름 * 반지름;
        }

        // bool 반환 - 참/거짓 판단
        static bool 짝수인가(int 숫자)
        {
            return 숫자 % 2 == 0;
        }

        // string 반환
        static string 등급매기기(int 점수)
        {
            if (점수 >= 90) return "A";
            if (점수 >= 80) return "B";
            if (점수 >= 70) return "C";
            if (점수 >= 60) return "D";
            return "F";
        }

        // ════════════════════════════════════════════════════
        //  3. 메서드 오버로딩 - "같은 이름, 다른 재료"
        // ════════════════════════════════════════════════════

        /*
         * 오버로딩이란 무엇인가요?
         * ────────────────────────
         * 같은 이름의 메서드를 다른 매개변수로 여러 개 만들 수 있어요.
         *
         * 마치 "안녕"이라는 인사를
         * - 친구에게: "야, 안녕!"
         * - 선생님에게: "선생님, 안녕하세요!"
         * - 외국인에게: "Hello!"
         * 다르게 하는 것처럼요.
         *
         * C#이 알아서 어떤 오버로드를 쓸지 결정해줘요!
         */

        // 같은 이름 "출력하기"인데 매개변수가 달라요
        static void 출력하기(int 숫자)
        {
            Console.WriteLine($"숫자: {숫자}");
        }

        static void 출력하기(double 숫자)
        {
            Console.WriteLine($"소수: {숫자:F2}");
        }

        static void 출력하기(string 텍스트)
        {
            Console.WriteLine($"문자열: {텍스트}");
        }

        static void 출력하기(string 텍스트, int 반복횟수)
        {
            for (int i = 0; i < 반복횟수; i++)
                Console.WriteLine($"  [{i + 1}] {텍스트}");
        }

        // 넓이 계산 오버로딩
        static double 넓이계산(double 가로, double 세로)          // 직사각형
            => 가로 * 세로;

        static double 넓이계산(double 반지름)                      // 원
            => Math.PI * 반지름 * 반지름;

        static double 넓이계산(double 밑변, double 높이, bool 삼각형)  // 삼각형
            => 삼각형 ? 밑변 * 높이 / 2 : 밑변 * 높이;

        // ════════════════════════════════════════════════════
        //  4. 선택적 매개변수 (기본값)
        // ════════════════════════════════════════════════════

        /*
         * 선택적 매개변수란?
         * ──────────────────
         * 매개변수에 기본값을 주면,
         * 호출할 때 그 매개변수를 안 써도 돼요!
         *
         * 마치 피자 주문할 때
         * "치즈 피자 주세요" (도우는 기본값 사용)
         * "치즈 피자, 씬 도우로 주세요" (도우를 지정)
         * 처럼요.
         */

        // 기본값이 있는 매개변수들
        static void 커피주문(string 종류 = "아메리카노", int 샷 = 1, bool 얼음 = true)
        {
            string 온도 = 얼음 ? "아이스" : "핫";
            Console.WriteLine($"주문: {온도} {종류} {샷}샷");
        }

        // 인사 함수 (횟수에 기본값)
        static void 반복인사(string 이름, int 횟수 = 1, string 인사말 = "안녕하세요")
        {
            for (int i = 0; i < 횟수; i++)
                Console.WriteLine($"{인사말}, {이름}님!");
        }

        // ════════════════════════════════════════════════════
        //  5. 이름 있는 인수 (Named Arguments)
        // ════════════════════════════════════════════════════

        /*
         * 이름 있는 인수란?
         * ─────────────────
         * 매개변수 이름을 명시해서 순서를 바꿔 쓸 수 있어요.
         *
         * 마치 편지 봉투에
         * "받는 사람: 김민준" 처럼 라벨을 붙이는 것처럼요.
         */

        static void 학생등록(string 이름, int 나이, string 반)
        {
            Console.WriteLine($"등록: {이름}학생, {나이}살, {반}반");
        }

        // ════════════════════════════════════════════════════
        //  6. ref 매개변수 - "진짜 값을 직접 바꾸기"
        // ════════════════════════════════════════════════════

        /*
         * ref란 무엇인가요?
         * ─────────────────
         * 보통 매개변수는 "복사본"을 받아요.
         * 원본은 그대로예요.
         *
         * 하지만 ref를 쓰면 "원본"을 직접 받아서 바꿀 수 있어요!
         *
         * 비유:
         * - 일반 매개변수: 사진 복사본을 받아서 낙서 → 원본은 깨끗
         * - ref 매개변수: 원본 사진을 직접 받아서 낙서 → 원본이 바뀜!
         */

        static void 두배로만들기_일반(int 숫자)
        {
            숫자 = 숫자 * 2;  // 복사본만 바뀜, 원본은 그대로!
            Console.WriteLine($"  메서드 안: {숫자}");
        }

        static void 두배로만들기_ref(ref int 숫자)
        {
            숫자 = 숫자 * 2;  // 원본이 바뀜!
            Console.WriteLine($"  메서드 안: {숫자}");
        }

        // 두 값 교환 (swap)
        static void 교환하기(ref int a, ref int b)
        {
            int 임시 = a;
            a = b;
            b = 임시;
        }

        // ════════════════════════════════════════════════════
        //  7. out 매개변수 - "메서드에서 여러 값 받기"
        // ════════════════════════════════════════════════════

        /*
         * out이란 무엇인가요?
         * ───────────────────
         * 메서드가 하나의 return 값만 줄 수 있는데,
         * out을 쓰면 여러 개의 값을 받을 수 있어요!
         *
         * 마치 계산기가 "몫"과 "나머지"를 동시에 알려주는 것처럼요.
         */

        // 나눗셈 결과와 나머지를 동시에 반환
        static void 나눗셈정보(int 피제수, int 제수, out int 몫, out int 나머지)
        {
            몫 = 피제수 / 제수;
            나머지 = 피제수 % 제수;
        }

        // 최댓값과 최솟값을 동시에 찾기
        static int 최댓값찾기(int[] 배열, out int 최솟값)
        {
            int 최댓값 = 배열[0];
            최솟값 = 배열[0];

            foreach (int 숫자 in 배열)
            {
                if (숫자 > 최댓값) 최댓값 = 숫자;
                if (숫자 < 최솟값) 최솟값 = 숫자;
            }

            return 최댓값;
        }

        // ════════════════════════════════════════════════════
        //  8. params - "개수 제한 없이 받기"
        // ════════════════════════════════════════════════════

        /*
         * params란 무엇인가요?
         * ────────────────────
         * 매개변수 개수가 정해지지 않을 때 사용해요.
         *
         * 마치 뷔페처럼:
         * "접시에 원하는 만큼 음식 담아요" (1개든, 10개든 OK!)
         */

        static int 합계계산(params int[] 숫자들)
        {
            int 합 = 0;
            foreach (int n in 숫자들)
                합 += n;
            return 합;
        }

        static void 목록출력(string 제목, params string[] 항목들)
        {
            Console.WriteLine($"== {제목} ==");
            for (int i = 0; i < 항목들.Length; i++)
                Console.WriteLine($"  {i + 1}. {항목들[i]}");
        }

        // ════════════════════════════════════════════════════
        //  9. 재귀 메서드 - "자기 자신을 부르는 마법"
        // ════════════════════════════════════════════════════

        /*
         * 재귀란 무엇인가요?
         * ──────────────────
         * 메서드가 자기 자신을 호출하는 거예요!
         *
         * 마치 거울을 마주보면 거울 속에 거울이, 그 안에 또 거울이...
         * 처럼 반복되는 구조예요.
         *
         * 꼭 필요한 것: "멈추는 조건" (기저 사례)
         * 없으면 영원히 반복돼요! (스택 오버플로우 오류!)
         *
         * 예시: 팩토리얼
         * 5! = 5 × 4 × 3 × 2 × 1
         * factorial(5) = 5 × factorial(4)
         *                    = 4 × factorial(3)
         *                         = 3 × factorial(2)
         *                              = 2 × factorial(1)
         *                                   = 1 (멈춤!)
         */

        // 팩토리얼 (n!)
        static long 팩토리얼(int n)
        {
            // 기저 사례: 멈추는 조건!
            if (n <= 1) return 1;

            // 재귀 호출: 자기 자신을 더 작은 값으로 부름
            return n * 팩토리얼(n - 1);
        }

        // 피보나치 수열
        // 1, 1, 2, 3, 5, 8, 13, 21...
        // 앞 두 수의 합이 다음 수!
        static int 피보나치(int n)
        {
            if (n <= 1) return n;
            return 피보나치(n - 1) + 피보나치(n - 2);
        }

        // 거듭제곱 (재귀 버전)
        static double 거듭제곱(double 밑, int 지수)
        {
            if (지수 == 0) return 1;
            if (지수 < 0) return 1 / 거듭제곱(밑, -지수);
            return 밑 * 거듭제곱(밑, 지수 - 1);
        }

        // ════════════════════════════════════════════════════
        //  Main 메서드 - 모든 걸 실행하는 곳
        // ════════════════════════════════════════════════════
        static void Main(string[] args)
        {
            Console.WriteLine("══ 1. 기본 메서드 ══\n");

            인사하기();
            이름으로인사하기("김민준");
            자기소개("이수진", 11, "행복초등학교");

            Console.WriteLine("\n── 반환값 있는 메서드 ──");
            int 합 = 더하기(15, 27);
            Console.WriteLine($"15 + 27 = {합}");
            Console.WriteLine($"20 - 8 = {빼기(20, 8)}");
            Console.WriteLine($"6 × 7 = {곱하기(6, 7)}");
            Console.WriteLine($"10 ÷ 3 = {나누기(10, 3):F4}");
            Console.WriteLine($"반지름 5인 원의 넓이: {원넓이(5):F2}");
            Console.WriteLine($"7은 짝수인가? {짝수인가(7)}");
            Console.WriteLine($"8은 짝수인가? {짝수인가(8)}");
            Console.WriteLine($"85점의 등급: {등급매기기(85)}");

            Console.WriteLine("\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");
            Console.WriteLine("══ 2. 메서드 오버로딩 ══\n");

            출력하기(42);
            출력하기(3.14);
            출력하기("안녕하세요");
            출력하기("화이팅!", 3);

            Console.WriteLine("\n── 넓이 계산 오버로딩 ──");
            Console.WriteLine($"직사각형 (4×6): {넓이계산(4, 6):F2}");
            Console.WriteLine($"원 (반지름 3): {넓이계산(3.0):F2}");
            Console.WriteLine($"삼각형 (밑변 4, 높이 5): {넓이계산(4, 5, true):F2}");

            Console.WriteLine("\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");
            Console.WriteLine("══ 3. 선택적 매개변수 ══\n");

            커피주문();                              // 기본값 사용
            커피주문("카페라떼");                     // 종류만 지정
            커피주문("모카", 2);                     // 종류, 샷 지정
            커피주문("바닐라라떼", 2, false);         // 모두 지정

            Console.WriteLine();
            반복인사("철수");
            반복인사("영희", 2);
            반복인사("민준", 3, "좋은 아침이에요");

            Console.WriteLine("\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");
            Console.WriteLine("══ 4. 이름 있는 인수 ══\n");

            // 순서대로 전달
            학생등록("김민준", 11, "3");

            // 이름으로 전달 (순서 달라도 OK!)
            학생등록(반: "2", 이름: "이수진", 나이: 10);

            // 일부만 이름으로 전달
            학생등록("박철수", 나이: 12, 반: "1");

            Console.WriteLine("\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");
            Console.WriteLine("══ 5. ref 매개변수 ══\n");

            int 원본 = 5;
            Console.WriteLine($"메서드 호출 전: {원본}");

            두배로만들기_일반(원본);
            Console.WriteLine($"일반 매개변수 후: {원본} (변화 없음!)");

            두배로만들기_ref(ref 원본);
            Console.WriteLine($"ref 매개변수 후: {원본} (원본이 바뀜!)");

            Console.WriteLine("\n── swap (두 값 교환) ──");
            int 사과 = 10, 바나나 = 20;
            Console.WriteLine($"교환 전: 사과={사과}, 바나나={바나나}");
            교환하기(ref 사과, ref 바나나);
