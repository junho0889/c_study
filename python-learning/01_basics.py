def lesson1_hello_world():
    # =========================================================================
    #
    #   레슨 1 — Hello, World!  (프로그램의 기본 구조)
    #
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 1 : Hello, World!              │")
    print("└──────────────────────────────────────┘")
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ print() 함수란?
    # ─────────────────────────────────────────────────────────────────────
    #
    #   화면에 글자를 출력하는 함수입니다.
    #
    #   비유: print()는 마이크!  마이크에 대고 말하면 화면에 나타납니다.
    #         "Hello"를 마이크에 넣으면 → 화면에 "Hello" 가 나타남.
    #
    #   C++ : cout << "Hello, World!" << endl;
    #   파이썬: print("Hello, World!")
    #
    #   → 파이썬이 훨씬 짧고 간단합니다!
    #
    #   print()의 특징:
    #   - 자동으로 줄바꿈 (endl을 안 써도 됨!)
    #   - 여러 값을 쉼표(,)로 연결 가능
    #   - 숫자, 문자열, 계산 결과 모두 출력 가능
    #
    print("  Hello, World!")                      # 가장 기본적인 출력
    print("  안녕하세요, 파이썬 세계!")            # 한글도 완벽하게 됩니다!
    print("  숫자 출력:", 42)                       # 쉼표로 연결
    print("  계산 결과:", 3 + 5)                    # 계산도 바로!

    # 여러 값을 쉼표로 한 번에 출력 (자동으로 공백 추가)
    print("  이름:", "홍길동", ", 나이:", 25, "세")
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ print() 자세히 알기
    # ─────────────────────────────────────────────────────────────────────
    #
    #   print(값1, 값2, ..., sep=구분자, end=끝문자)
    #
    #   sep  = 값들 사이의 구분자 (기본값: " " 공백 하나)
    #   end  = 마지막에 붙는 문자 (기본값: "\n" 줄바꿈)
    #
    #   이것들을 바꿀 수 있습니다!
    #
    print("  구분자 변경:", 1, 2, 3, sep="-")           # 1-2-3
    print("  구분자 없음:", 1, 2, 3, sep="")             # 123
    print("  끝 문자 변경:", "줄 안 바꿈", end=" ← 같은 줄!")
    print()
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ 파이썬 코드의 뼈대
    # ─────────────────────────────────────────────────────────────────────
    #
    #   ┌──────────────────────────────────────────┐
    #   │  # 주석 (설명글, 실행 안 됨)             │
    #   │                                           │
    #   │  print("Hello")   ← 코드 실행            │
    #   │                                           │
    #   │  ※ C++과 다른 점:                        │
    #   │    - main() 함수가 없어도 됨!             │
    #   │    - 세미콜론(;) 없음!                   │
    #   │    - 중괄호 {} 없음! (들여쓰기로 구분)   │
    #   └──────────────────────────────────────────┘
    #
    #   ★ 초보자 실수 TOP 3
    #   ────────────────────
    #   1. 들여쓰기(인덴트)가 안 맞음  ← 가장 흔한 실수!
    #   2. 대소문자 구분 (Print ≠ print)
    #   3. 따옴표 종류 혼용 (시작은 " 끝은 ' → 에러!)
    #
    print("  ★ 파이썬 코드 규칙")
    print("  - 들여쓰기: 스페이스 4칸 또는 탭 1개")
    print("  - 대소문자 구분: print ≠ Print")
    print("  - 줄 끝에 세미콜론 불필요!")
    print()


def lesson2_variables():
    # =========================================================================
    #
    #   레슨 2 — 변수와 자료형
    #
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 2 : 변수와 자료형              │")
    print("└──────────────────────────────────────┘")
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ 변수란?
    # ─────────────────────────────────────────────────────────────────────
    #
    #   변수 = 값을 담는 상자  (상자에 이름표를 붙여서 구분)
    #
    #   비유:
    #     서랍장의 서랍 하나하나가 "변수"
    #     서랍에 이름표("age", "name")를 붙이고
    #     그 안에 값(25, "홍길동")을 넣는 것
    #
    #   C++ : int age = 25;     ← 타입을 미리 선언해야 함!
    #   파이썬:   age = 25       ← 타입 선언 없이 그냥 쓰면 됨!
    #
    #   파이썬은 C++과 다르게 타입을 미리 선언하지 않아도 됩니다!
    #   마치 어떤 물건이든 넣을 수 있는 "마법 서랍" 같아요.
    #
    #   ★ 변수 이름 규칙
    #   ─────────────────
    #   - 영문자, 숫자, 밑줄(_)만 사용 가능
    #   - 숫자로 시작할 수 없음  (2nd → 안됨, second → 됨)
    #   - 예약어 사용 불가 (if, for, class 등)
    #   - 대소문자 구분 (age ≠ Age ≠ AGE)
    #   - 관례: snake_case 사용 (my_score, player_name)
    #

    # ─────────────────────────────────────────────
    # ■ 정수형 (int) — 소수점이 없는 숫자
    # ─────────────────────────────────────────────
    #
    #   파이썬의 int는 크기 제한이 없습니다!
    #   C++의 int는 약 21억 제한, 파이썬은 무한대!
    #
    #   비유: C++의 int는 특정 크기 서랍
    #         파이썬의 int는 마법으로 늘어나는 서랍!
    #
    age = 25                          # 나이
    temperature = -10                 # 음수도 됩니다
    world_population = 8_000_000_000  # _ 로 자릿수 구분 (가독성!)

    print("  ■ 정수형 (int)")
    print("  ─────────────────────────────────────")
    print("  age             =", age)
    print("  temperature     =", temperature)
    print("  world_pop       =", world_population)

    # ★ 파이썬만의 기능: 언더스코어로 숫자 가독성 향상
    big_number = 1_000_000_000   # 10억 (읽기 쉽게!)
    print("  big_number      =", big_number, "(1_000_000_000 → 10억)")
    print()

    # ─────────────────────────────────────────────
    # ■ 실수형 (float) — 소수점이 있는 숫자
    # ─────────────────────────────────────────────
    #
    #   파이썬의 float = C++의 double (64비트 배정도 부동소수점)
    #
    #   ★★★ 주의! 부동소수점 오차 ★★★
    #   컴퓨터는 소수를 2진수로 저장해서 미세한 오차가 생깁니다.
    #   0.1 + 0.2 = 0.3 이 아닐 수 있어요!
    #
    pi = 3.14159265358979
    price = 9.99
    negative = -3.14

    print("  ■ 실수형 (float)")
    print("  ─────────────────────────────────────")
    print("  pi       =", pi)
    print("  price    =", price)
    print("  negative =", negative)

    # 부동소수점 오차 확인
    print()
    print("  ★ 부동소수점 오차!")
    result = 0.1 + 0.2
    print("  0.1 + 0.2 =", result)          # 0.3이 아닐 수 있음!
    print("  0.1 + 0.2 == 0.3:", 0.1 + 0.2 == 0.3)  # False!
    print("  → 소수끼리 == 비교는 위험합니다!")
    print()

    # ─────────────────────────────────────────────
    # ■ 문자열 (str) — 글자들의 모음
    # ─────────────────────────────────────────────
    #
    #   작은따옴표 ' 또는 큰따옴표 " 모두 사용 가능!
    #   시작과 끝 따옴표 종류만 같으면 됩니다.
    #
    #   C++: string name = "홍길동";  ← 큰따옴표만
    #   파이썬: name = "홍길동"
    #           name = '홍길동'      ← 둘 다 됩니다!
    #
    #   여러 줄 문자열: 따옴표 세 개 ''' 또는 """
    #
    name = "홍길동"
    greeting = '안녕하세요'
    multiline = """여러 줄
문자열
가능합니다"""

    print("  ■ 문자열 (str)")
    print("  ─────────────────────────────────────")
    print("  name      =", name)
    print("  greeting  =", greeting)
    print("  multiline:")
    print(multiline)
    print()

    # ─────────────────────────────────────────────
    # ■ 논리형 (bool) — 참(True) 또는 거짓(False)
    # ─────────────────────────────────────────────
    #
    #   True  = 참  (반드시 대문자 T!)
    #   False = 거짓 (반드시 대문자 F!)
    #
    #   C++: bool is_student = true;   (소문자)
    #   파이썬: is_student = True      (대문자!)
    #
    #   ★ 파이썬에서 True/False는 대문자로 시작!
    #     true/false → 에러! (소문자 쓰면 안 됨!)
    #
    is_student = True
    is_sleeping = False

    print("  ■ 논리형 (bool)")
    print("  ─────────────────────────────────────")
    print("  is_student  =", is_student)
    print("  is_sleeping =", is_sleeping)
    print()

    # ─────────────────────────────────────────────
    # ■ None — 파이썬만의 특별한 값
    # ─────────────────────────────────────────────
    #
    #   "값이 없다" 또는 "아직 정해지지 않았다"를 표현
    #
    #   비유: 빈 서랍 (서랍이 있긴 한데 내용물이 없는 상태)
    #
    #   C++에서는 이런 개념이 없었지만
    #   파이썬에서는 자주 사용합니다.
    #
    result = None
    print("  ■ None (값 없음)")
    print("  ─────────────────────────────────────")
    print("  result =", result)
    print("  result is None:", result is None)   # None 비교는 == 대신 is 사용!
    print()


def lesson3_type_checking():
    # =========================================================================
    #
    #   레슨 3 — 타입 확인 (type())
    #
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 3 : 타입 확인 (type())         │")
    print("└──────────────────────────────────────┘")
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ type() 함수
    # ─────────────────────────────────────────────────────────────────────
    #
    #   변수의 자료형(타입)을 확인하는 함수
    #
    #   비유: 서랍 안에 뭐가 들었는지 확인하는 것
    #         type(age) → "이 서랍엔 정수가 들어있네!"
    #
    #   C++은 선언할 때 타입을 쓰니까 알 수 있지만,
    #   파이썬은 타입을 안 쓰기 때문에 type()이 유용합니다.
    #

    x = 42
    y = 3.14
    z = "안녕"
    w = True
    n = None

    print("  ■ type() 함수 사용")
    print("  ─────────────────────────────────────")
    print("  type(42)     =", type(x))        # <class 'int'>
    print("  type(3.14)   =", type(y))        # <class 'float'>
    print("  type('안녕') =", type(z))        # <class 'str'>
    print("  type(True)   =", type(w))        # <class 'bool'>
    print("  type(None)   =", type(n))        # <class 'NoneType'>
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ isinstance() 함수 — 타입 검사 (권장!)
    # ─────────────────────────────────────────────────────────────────────
    #
    #   "이 변수가 이 타입이 맞나요?" 라고 물어보는 함수
    #
    #   type(x) == int  보다  isinstance(x, int)  를 권장합니다!
    #   (이유는 나중에 상속에서 배웁니다)
    #
    age = 25
    name = "김철수"

    print("  ■ isinstance() 함수")
    print("  ─────────────────────────────────────")
    print("  isinstance(age, int)    =", isinstance(age, int))
    print("  isinstance(age, str)    =", isinstance(age, str))
    print("  isinstance(name, str)   =", isinstance(name, str))
    print("  isinstance(True, int)   =", isinstance(True, int))   # True!
    # ★ 흥미로운 사실: 파이썬에서 bool은 int의 자식!
    # True는 1, False는 0으로 사용 가능
    print()

    # 여러 타입 동시에 검사
    value = 42
    print("  isinstance(42, (int, float)):", isinstance(value, (int, float)))
    print()


def lesson4_type_conversion():
    # =========================================================================
    #
    #   레슨 4 — 타입 변환
    #
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 4 : 타입 변환                  │")
    print("└──────────────────────────────────────┘")
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ 타입 변환이란?
    # ─────────────────────────────────────────────────────────────────────
    #
    #   한 자료형의 값을 다른 자료형으로 바꾸는 것
    #
    #   비유: 달러를 원화로 환전하는 것
    #         → 때로는 정보가 사라질 수 있음 (소수점 잘림)
    #
    #   파이썬은 int(), float(), str(), bool() 함수로 변환합니다.
    #   C++의 static_cast<int>() 와 비슷한 역할!
    #

    print("  ■ 정수로 변환 (int())")
    print("  ─────────────────────────────────────")
    print("  int(3.9)     =", int(3.9))     # 3  소수점 버림! (반올림 아님!)
    print("  int(3.1)     =", int(3.1))     # 3  무조건 버림
    print("  int('42')    =", int('42'))    # 42  문자열 → 정수
    print("  int(True)    =", int(True))    # 1
    print("  int(False)   =", int(False))   # 0
    print()

    # ★ 흔한 실수: int('3.14')는 에러!
    # 소수점이 있는 문자열은 바로 int()로 변환 못 함
    # float('3.14') 먼저 하고, 그 다음 int() 해야 함
    print("  ★ 주의: int('3.14')는 에러!")
    print("  해결: int(float('3.14')) =", int(float('3.14')))
    print()

    print("  ■ 실수로 변환 (float())")
    print("  ─────────────────────────────────────")
    print("  float(42)    =", float(42))     # 42.0
    print("  float('3.14')=", float('3.14')) # 3.14
    print("  float(True)  =", float(True))   # 1.0
    print()

    print("  ■ 문자열로 변환 (str())")
    print("  ─────────────────────────────────────")
    print("  str(42)      =", str(42))       # '42'
    print("  str(3.14)    =", str(3.14))     # '3.14'
    print("  str(True)    =", str(True))     # 'True'

    # 실용 예제: 숫자와 문자열 합치기
    age = 25
    message = "나이: " + str(age) + "세"  # str()로 변환 후 + 로 합치기
    print("  '나이: ' + str(25) + '세' =", message)
    print()

    print("  ■ 논리값으로 변환 (bool())")
    print("  ─────────────────────────────────────")
    #
    #   False가 되는 값들 (외워두세요!)
    #   ─────────────────────────────
    #   0, 0.0, "", [], {}, (), None, False
    #
    #   위 값들을 제외한 모든 것 → True
    #
    print("  bool(0)      =", bool(0))        # False
    print("  bool(1)      =", bool(1))        # True
    print("  bool(-1)     =", bool(-1))       # True (0이 아니면 True!)
    print("  bool('')     =", bool(''))       # False (빈 문자열)
    print("  bool('hi')   =", bool('hi'))     # True
    print("  bool([])     =", bool([]))       # False (빈 리스트)
    print("  bool(None)   =", bool(None))     # False
    print()


def lesson5_constants():
    # =========================================================================
    #
    #   레슨 5 — 상수 관례
    #
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 5 : 상수 관례 (UPPER_CASE)    │")
    print("└──────────────────────────────────────┘")
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ 파이썬의 상수
    # ─────────────────────────────────────────────────────────────────────
    #
    #   C++에는 const, constexpr 키워드로 상수를 강제할 수 있지만,
    #   파이썬에는 진짜 상수(변경 불가)가 없습니다!
    #
    #   대신 관례로 이름을 대문자로 써서 "상수처럼 쓸 것"을 표시합니다.
    #
    #   비유: "이 서랍에는 함부로 손대지 마세요" 라는 경고문을 붙이는 것
    #
    #   ★ 규칙: 이름을 대문자 + 밑줄로 쓴다 (UPPER_SNAKE_CASE)
    #
