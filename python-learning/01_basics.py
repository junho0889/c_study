    n //= 4
    print("  n //= 4  →", n)    # 정수 나눗셈
    n %= 7
    print("  n %= 7   →", n)
    n **= 2
    print("  n **= 2  →", n, "  (제곱)")
    print()

    # ★ 주의: 파이썬에는 ++ 와 -- 가 없습니다!
    # C++: i++, i--, ++i, --i
    # 파이썬: i += 1, i -= 1
