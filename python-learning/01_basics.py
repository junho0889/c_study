    #   파이썬: 17 / 5 = 3.4  (항상 실수!)
    #
    #   파이썬은 / 연산자가 항상 실수(float)를 반환합니다.
    #   정수 나눗셈(몫)을 원하면 // 를 씁니다.
    #
    print("  ■ C++ vs 파이썬 나눗셈 차이")
    print("  ─────────────────────────────────────")
    print("  파이썬: 17 / 5  =", 17 / 5, "   ← 항상 실수!")
    print("  파이썬: 17 // 5 =", 17 // 5, "    ← 정수 나눗셈(몫)")
    print("  파이썬: 17 % 5  =", 17 % 5, "    ← 나머지")
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ ** 거듭제곱 연산자
    # ─────────────────────────────────────────────────────────────────────
    #
    #   C++: pow(2, 10) 함수를 써야 함
    #   파이썬: 2 ** 10  ← 연산자로 바로!
    #
    print("  ■ 거듭제곱 (**)")
    print("  ─────────────────────────────────────")
    print("  2 ** 10 =", 2 ** 10, "  (2의 10승)")
