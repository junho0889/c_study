def lesson9_collection_guide():
    # =========================================================================
    #
    #   레슨 9 — 컬렉션 선택 가이드
    #
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 9 : 컬렉션 선택 가이드         │")
    print("└──────────────────────────────────────┘")
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ 언제 무엇을 쓸까? — 비교표
    # ─────────────────────────────────────────────────────────────────────
    #
    #   ┌─────────┬────────┬────────┬────────────┬───────────────────┐
    #   │ 자료형  │ 순서   │ 수정   │ 중복 허용  │ 주 용도           │
    #   ├─────────┼────────┼────────┼────────────┼───────────────────┤
    #   │ list    │ O      │ O      │ O          │ 범용, 순서 중요   │
    #   │ tuple   │ O      │ X      │ O          │ 고정 데이터       │
    #   │ set     │ X      │ O      │ X          │ 중복 제거, 집합   │
    #   │ dict    │ O(3.7+)│ O      │ 키:X 값:O  │ 키-값 매핑       │
    #   │ deque   │ O      │ O      │ O          │ 양쪽 삽입/삭제   │
    #   └─────────┴────────┴────────┴────────────┴───────────────────┘
    #

    # ─────────────────────────────────────────────────────────────────────
    # ■ 시간복잡도 (Big-O) — 성능 비교
    # ─────────────────────────────────────────────────────────────────────
    #
    #   ┌────────────────┬──────────┬──────────┬──────────┐
    #   │ 연산           │ list     │ dict/set │ deque    │
    #   ├────────────────┼──────────┼──────────┼──────────┤
    #   │ 인덱스 접근    │ O(1)     │ -        │ O(1)양끝 │
    #   │ 검색 (in)      │ O(n)     │ O(1) ★  │ O(n)     │
    #   │ 맨 뒤 추가     │ O(1)     │ O(1)     │ O(1)     │
    #   │ 맨 앞 추가     │ O(n) ★  │ -        │ O(1) ★  │
    #   │ 중간 삽입      │ O(n)     │ -        │ O(n)     │
    #   │ 삭제 (값으로)  │ O(n)     │ O(1) ★  │ O(n)     │
    #   └────────────────┴──────────┴──────────┴──────────┘
    #
    #   ★ = 이 자료형이 유리한 연산!
    #
    #   핵심 규칙:
    #   - "이 값이 있는지 자주 확인?" → set 또는 dict
    #   - "순서대로 처리?" → list
    #   - "앞뒤로 넣고 빼기?" → deque
    #   - "키로 값 찾기?" → dict
    #   - "중복 제거?" → set
    #   - "절대 바뀌면 안 되는 데이터?" → tuple
    #

    # 실제 성능 차이 데모
    import time

    big_list = list(range(1_000_000))
    big_set = set(range(1_000_000))

    # list에서 검색
    start = time.perf_counter()
    _ = 999_999 in big_list
    list_time = time.perf_counter() - start

    # set에서 검색
    start = time.perf_counter()
    _ = 999_999 in big_set
    set_time = time.perf_counter() - start

    print(f"  list에서 검색: {list_time:.6f}초")
    print(f"  set에서 검색:  {set_time:.6f}초")
    if list_time > 0 and set_time > 0:
        print(f"  → set이 약 {list_time/max(set_time, 1e-9):.0f}배 빠름!")
    print()


def lesson10_practice():
    # =========================================================================
    #
    #   레슨 10 — 실전: 학생 성적 관리 시스템
    #
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 10 : 학생 성적 관리 시스템     │")
    print("└──────────────────────────────────────┘")
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ 모든 컬렉션을 활용한 종합 예제
    # ─────────────────────────────────────────────────────────────────────
    #
    #   사용하는 컬렉션:
    #   - list: 학생 목록, 점수 목록
    #   - dict: 학생별 정보
    #   - set: 과목 목록 (중복 없이)
    #   - tuple: (학생이름, 과목) 쌍
    #   - defaultdict: 과목별 점수 모으기
    #   - Counter: 등급 통계
    #   - deque: 최근 성적 기록
    #

    # 학생 데이터 (리스트 + 딕셔너리)
    students = [
        {"이름": "민수", "반": 1, "성적": {"국어": 85, "수학": 92, "영어": 78}},
        {"이름": "지유", "반": 1, "성적": {"국어": 95, "수학": 88, "영어": 97}},
        {"이름": "서연", "반": 2, "성적": {"국어": 72, "수학": 95, "영어": 83}},
        {"이름": "하준", "반": 2, "성적": {"국어": 88, "수학": 76, "영어": 91}},
        {"이름": "수빈", "반": 1, "성적": {"국어": 91, "수학": 84, "영어": 89}},
    ]

    # 1) 전체 과목 세트 (중복 없이)
    all_subjects = set()
    for s in students:
        all_subjects.update(s["성적"].keys())
    print("  전체 과목:", all_subjects)

    # 2) 학생별 평균 (딕셔너리 컴프리헨션)
    averages = {
        s["이름"]: sum(s["성적"].values()) / len(s["성적"])
        for s in students
    }
    print("  학생별 평균:", {k: f"{v:.1f}" for k, v in averages.items()})

    # 3) 과목별 전체 평균 (defaultdict)
    subject_scores = defaultdict(list)
    for s in students:
        for subject, score in s["성적"].items():
            subject_scores[subject].append(score)

    print("  과목별 평균:")
    for subject, scores in subject_scores.items():
        avg = sum(scores) / len(scores)
        print(f"    {subject}: {avg:.1f}점")

    # 4) 등급 매기기 (Counter)
    def get_grade(avg):
        if avg >= 90: return "A"
        if avg >= 80: return "B"
        if avg >= 70: return "C"
        return "D"

    grades = [get_grade(avg) for avg in averages.values()]
    grade_count = Counter(grades)
    print("  등급 분포:", dict(grade_count))

    # 5) 반별 학생 그룹핑 (defaultdict)
    class_groups = defaultdict(list)
    for s in students:
        class_groups[s["반"]].append(s["이름"])
    print("  반별 학생:", dict(class_groups))

    # 6) 1등 찾기 (tuple 언패킹)
    top_name, top_avg = max(averages.items(), key=lambda x: x[1])
    print(f"  전체 1등: {top_name} ({top_avg:.1f}점)")

    # 7) 최근 성적 기록 (deque)
    recent_scores = deque(maxlen=3)
    score_history = [85, 88, 92, 78, 95, 91]
    for score in score_history:
        recent_scores.append(score)
    print(f"  최근 3번 점수: {list(recent_scores)}")

    # 8) 80점 이상인 (학생, 과목) 튜플 리스트
    high_scores = [
        (s["이름"], subject)
        for s in students
        for subject, score in s["성적"].items()
        if score >= 90
    ]
    print("  90점 이상 목록:", high_scores)
    print()


