    # 연습 1: 최대공약수 (유클리드 알고리즘)
    def gcd(a, b):
        """유클리드 알고리즘으로 최대공약수 계산"""
        while b:
            a, b = b, a % b
        return a

    def lcm(a, b):
        """최소공배수 = a*b / gcd(a,b)"""
        return a * b // gcd(a, b)

    print("  ■ 최대공약수와 최소공배수")
    print(f"  gcd(12, 8)  = {gcd(12, 8)}")
    print(f"  lcm(4, 6)   = {lcm(4, 6)}")
    print()

