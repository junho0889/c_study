def lesson1_if_elif_else():
    # =========================================================================
    #   레슨 1 — if / elif / else
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 1 : if / elif / else           │")
    print("└──────────────────────────────────────┘")
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ if문이란?
    # ─────────────────────────────────────────────────────────────────────
    #
    #   "만약 ~라면, 이것을 해라"
    #
    #   비유: 신호등
    #     초록불이면 → 건넌다
    #     노란불이면 → 천천히
    #     빨간불이면 → 멈춘다
    #
    #   C++:
    #     if (score >= 90) {    ← 소괄호 + 중괄호
    #         cout << "A";
    #     }
    #     else if (score >= 80) { ...
    #
    #   파이썬:
    #     if score >= 90:       ← 소괄호 없음! 끝에 콜론(:)!
    #         print("A")        ← 들여쓰기로 블록 구분!
    #     elif score >= 80:     ← else if → elif 로 줄임!
    #         ...
    #
    #   핵심 차이:
    #   1. 조건에 ( ) 없어도 됨
    #   2. 블록 끝에 콜론(:) 필수!
    #   3. 중괄호 {} 없음 → 들여쓰기로 블록 구분!
    #   4. else if → elif
    #

    score = 85

    print(f"  ■ 성적 판정 (score = {score})")
    print("  ─────────────────────────────────────")

    if score >= 90:
        print("  등급: A (수)")
    elif score >= 80:
        print("  등급: B (우)")       # ← 여기 실행! (85 >= 80)
    elif score >= 70:
        print("  등급: C (미)")
    elif score >= 60:
        print("  등급: D (양)")
    else:
        print("  등급: F (가)")
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ 논리 연산자 조합
    # ─────────────────────────────────────────────────────────────────────
    #
    #   and  = 그리고 (C++의 &&)
    #   or   = 또는   (C++의 ||)
    #   not  = 아닌   (C++의 !)
    #
    #   파이썬은 기호 대신 단어를 씁니다! 더 읽기 쉬워요.
    #
    age = 20
    has_ticket = True
    is_vip = False

    print(f"  ■ 논리 조합 (나이={age}, 티켓={has_ticket}, VIP={is_vip})")
    print("  ─────────────────────────────────────")

    if age >= 18 and has_ticket:
        print("  입장 가능 (성인 + 티켓)")

    if is_vip or has_ticket:
        print("  입장 가능 (VIP거나 티켓)")

    if not is_vip:
        print("  VIP가 아닙니다")
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ 파이썬만의 특별 비교
    # ─────────────────────────────────────────────────────────────────────
    #
    #   x < y < z  →  x < y and y < z  (수학적 비교 가능!)
    #   in  연산자  →  리스트/문자열에 포함되는지
    #   not in      →  포함되지 않는지
    #   is          →  동일한 객체인지 (주소 비교)
    #   is not      →  다른 객체인지
    #
    num = 15
    print(f"  ■ 파이썬 특별 비교 (num = {num})")
    print("  ─────────────────────────────────────")
    print("  10 < num < 20:", 10 < num < 20)      # True (연속 비교!)
    print("  num in [10,15,20]:", num in [10, 15, 20])  # True
    print("  num not in [1,2,3]:", num not in [1, 2, 3])  # True
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ 흔한 실수
    # ─────────────────────────────────────────────────────────────────────
    #
    #   ★ 실수 #1: 콜론(:) 빠뜨림
    #     if x > 0      ← 에러! 끝에 : 가 없음
    #     if x > 0:     ← 올바름
    #
    #   ★ 실수 #2: 들여쓰기 안 맞음
    #     if x > 0:
    #     print("양수")  ← 에러! 들여쓰기 필요
    #         print("양수")  ← 올바름
    #
    #   ★ 실수 #3: = 와 == 혼동
    #     if x = 5:   ← 에러! (파이썬은 = 가 if 안에서 에러)
    #     if x == 5:  ← 올바름
    #
    print("  ★ 흔한 실수 정리")
    print("  if x > 0     ← 에러! (콜론 없음)")
    print("  if x > 0:    ← 올바름")
    print("  들여쓰기 불일치 → IndentationError")
    print("  if x = 5:    ← 에러! (파이썬은 이것도 에러)")
    print()


def lesson2_ternary():
    # =========================================================================
    #   레슨 2 — 삼항 표현식 (조건 표현식)
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 2 : 삼항 표현식               │")
    print("└──────────────────────────────────────┘")
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ 삼항 표현식이란?
    # ─────────────────────────────────────────────────────────────────────
    #
    #   if/else를 한 줄로 줄인 것
    #
    #   C++:    result = (score >= 60) ? "합격" : "불합격";
    #   파이썬: result = "합격" if score >= 60 else "불합격"
    #
    #   파이썬은 순서가 다릅니다!
    #   참일때값  if  조건  else  거짓일때값
    #
    #   비유: "합격이야, 만약 60점 이상이면, 아니면 불합격"
    #
    score = 75

    result = "합격" if score >= 60 else "불합격"
    print(f"  score={score}: {result}")

    # 다양한 활용
    age = 20
    status = "성인" if age >= 18 else "미성년"
    print(f"  age={age}: {status}")

    # 숫자 활용
    x = -5
    absolute = x if x >= 0 else -x     # 절대값
    print(f"  |{x}| = {absolute}")

    # 중첩 삼항 (가독성 주의!)
    num = 0
    sign = "양수" if num > 0 else ("음수" if num < 0 else "영")
    print(f"  {num} → {sign}")
    print()
    print("  ★ 중첩 삼항은 복잡해지면 일반 if/elif/else 쓰세요!")
    print()


def lesson3_for_loops():
    # =========================================================================
    #   레슨 3 — for 반복문
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 3 : for 반복문                 │")
    print("└──────────────────────────────────────┘")
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ for문이란?
    # ─────────────────────────────────────────────────────────────────────
    #
    #   "리스트나 범위의 값을 하나씩 꺼내서 처리"
    #
    #   C++:    for (int i = 0; i < 5; i++) { ... }
    #   파이썬: for i in range(5): ...
    #
    #   파이썬의 for는 C++의 범위 기반 for 와 더 비슷합니다.
    #   for 변수 in 반복가능한것:
    #       실행할 코드
    #

    # ─────────────────────────────────────────────────────────────────────
    # ■ range() 함수
    # ─────────────────────────────────────────────────────────────────────
    #
    #   range(끝)          → 0, 1, 2, ..., 끝-1
    #   range(시작, 끝)    → 시작, ..., 끝-1
    #   range(시작, 끝, 간격) → 시작, 시작+간격, ..., 끝 미만
    #
    print("  ■ range() 사용")
    print("  ─────────────────────────────────────")

    # 1부터 5까지
    print("  1~5: ", end="")
    for i in range(1, 6):           # range(1, 6) = 1,2,3,4,5
        print(i, end=" ")
    print()

    # 5부터 1까지 (역순)
    print("  5~1: ", end="")
    for i in range(5, 0, -1):       # range(5, 0, -1) = 5,4,3,2,1
        print(i, end=" ")
    print()

    # 짝수만
    print("  짝수: ", end="")
    for i in range(2, 11, 2):       # 2씩 증가
        print(i, end=" ")
    print()

    # 3의 배수
    print("  3의 배수: ", end="")
    for i in range(3, 31, 3):
        print(i, end=" ")
    print()
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ 리스트 순회
    # ─────────────────────────────────────────────────────────────────────
    #
    #   C++의 범위 기반 for와 동일:
    #   for (auto& item : list) { ... }  ↔  for item in list:
    #
    fruits = ["사과", "바나나", "체리", "딸기", "포도"]

    print("  ■ 리스트 순회")
    print("  ─────────────────────────────────────")
    print("  과일: ", end="")
    for fruit in fruits:
        print(fruit, end=" ")
    print()

    # enumerate(): 인덱스와 값 동시에 가져오기
    print()
    print("  enumerate() - 인덱스 + 값:")
    for i, fruit in enumerate(fruits):
        print(f"    [{i}] {fruit}")
    print()

    # enumerate(시작값) - 1부터 시작
    print("  enumerate(1번부터):")
    for i, fruit in enumerate(fruits, start=1):
        print(f"    {i}번: {fruit}")
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ 문자열 순회
    # ─────────────────────────────────────────────────────────────────────
    #
    #   문자열도 반복 가능합니다! (글자 하나씩 꺼냄)
    #
    word = "Python"
    print("  ■ 문자열 순회")
    print("  ─────────────────────────────────────")
    print("  글자: ", end="")
    for char in word:
        print(char, end="-")
    print()
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ zip() — 두 리스트 동시에 순회
    # ─────────────────────────────────────────────────────────────────────
    names = ["홍길동", "김철수", "이영희"]
    scores = [95, 82, 78]

    print("  ■ zip() — 두 리스트 동시 순회")
    print("  ─────────────────────────────────────")
    for name, score in zip(names, scores):
        print(f"    {name}: {score}점")
    print()


def lesson4_while_loops():
    # =========================================================================
    #   레슨 4 — while 반복문
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 4 : while 반복문               │")
    print("└──────────────────────────────────────┘")
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ while문이란?
    # ─────────────────────────────────────────────────────────────────────
    #
    #   "조건이 참인 동안 계속 반복"
    #
    #   C++: while (power < 1000) { power *= 2; }
    #   파이썬: while power < 1000: power *= 2
    #
    #   언제 쓸까?
    #   ─────────
    #   for → 반복 횟수를 미리 알 때
    #   while → 조건이 참인 동안 (언제 끝날지 모를 때)
    #

    # 2의 거듭제곱
    print("  ■ 2의 거듭제곱 (1000 미만)")
    print("  ", end="")
    power = 1
    while power < 1000:
        print(power, end=" ")
        power *= 2
    print()
    print()

    # 자릿수 세기
    number = 123456
    digits = 0
    temp = number
    while temp > 0:
        digits += 1
        temp //= 10     # 10으로 나누면 맨 뒤 자릿수 제거
    print(f"  {number}의 자릿수: {digits}")
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ 무한루프 + break 패턴
    # ─────────────────────────────────────────────────────────────────────
    #
    #   while True: → 영원히 반복 (무한루프)
    #   반드시 break로 탈출 조건을 만들어야 합니다!
    #
    #   실무에서 자주 쓰이는 패턴:
    #   - 사용자 입력 대기
    #   - 게임 메인 루프
    #   - 서버 요청 대기
    #
    print("  ■ 무한루프 + break 패턴")
    attempt = 0
    while True:
        attempt += 1
        print(f"  시도 #{attempt}")
        if attempt >= 3:
            print("  → 3번 시도 후 탈출!")
            break
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ while...else (파이썬만의 특별 기능!)
    # ─────────────────────────────────────────────────────────────────────
    #
    #   while 루프가 break 없이 정상적으로 끝나면 else 실행
    #   break로 탈출하면 else 실행 안 됨!
    #
    #   비유: 반복문이 "성공적으로" 끝났을 때 실행하는 코드
    #
    print("  ■ while...else")
    target = 7
    i = 1
    while i <= 5:
        if i == target:
            print(f"  {target} 발견!")
            break
        i += 1
    else:
        print(f"  1~5에서 {target}을 찾지 못했습니다")   # ← 이게 실행됨!
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ 흔한 실수: 무한루프
    # ─────────────────────────────────────────────────────────────────────
    print("  ★ 무한루프 흔한 실수")
    print("  i = 0")
    print("  while i < 10:")
    print("      print(i)  # i += 1 을 빠뜨리면 → 영원히 0 출력!")
    print()
    print("  해결: Ctrl + C 로 강제 종료")
    print()


def lesson5_break_continue_pass():
    # =========================================================================
    #   레슨 5 — break / continue / pass
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 5 : break / continue / pass    │")
    print("└──────────────────────────────────────┘")
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ break vs continue vs pass
    # ─────────────────────────────────────────────────────────────────────
    #
    #   break    : 반복문을 즉시 탈출 (바깥으로 나감)
    #   continue : 이번 회차만 건너뛰고 다음 회차로
    #   pass     : 아무것도 안 함 (자리만 채우기)
    #
    #   그림:
    #   for i in ...:            for i in ...:
    #       ...                      ...
    #       break  ─→ 탈출          continue ─┐
    #       ...  (실행 안됨)         ...  (건너뜀)│
    #   탈출 후 여기                  ←──────────┘
    #

    # break: 배열에서 30 찾기
    print("  ■ break — 리스트에서 30 찾기")
    numbers = [10, 20, 30, 40, 50]
    for i, num in enumerate(numbers):
        print(f"  검사: [{i}] = {num}", end="")
        if num == 30:
            print(" ← 찾았다! 중단!")
            break
        print()
    print()

    # continue: 홀수 건너뛰기
    print("  ■ continue — 짝수만 출력")
    print("  ", end="")
    for i in range(1, 11):
        if i % 2 != 0:
            continue    # 홀수면 건너뜀
        print(i, end=" ")
    print()
    print()

    # 실용 예제: 음수 무시하고 합계
    print("  ■ 실용 예제 — 양수만 합산")
    data = [5, -3, 8, -1, 7, -4, 2]
    total = 0
    for val in data:
        if val < 0:
            continue    # 음수 건너뜀
        total += val
    print(f"  데이터: {data}")
    print(f"  양수 합계: {total}")
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ pass — 아무것도 안 함
    # ─────────────────────────────────────────────────────────────────────
    #
    #   C++에는 없는 개념!
    #   파이썬에서 코드 블록이 비어있으면 에러가 납니다.
    #   pass를 쓰면 "아무것도 안 하겠다"고 명시합니다.
    #
    #   언제 사용?
    #   - 나중에 채울 코드 자리 확보
    #   - 예외를 의도적으로 무시
    #   - 빈 클래스/함수 정의 시
    #
    print("  ■ pass 사용 예시")

    for i in range(5):
        if i == 3:
            pass        # 나중에 여기 뭔가 채울 예정
        else:
            print(f"  i = {i}")
    print()

    # 빈 함수 (나중에 구현 예정)
    def todo_function():
        pass    # 아직 미구현

    print("  todo_function() 정의됨 (pass로 비어있음)")
    print()


def lesson6_list_comprehension():
    # =========================================================================
    #   레슨 6 — 리스트 컴프리헨션
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 6 : 리스트 컴프리헨션          │")
    print("└──────────────────────────────────────┘")
    print()

    # ─────────────────────────────────────────────────────────────────────
    # ■ 리스트 컴프리헨션이란?
    # ─────────────────────────────────────────────────────────────────────
    #
    #   for 루프로 리스트를 만드는 것을 한 줄로 줄인 것!
    #   파이썬만의 강력한 기능입니다.
    #
    #   C++에는 없는 기능!
    #
    #   형식:
    #   [표현식 for 변수 in 반복가능한것]
    #   [표현식 for 변수 in 반복가능한것 if 조건]
    #
    #   비유:
    #   "친구들 목록에서 나이 20 이상인 친구들의 이름만 모아라"
    #   → [이름 for 친구 in 친구목록 if 나이 >= 20]
    #

    # 일반 방식 vs 컴프리헨션
    print("  ■ 일반 방식 vs 컴프리헨션")
    print("  ─────────────────────────────────────")

    # 일반 방식 (for 루프)
    squares_loop = []
    for i in range(1, 6):
        squares_loop.append(i ** 2)

    # 리스트 컴프리헨션
    squares_comp = [i ** 2 for i in range(1, 6)]

    print("  일반 방식:", squares_loop)
    print("  컴프리헨션:", squares_comp)
    print()

    # 조건 포함
    print("  ■ 조건 포함 컴프리헨션")
    print("  ─────────────────────────────────────")

    # 1~20 중 짝수만
    evens = [i for i in range(1, 21) if i % 2 == 0]
    print("  짝수:", evens)

