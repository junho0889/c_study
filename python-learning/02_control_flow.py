def lesson7_nested_loops():
    # =========================================================================
    #   레슨 7 — 중첩 반복문
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 7 : 중첩 반복문                │")
    print("└──────────────────────────────────────┘")
    print()

    # 구구단
    print("  ■ 구구단 (2~3단)")
    print("  ─────────────────────────────────────")
    for dan in range(2, 4):
        print(f"  [{dan}단]")
        for i in range(1, 10):
            print(f"    {dan} x {i} = {dan * i}")
    print()

    # 별 찍기: 직각삼각형
    print("  ■ 직각 삼각형")
    for row in range(1, 6):
        print("  " + "★ " * row)
    print()

    # 피라미드
    print("  ■ 피라미드")
    height = 5
    for row in range(1, height + 1):
        spaces = " " * (height - row)
        stars = "★" * (2 * row - 1)
        print(f"  {spaces}{stars}")
    print()

    # 중첩 루프에서 break
    print("  ■ 중첩 break (플래그 방식)")
    found = False
    for i in range(3):
        for j in range(3):
            print(f"  ({i},{j})", end="")
            if i == 1 and j == 1:
                print(" ← 찾음!")
                found = True
                break       # 안쪽 루프 탈출
            print()
        if found:
            break           # 바깥 루프도 탈출
    print()


