def lesson2_statistical():
    # =========================================================================
    #   레슨 2 — 통계식 탐지
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 2 : 통계식 탐지                │")
    print("└──────────────────────────────────────┘")
    # ■ z-score:  z = (x - μ) / σ.  |z| > 3 이면 이상 후보.
    #   - 가정: 정규분포. 분포가 두꺼운 꼬리이면 과탐.
    # ■ IQR:     Q1 - 1.5·IQR ~ Q3 + 1.5·IQR.  비모수, 강건.
    # ■ Robust z (MAD): MAD = median(|x - median(x)|).  z* = 0.6745·(x - median)/MAD.
    #   - 이상치 자체가 평균을 끌어가는 문제를 해결.
    series = [10, 11, 9, 10, 12, 9, 11, 50, 10, 8]
    med = sorted(series)[len(series) // 2]
    mad = sorted([abs(x - med) for x in series])[len(series) // 2]
    print(" series:", series)
    print(f" median={med}, MAD={mad}")
    for x in series:
        z = 0.6745 * (x - med) / (mad if mad else 1)
        flag = "  ← 이상!" if abs(z) > 3.5 else ""
        print(f"  x={x}, robust_z={z:+.2f}{flag}")
    print()


