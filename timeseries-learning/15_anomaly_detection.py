def lesson7_practice():
    # =========================================================================
    #   레슨 7 — 실전: z-score / 잔차 / AE식 단순 비교
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 7 : 3가지 방법 비교            │")
    print("└──────────────────────────────────────┘")
    random.seed(13)
    n = 60
    Y = [50 + 5 * math.sin(2 * math.pi * t / 7) + random.gauss(0, 1.0) for t in range(n)]
    # 이상 주입
    Y[20] += 15
    Y[40] -= 12
    Y[55] += 8

    # 1) z-score
    mean = sum(Y) / n
    std = math.sqrt(sum((y - mean) ** 2 for y in Y) / n)
    z = [(y - mean) / std for y in Y]

    # 2) 잔차 기반: 7일 rolling mean 예측
    pred = []
    for t in range(n):
        if t < 7:
            pred.append(None)
        else:
            pred.append(sum(Y[t - 7:t]) / 7)
    resid = [(Y[t] - pred[t]) if pred[t] is not None else 0.0 for t in range(n)]

    # 3) AE식 단순 복원: 한 윈도우 평균으로 ‘복원’ 가정 → 잔차와 거의 같지만, 양쪽 윈도우(과거+미래) 사용한다고 가정
    recon_err = [abs(y - mean) for y in Y]  # 매우 단순화

    print(" t | Y      |  z   | 잔차  | AE_err | 의심?")
    for t in range(n):
        flags = []
        if abs(z[t]) > 2.5:
            flags.append("z")
        if abs(resid[t]) > 3 * std:
            flags.append("res")
        if recon_err[t] > 3 * std:
            flags.append("ae")
        if flags:
            print(f"{t:>3} | {Y[t]:6.2f} | {z[t]:+5.2f} | {resid[t]:+6.2f} | {recon_err[t]:6.2f} |  ← {','.join(flags)}")
    print()
    # 관찰: 주입된 이상치(t=20,40,55) 가 잔차 기반에서 가장 깨끗하게 잡힘.


