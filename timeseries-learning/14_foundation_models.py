def lesson7_practice_quantile_tokenize():
    # =========================================================================
    #   레슨 7 — Quantile binning 토큰화 실습
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 7 : quantile binning           │")
    print("└──────────────────────────────────────┘")
    series = [1.0, 1.2, 0.9, 1.5, 2.0, 1.8, 1.3, 0.7, 3.0, 2.5, 2.2, 1.1]
    K = 5
    sorted_s = sorted(series)
    # 경계: K-1 개의 컷팅 포인트
    cuts = [sorted_s[(i + 1) * len(sorted_s) // K - 1] for i in range(K - 1)]

    def to_token(v):
        for idx, c in enumerate(cuts):
            if v <= c:
                return idx
        return K - 1

    tokens = [to_token(v) for v in series]
    print(" cuts:", [round(c, 2) for c in cuts])
    print(" series :", series)
    print(" tokens :", tokens)
    print()
    # → 이렇게 정수 토큰화하면 LLM 어휘에 매핑 가능.  Chronos 가 정확히 이런 방식을 쓴다.


