def lesson1_ses():
    # =========================================================================
    #   레슨 1 — SES
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 1 : SES                        │")
    print("└──────────────────────────────────────┘")
    # ■ 단순 지수평활 (Simple Exponential Smoothing):
    #     L_t = α · Y_t + (1 - α) · L_{t-1}
    #     ŷ_{t+h} = L_t           (모든 미래 시점에 같은 값을 예측)
    #
    # ■ α(0~1): 1 에 가까울수록 ‘최근값’을 더 따라감, 0 에 가까울수록 ‘과거 평균’을 유지
    #
    # ■ 적합 대상:
    #   - 트렌드 없고 계절성 없는 데이터
    #   - 예: 일정 수준 근처에서 진동하는 “재고 보유량” 같은 시계열
    print(" L_t = αY_t + (1-α)L_{t-1}.   α 가 클수록 ‘민첩한’ 평활.")
    print()


def lesson2_holt():
    # =========================================================================
    #   레슨 2 — Holt 선형 추세
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 2 : Holt                       │")
    print("└──────────────────────────────────────┘")
    # ■ Holt's Linear Trend:
    #     L_t = α · Y_t + (1 - α)(L_{t-1} + T_{t-1})       ← 레벨
    #     T_t = β · (L_t - L_{t-1}) + (1 - β) · T_{t-1}    ← 추세
    #     ŷ_{t+h} = L_t + h · T_t                          ← h-step 예측
    #
    # ■ Damped trend (감쇠 추세):  미래 멀어질수록 트렌드가 약해짐
    #     ŷ_{t+h} = L_t + (φ + φ² + … + φ^h) · T_t  (0<φ<1)
    print(" Holt = SES + 추세항(T_t).   damped 옵션으로 ‘추세 무한 외삽’을 막을 수 있음.")
    print()


def lesson3_holt_winters():
    # =========================================================================
    #   레슨 3 — Holt-Winters
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 3 : Holt-Winters               │")
    print("└──────────────────────────────────────┘")
    # ■ 가법(additive) 계절:
    #     L_t = α(Y_t - S_{t-m}) + (1-α)(L_{t-1} + T_{t-1})
    #     T_t = β(L_t - L_{t-1}) + (1-β)T_{t-1}
    #     S_t = γ(Y_t - L_t)      + (1-γ)S_{t-m}
    #     ŷ_{t+h} = L_t + h·T_t + S_{t+h-m}   (h ≤ m 일 때)
    #
    # ■ 승법(multiplicative) 계절:
    #     L_t = α(Y_t / S_{t-m}) + (1-α)(L_{t-1}+T_{t-1})
    #     S_t = γ(Y_t / L_t) + (1-γ)S_{t-m}
    #     ŷ_{t+h} = (L_t + h·T_t) · S_{t+h-m}
    #
    # ■ statsmodels:
    #     from statsmodels.tsa.holtwinters import ExponentialSmoothing
    #     fit = ExponentialSmoothing(y, trend='add', seasonal='add',
    #                                seasonal_periods=12).fit()
    #     fc = fit.forecast(12)
    print(" Holt-Winters = SES + 추세 + 계절(m).   M5/Kaggle 류에서도 강한 베이스라인.")
    print()


def lesson4_ets_taxonomy():
    # =========================================================================
    #   레슨 4 — ETS 분류
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 4 : ETS 분류                   │")
    print("└──────────────────────────────────────┘")
    # ■ ETS 의 3 글자 코드:
    #     Error      : A (additive)  /  M (multiplicative)
    #     Trend      : N (none) / A / Ad (additive damped)
    #     Seasonality: N / A / M
    #
    # ■ 대표 조합:
    #     (A,N,N) = SES
    #     (A,A,N) = Holt
    #     (A,A,A) = Holt-Winters 가법
    #     (M,A,M) = 곱셈식 Holt-Winters
    #     (A,Ad,A) = Damped Holt-Winters
    print(" ETS(E,T,S) 표기는 ‘에러/추세/계절’의 형태를 한 줄로 압축한 분류 체계.")
    print()


