def lesson6_when_arima_vs_ets():
    # =========================================================================
    #   레슨 6 — ARIMA vs ETS
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 6 : 언제 무엇을?               │")
    print("└──────────────────────────────────────┘")
    # ■ ETS 선호:
    #   - 명확한 추세/계절성, 단기 예측, 빠른 베이스라인
    #   - 비통계 배경의 분석가에게도 해석이 쉬움
    #
    # ■ ARIMA 선호:
    #   - 외생변수(X) 영향을 같이 다루고 싶음 → SARIMAX
    #   - 잔차 자기상관 같은 “복잡한 시계열 구조”
    #   - 단위근 검정 등 통계적 엄격성이 필요할 때
    #
    # ■ 실무 팁:
    #   - 둘 다 돌리고 walk-forward CV 로 비교.
    #   - 둘을 평균(앙상블)만 해도 보통 더 안정적.
    print(" ETS = 빠르고 단단한 베이스라인, ARIMA = 외생/구조 포함의 정밀 모델")
