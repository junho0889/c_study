def lesson7_practice_ses_holt():
    # =========================================================================
    #   레슨 7 — 실전: SES / Holt 직접 코딩
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 7 : SES & Holt 손코딩          │")
    print("└──────────────────────────────────────┘")
    random.seed(2026)
    Y = [10 + 0.5 * t + random.gauss(0, 1) for t in range(20)]

    # SES (α=0.3)
    alpha = 0.3
    L = [Y[0]]
    for t in range(1, len(Y)):
        L.append(alpha * Y[t] + (1 - alpha) * L[-1])

    # Holt (α=0.6, β=0.3)
    a, b = 0.6, 0.3
    Lh = [Y[0]]
    Th = [Y[1] - Y[0]]
    for t in range(1, len(Y)):
        l_new = a * Y[t] + (1 - a) * (Lh[-1] + Th[-1])
        t_new = b * (l_new - Lh[-1]) + (1 - b) * Th[-1]
        Lh.append(l_new); Th.append(t_new)

    print(" t |   Y   |  SES  | Holt L | Holt T |  Holt ŷ(t+1)")
    for t in range(len(Y)):
        forecast_holt = Lh[t] + Th[t]
        print(f"{t:>2} | {Y[t]:5.2f} | {L[t]:5.2f} | {Lh[t]:6.2f} | {Th[t]:6.2f} | {forecast_holt:6.2f}")
    print()
    # ■ 관찰: SES 는 마지막 레벨 한 값만 예측, Holt 는 트렌드를 추세선으로 외삽.


