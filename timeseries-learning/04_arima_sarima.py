#   2. MA(q)  — 과거 ‘충격’이 현재에 미치는 영향
#   3. ARMA(p,q) → ARIMA(p,d,q) → SARIMA(p,d,q)(P,D,Q,s)
#   4. ACF/PACF 로 (p,q) 식별하기
