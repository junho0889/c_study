    #     ARMA    │ 둘 다 천천히 감소 (혼합)
    #
    # ■ 실무 팁:
    #   - 정확히 들어맞는 경우는 드뭄. 후보 몇 개를 fitting → AIC/BIC 로 선택.
    #   - auto_arima 가 grid search 로 자동.
    print(" 식별표를 외워두면 90%의 케이스에서 첫 후보 (p,q) 를 찍을 수 있다.")
