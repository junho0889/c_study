def lesson7_yule_walker_ar1():
    # =========================================================================
    #   레슨 7 — 실전: AR(1) Yule-Walker 추정
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 7 : AR(1) 직접 추정            │")
    print("└──────────────────────────────────────┘")
    # ■ Yule-Walker 방정식 (AR1 의 경우):
    #     ρ(1) = φ_1
    #   즉, 자기상관 lag1 이 곧 φ_1 의 추정.
    random.seed(11)
    true_phi = 0.6
    Y = [0.0]
    for _ in range(2000):
        Y.append(true_phi * Y[-1] + random.gauss(0, 1))
    Y = Y[100:]  # burn-in
    n = len(Y)
    mean = sum(Y) / n
    num = sum((Y[t] - mean) * (Y[t - 1] - mean) for t in range(1, n))
    den = sum((v - mean) ** 2 for v in Y)
    phi_hat = num / den
    print(f" 진짜 φ = {true_phi},   yule-walker 추정 = {phi_hat:.3f}")
    print(" → 표본 크기가 클수록 진짜 값에 수렴함을 확인할 수 있다.")
    print()


