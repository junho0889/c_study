def lesson5_aic_bic():
    # =========================================================================
    #   레슨 5 — AIC / BIC
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 5 : AIC / BIC                  │")
    print("└──────────────────────────────────────┘")
    # ■ AIC = 2k − 2 log L      ( k = 파라미터 수, L = 우도 )
    # ■ BIC = k log n − 2 log L
    #
    # ■ 둘 다 “적합도 좋을수록 작아짐”. 더 작을수록 좋다.
    # ■ BIC 가 페널티가 더 큼 → 더 단순한 모델 선호
    # ■ 후보 모델 (1,1,1), (2,1,1), (1,1,2), (2,1,2) … 의 AIC 를 비교해서 선택
    print(" 후보 모델 fitting → AIC 최소 모델 채택, 잔차 진단 통과까지 확인.")
    print()


