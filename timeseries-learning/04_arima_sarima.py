    #   레슨 4 — (p, q) 식별
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 4 : ACF/PACF로 p,q 정하기     │")
    print("└──────────────────────────────────────┘")
    # ■ 클래식 규칙 (Box-Jenkins 식별표):
