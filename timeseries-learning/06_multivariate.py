def lesson7_practice_var1():
    # =========================================================================
    #   레슨 7 — 실전: 2변량 VAR(1) 모의
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 7 : 2변량 VAR(1)               │")
    print("└──────────────────────────────────────┘")
    # 실제 VAR(1): a11=0.5, a12=0.3, a21=0.0, a22=0.6
    random.seed(99)
    a11, a12, a21, a22 = 0.5, 0.3, 0.0, 0.6
    y1 = [0.0]
    y2 = [0.0]
    for _ in range(50):
        e1 = random.gauss(0, 1)
        e2 = random.gauss(0, 1)
        n1 = a11 * y1[-1] + a12 * y2[-1] + e1
        n2 = a21 * y1[-1] + a22 * y2[-1] + e2
        y1.append(n1); y2.append(n2)

    # 가짜로 OLS 1-lag 추정 (간단 버전: 정규방정식 직접 풀이는 생략, 상관계수만)
    def corr(a, b):
        n = len(a)
        ma, mb = sum(a) / n, sum(b) / n
        num = sum((a[i] - ma) * (b[i] - mb) for i in range(n))
        da = math.sqrt(sum((a[i] - ma) ** 2 for i in range(n)))
        db = math.sqrt(sum((b[i] - mb) ** 2 for i in range(n)))
        return num / (da * db) if da * db else 0.0

    print(f" corr(Y1_t, Y1_{{t-1}}) = {corr(y1[1:], y1[:-1]):.3f}  (≈ a11+영향)")
    print(f" corr(Y1_t, Y2_{{t-1}}) = {corr(y1[1:], y2[:-1]):.3f}  (a12 양수면 양상관)")
    print(f" corr(Y2_t, Y1_{{t-1}}) = {corr(y2[1:], y1[:-1]):.3f}  (a21=0 이면 약함)")
    print()
    # → Y2 가 Y1 의 미래를 예측하는데 도움이 됨 (Granger Y2 → Y1).
    #   반대 방향은 0 에 가까울 것 → 단방향 인과.


