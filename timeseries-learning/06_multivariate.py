def lesson1_what_is_multivariate():
    # =========================================================================
    #   레슨 1 — 다변량 시계열
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 1 : 다변량 시계열              │")
    print("└──────────────────────────────────────┘")
    # ■ 정의:  여러 시계열 변수가 동시에 관측되고, 서로 영향을 주고받는다.
    #   예) (매출, 광고비, 검색량), (온도, 습도, CO2), (환율, 금리, 주가)
