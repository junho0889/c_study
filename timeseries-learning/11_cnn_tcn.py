def lesson1_conv_for_ts():
    # =========================================================================
    #   레슨 1 — 1D CNN 의 시계열 적용
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 1 : 1D CNN                     │")
    print("└──────────────────────────────────────┘")
    # ■ 1D conv 는 ‘k 길이 윈도우’ 를 미끄러뜨리며 학습된 필터로 패턴 매칭.
    # ■ 시계열에서의 의미:
    #   - 필터 = ‘작은 시간 모티프’ (예: 급등 패턴, 골짜기 패턴)
    #   - 여러 채널 = 여러 변수의 동시 관측
    #
    #   x: [────────────────────]   ← 길이 T
    #   w: [── k ──]                  ← 학습되는 필터
    #
    # ■ 장점:
    #   - 병렬 학습 (RNN 의 순차 처리 한계 없음)
    #   - 메모리 효율적
    #   - 긴 시퀀스에 강함 (with dilation)
    print(" 1D CNN = 시간 축을 따라 ‘작은 모티프’를 학습하는 필터의 모음.")
    print()


def lesson2_receptive_field():
    # =========================================================================
    #   레슨 2 — Receptive Field
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 2 : Receptive Field            │")
    print("└──────────────────────────────────────┘")
    # ■ 정의: 출력 한 픽셀이 ‘보는’ 입력 길이.
    # ■ 1D conv L층, kernel k, stride 1, dilation 1:
    #     RF = L · (k - 1) + 1
    #
    # ■ 예: k=3, L=5  →  RF = 11
    # ■ 시계열 의존성이 길면 RF 도 커야 함 → 깊게 쌓거나 dilation 으로 키움.
    L, k = 5, 3
    print(f" plain conv  L={L}, k={k}  →  RF = {L*(k-1)+1}")
    print()


def lesson3_causal_padding():
    # =========================================================================
    #   레슨 3 — Causal padding
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 3 : Causal Padding             │")
    print("└──────────────────────────────────────┘")
    # ■ 기본 padding="same" 은 양쪽 패딩 → 출력 t 가 t+1 의 입력을 ‘본다’ → 미래 누설.
    # ■ Causal padding: 왼쪽(과거)만 패딩.
    #   - 출력 t 는 입력 t, t-1, …, t-k+1 만 사용
    #   - 시계열 예측에 필수.
    #
    #   x:  [pad, pad, x_0, x_1, x_2, x_3]
    #   w:               [w_0, w_1, w_2]
    #   y_0 = w_0*pad + w_1*pad + w_2*x_0    ← 과거만 사용
    print(" Causal padding = 왼쪽만 padding.  미래 누설 차단.")
    print()


def lesson4_dilated_conv():
    # =========================================================================
    #   레슨 4 — Dilated Conv
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 4 : Dilated Conv               │")
    print("└──────────────────────────────────────┘")
    # ■ dilation d 인 conv: 입력을 ‘d 칸씩 건너뛰며’ 본다.
    #   d=1: [x_{t-2}, x_{t-1}, x_t]
    #   d=2: [x_{t-4}, x_{t-2}, x_t]
    #   d=4: [x_{t-8}, x_{t-4}, x_t]
    #
    # ■ 층마다 dilation 을 2배씩 늘리면(1,2,4,8,16,…) RF 가 지수적으로 커짐:
    #     RF = (k - 1) · (2^L - 1) + 1
    #
    # ■ 예: k=3, L=6 → RF = 2·(63)+1 = 127
    L, k = 6, 3
    rf = (k - 1) * (2 ** L - 1) + 1
    print(f" dilated stack  L={L}, k={k}  →  RF = {rf}  (= 2 · (2^L - 1) + 1)")
    print()


def lesson5_tcn():
    # =========================================================================
    #   레슨 5 — TCN
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 5 : TCN                        │")
    print("└──────────────────────────────────────┘")
    # ■ TCN(Temporal Convolutional Network)의 핵심 구성:
    #   1) Causal conv
    #   2) Dilated conv (지수적 dilation)
    #   3) Residual block (skip connection)
    #   4) WeightNorm + Dropout
    #
    # ■ 출력 길이가 입력 길이와 같음 → seq-to-seq 도 쉽다.
    # ■ 학습 안정, 추론 빠름, 메모리 효율적.
    #
    # ■ 구조도:
    #     x → [Causal Dilated Conv → ReLU → Dropout → Causal Dilated Conv → ReLU → Dropout] + residual → y
    print(" TCN = 시계열판 ResNet.  병렬 + 안정 + 큰 RF.")
    print()


def lesson6_cnn_vs_rnn():
    # =========================================================================
    #   레슨 6 — CNN vs RNN
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 6 : CNN vs RNN                 │")
    print("└──────────────────────────────────────┘")
    # ■ TCN/CNN:
    #   + 병렬 학습 → GPU 활용도 높음
    #   + 명시적 RF (해석 쉬움)
    #   + 긴 시퀀스에 안정적
    #   − 가변 길이/매우 긴 시퀀스(>RF) 에선 한계
    #
    # ■ RNN(LSTM/GRU):
    #   + 이론상 무한 메모리
    #   + 가변 길이 자연스러움
    #   − 학습 느림, vanishing gradient
    #
    # ■ Transformer (12단계): 둘의 장점 + 한계가 또 다른 형태로.
    #   ─ 실무 권장: 단기/중기 예측 → TCN 또는 Patch-Transformer 우선 시도.
    print(" 실무 우선순위: TCN ≈ Transformer >  LSTM/GRU.  단, 데이터 작으면 LSTM.")
    print()


def lesson7_practice_1d_conv():
    # =========================================================================
    #   레슨 7 — 실전: 길이 16 시퀀스의 1D causal conv
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 7 : 1D conv 손코딩             │")
    print("└──────────────────────────────────────┘")
    random.seed(7)
    x = [round(math.sin(t / 2), 2) for t in range(16)]
    w = [0.3, 0.4, 0.3]  # k=3 filter
    pad = [0.0, 0.0]     # causal padding (왼쪽만)
    padded = pad + x
    y = []
    for t in range(len(x)):
        s = sum(padded[t + i] * w[i] for i in range(3))
        y.append(round(s, 3))
    print(" x :", x)
    print(" y :", y)
    print()
    # → 출력 y[0] 은 x[-2..0] (패딩 두 개 + x[0]) 의 가중합 — 과거만 사용.

    # Dilated 예: dilation=2, k=3
    print(" Dilation=2 version (앞 0 무시):")
    pad2 = [0.0, 0.0, 0.0, 0.0]   # 2*(k-1)=4 칸 패딩
    padded2 = pad2 + x
    y2 = []
    for t in range(len(x)):
        s = (padded2[t] * w[0] + padded2[t + 2] * w[1] + padded2[t + 4] * w[2])
        y2.append(round(s, 3))
    print(" y2:", y2)


