def lesson2_block_structure():
    # =========================================================================
    #   레슨 2 — Block 구조
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 2 : Block 구조                 │")
    print("└──────────────────────────────────────┘")
    # ■ 한 블록의 입력: 과거 lookback 윈도우 x (길이 L)
    # ■ 한 블록의 출력:
    #     backcast(x̂)  : 과거를 재구성한 추정
    #     forecast(ŷ)  : 미래 H step 예측
    #
    # ■ 잔차 갱신:  x_{t+1} = x_t − backcast_t   (다음 블록은 잔차로 다시 학습)
    #
    #   ┌─────┐         ┌─────┐
    #   │ Blk │──ŷ_1───▶│ Blk │──ŷ_2────▶ …
    #   └─┬───┘         └─┬───┘
    #     │ x - x̂_1       │ x - x̂_2
    print(" 각 블록은 backcast + forecast 를 ‘동시에’ 만든다.  잔차로 다음 블록.")
    print()


def lesson3_generic_vs_interpretable():
    # =========================================================================
    #   레슨 3 — Generic vs Interpretable
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 3 : Generic vs Interpretable   │")
    print("└──────────────────────────────────────┘")
    # ■ Generic Block:
    #   - 출력 = θ (학습 파라미터)
    #   - 자유로움 → 강력하지만 ‘해석 불가’
    #
    # ■ Interpretable Block:
    #   - Trend Block: ŷ_h = Σ_p θ_p · h^p  (다항식 basis)
    #   - Seasonality Block: ŷ_h = Σ_k (a_k cos + b_k sin)
    #   - 의미: 모델이 “이 기간의 트렌드는 +0.4 기울기, 7일 주기로 ±5 진동” 같은 사람 친화 설명을 제공
    print(" Interpretable 모드 = 모델이 ‘트렌드 + 계절’ 형태로 미래를 설명한다.")
    print()


