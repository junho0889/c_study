def lesson7_practice_basis():
    # =========================================================================
    #   레슨 7 — Polynomial / Fourier basis 로 1-step 흉내
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 7 : basis 1-step 흉내          │")
    print("└──────────────────────────────────────┘")
    # 가짜 미래 horizon = 5 step.
    H = 5
    # Trend basis (다항식 차수 2): {1, h, h²}
    # Seasonality basis (k=1): {cos(2πh/H), sin(2πh/H)}
    theta_trend = [10.0, 1.0, 0.05]              # 절편 + 기울기 + 곡률
    theta_season = [0.0, 2.0]                    # cos 계수, sin 계수

    print(" horizon h | trend | season | y_hat = trend + season")
    for h in range(1, H + 1):
        tr = theta_trend[0] + theta_trend[1] * h + theta_trend[2] * h * h
        se = theta_season[0] * math.cos(2 * math.pi * h / H) + theta_season[1] * math.sin(2 * math.pi * h / H)
        print(f"     {h}      | {tr:5.2f} | {se:+5.2f} | {tr + se:6.2f}")
    print()
    # 직관: 학습은 ‘θ_trend, θ_season 를 데이터에 맞게’ 찾는 일.


