def lesson7_practice_simple_next_item():
    # =========================================================================
    #   레슨 7 — 단순 ‘다음 아이템’ 예측
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 7 : 다음 아이템 (마르코프)     │")
    print("└──────────────────────────────────────┘")
    # 매우 단순한 ‘1차 마르코프’ 모델: P(item_t | item_{t-1})
    sessions = [
        ["A", "B", "C", "B", "C", "D"],
        ["A", "C", "C", "D"],
        ["B", "C", "D", "C", "A"],
        ["A", "B", "C", "D"],
    ]
    from collections import defaultdict, Counter
    counts = defaultdict(Counter)
    for s in sessions:
        for i in range(len(s) - 1):
            counts[s[i]][s[i + 1]] += 1

    print(" 학습된 전이 확률(P(next | prev)):")
    for prev, nx in counts.items():
        total = sum(nx.values())
        for item, c in sorted(nx.items()):
            print(f"  {prev} → {item} : {c/total:.2f}")
    print()
    # ■ 추천:
    user_seq = ["A", "B"]
    last = user_seq[-1]
    top = counts[last].most_common(1)[0][0] if counts[last] else "?"
    print(f" 사용자가 {user_seq} 를 클릭했다면 다음 추천: {top}")
    # → SASRec 같은 어텐션 모델은 더 긴 컨텍스트를 ‘비선형’으로 본다.


