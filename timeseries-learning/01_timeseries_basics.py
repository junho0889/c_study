def lesson7_practice():
    # =========================================================================
    #
    #   레슨 7 — 실전: 가짜 일간 매출 30일 만들기 + ACF 점검
    #
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 7 : 실전 실습                  │")
    print("└──────────────────────────────────────┘")
    print()
    random.seed(42)
    days = 30
    sales = []
    for t in range(days):
        trend = 100 + 1.2 * t
        weekly = 20 * math.sin(2 * math.pi * t / 7)   # 주간 계절성
        noise = random.gauss(0, 5)
        sales.append(trend + weekly + noise)

    print("일별 매출 (단위 만원)")
    print("day | sales")
    for t, s in enumerate(sales):
        bar = "█" * int(s / 5)
        print(f"{t:>3} | {s:7.2f}  {bar}")
    print()

    # rolling mean (window=7)
    print("Rolling Mean (window=7) — 7일 평균이 ‘우상향’이면 트렌드 존재")
    for t in range(6, days):
        window = sales[t - 6 : t + 1]
        rm = sum(window) / 7
        print(f" t={t:>2} | rolling_mean = {rm:7.2f}")
    print()


