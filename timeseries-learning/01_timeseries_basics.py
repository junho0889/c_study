def lesson2_components():
    # =========================================================================
    #
    #   레슨 2 — 시계열의 4가지 구성요소
    #
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 2 : 4가지 구성요소             │")
    print("└──────────────────────────────────────┘")
    print()
    # ■ Y(t) = Trend(t) + Seasonality(t) + Cycle(t) + Residual(t)     ← 가법(additive)
    # ■ Y(t) = Trend(t) × Seasonality(t) × Cycle(t) × Residual(t)     ← 승법(multiplicative)
    #
    # ┌ Trend(추세) ─────── 장기적으로 우상향/우하향 하는 흐름
    # ├ Seasonality(계절) ─ 고정 주기(일/주/연)로 반복되는 패턴
    # ├ Cycle(순환) ─────── 주기가 일정치 않은 경기/사이클 패턴
    # └ Residual(잔차) ─── 위 셋으로 설명되지 않는 노이즈
    #
    # 가짜 시계열 한 줄 생성 예:
    days = list(range(0, 30))
    trend = [0.5 * t for t in days]                      # 매일 +0.5
    season = [10 * math.sin(2 * math.pi * t / 7) for t in days]  # 7일 주기
    noise = [random.gauss(0, 1) for _ in days]
    y = [tr + se + ns for tr, se, ns in zip(trend, season, noise)]

    print("day | trend  | season | noise  | y")
    for i in range(0, 30, 3):
        print(f"{i:>3} | {trend[i]:6.2f} | {season[i]:6.2f} | {noise[i]:6.2f} | {y[i]:6.2f}")
    print()
    # 메시지: 어떤 시계열도 “이 4가지의 조합”이라 가정하고 시작하면 분석이 단순해진다.


def lesson3_stationarity():
    # =========================================================================
    #
    #   레슨 3 — 정상성(Stationarity)
    #
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 3 : 정상성                     │")
    print("└──────────────────────────────────────┘")
    print()
    # ■ 정상(stationary) 시계열의 정의 (약정상성, weak stationarity):
    #   1) 평균이 시간에 무관     E[Y(t)] = μ
    #   2) 분산이 시간에 무관     Var[Y(t)] = σ²
    #   3) 공분산은 “시차”에만 의존   Cov(Y(t), Y(t+k)) = γ(k)
    #
    # ■ 왜 중요한가?
    #   - 거의 모든 통계적 시계열 모델(ARIMA 등)은 “정상 시계열”을 가정.
    #   - 비정상 → 그대로 학습하면 미래 예측이 과거 평균에 끌려가지 못함.
    #
    # ■ 실무 점검:
    #   1) Rolling mean / std 를 그려본다 → 시간에 따라 흔들리면 비정상
    #   2) ADF test (Augmented Dickey-Fuller): p-value < 0.05 → 정상이라고 본다
    #   3) KPSS test: 위와 반대 가설 (보완 도구)
    #
    # ■ 정상화 방법:
    #   - 1차 차분 ΔY(t) = Y(t) − Y(t−1)
    #   - 로그/Box-Cox 변환 (분산 안정화)
    #   - 계절 차분 Y(t) − Y(t−s)
    print("정상 = 평균/분산/자기공분산이 시간에 무관")
    print("비정상 → 차분 / 로그 / 계절차분으로 정상화 후 모델링")
    print()


def lesson4_acf_pacf():
    # =========================================================================
    #
    #   레슨 4 — ACF / PACF
    #
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 4 : ACF / PACF                 │")
    print("└──────────────────────────────────────┘")
    print()
    # ■ ACF (자기상관함수, AutoCorrelation Function)
    #   - 시차 k 만큼 떨어진 두 시점의 상관계수
    #   - 정의:  ρ(k) = Cov(Y_t, Y_{t-k}) / Var(Y_t)
    #
    # ■ PACF (부분자기상관함수, Partial ACF)
    #   - 시차 1~k-1 의 영향을 제거하고, 순수하게 t와 t-k 의 상관만 남긴 것
    #
    # ■ 직관:
    #   ACF  = “과거가 지금까지 끌고 들어오는 ‘총’ 영향”
    #   PACF = “정확히 k 시점 과거만의 ‘직접’ 영향”
    #
    # ■ 사용 예 (이후 04단계 ARIMA 차수 결정에서 핵심):
    #   - ACF가 천천히 감소하고 PACF가 p시차에서 끊김 → AR(p) 적합
    #   - ACF가 q시차에서 끊기고 PACF가 천천히 감소 → MA(q) 적합

    # 간단한 수기 ACF 계산
    y = [2, 4, 6, 8, 10, 12, 11, 9, 7, 5, 3, 1]
    n = len(y)
    mean = sum(y) / n
    denom = sum((v - mean) ** 2 for v in y)

    print("lag |  ACF")
    for k in range(0, 6):
        num = sum((y[t] - mean) * (y[t - k] - mean) for t in range(k, n))
        acf = num / denom if denom else 0.0
        bar = "█" * int(abs(acf) * 30)
        sign = "+" if acf >= 0 else "-"
        print(f"{k:>3} | {sign}{abs(acf):.3f}  {bar}")
    print()


