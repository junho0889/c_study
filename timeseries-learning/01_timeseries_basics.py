    print("└──────────────────────────────────────┘")
    print()
    # ■ 1) 미래 누설(Data Leakage)
    #    - 미래 시점 정보를 피처로 넣음. 예: rolling 평균을 전체 구간으로 계산 후 train/test 분리
    #    - 반드시 "그 시점까지의 데이터"만으로 피처를 만들 것.
    #
    # ■ 2) 시간대(TimeZone) / 일광절약시간(DST)
    #    - 서버 로그 UTC vs 매장 매출 KST 혼합 → 1~2시간씩 어긋나서 패턴이 깨짐.
    #
    # ■ 3) 결측치
    #    - 그냥 dropna 하면 시간 간격이 깨짐.
    #    - 시계열 결측은 보통 forward-fill / 선형 보간 / 모델 기반 보간.
    #
    # ■ 4) 비등간격(irregular sampling)
    #    - 센서 데이터가 항상 정확히 1초 간격이 아닐 수 있음.
    #    - resample("1S").mean() 같은 균등화 작업이 선행되어야 함.
    #
    # ■ 5) 시간 순서로 split 하지 않음
    #    - sklearn 의 random split → 시계열에서는 “재앙”.
    #    - 항상 시간 기준 분할 + walk-forward CV 사용.
