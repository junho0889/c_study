def lesson2_differencing():
    # =========================================================================
    #   레슨 2 — 차분의 종류
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 2 : 차분                       │")
    print("└──────────────────────────────────────┘")
    # ■ 1차 차분:    ΔY_t = Y_t − Y_{t-1}
    # ■ 2차 차분:    Δ²Y_t = ΔY_t − ΔY_{t-1}
    # ■ 계절 차분:   Δ_s Y_t = Y_t − Y_{t-s}     (예: 월간 데이터에서 s=12)
    # ■ ARIMA(p,d,q) 의 d 가 “몇 번 차분할지”

    y = [100, 105, 112, 120, 131, 140, 152, 165, 179, 190]
    d1 = [y[t] - y[t - 1] for t in range(1, len(y))]
    d2 = [d1[t] - d1[t - 1] for t in range(1, len(d1))]
    print(" Y    :", y)
    print(" ΔY   :", d1)
    print(" Δ²Y  :", d2)
    print()
    # ■ 직관:
    #   - Y 는 우상향(비정상)
    #   - ΔY 는 거의 일정 → 정상 가능성
    #   - Δ²Y 는 0 근방으로 더 평탄해짐 → 과도한 차분(over-differencing)


def lesson3_variance_transform():
    # =========================================================================
    #   레슨 3 — 분산 안정화 변환
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 3 : 분산 안정화                │")
    print("└──────────────────────────────────────┘")
    # ■ 시간이 흐를수록 변동폭이 커지는 시계열(흔히 매출/주가)
    #   - 로그:           Y' = log(Y)            (Y > 0)
    #   - 제곱근:         Y' = sqrt(Y)
    #   - Box-Cox(λ):     Y' = (Y^λ - 1) / λ  (λ=0 이면 log)
    #
    # ■ 효과:
    #   - 큰 값의 영향을 압축, 작은 값을 상대적으로 확대
    #   - “승법 시계열 → 가법 시계열” 변환
    raw = [10, 12, 15, 21, 30, 45, 70, 110, 170]
    logd = [math.log(v) for v in raw]
    print(" Raw       :", [round(v, 2) for v in raw])
    print(" log(Y)    :", [round(v, 3) for v in logd])
    print(f" raw var   = {variance(raw):.2f}")
    print(f" log var   = {variance(logd):.4f}")
    print()


def lesson4_adf_kpss():
    # =========================================================================
    #   레슨 4 — ADF / KPSS
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 4 : ADF / KPSS                 │")
    print("└──────────────────────────────────────┘")
    # ■ ADF (Augmented Dickey-Fuller)
    #   - H0: 단위근이 있다 (= 비정상)
    #   - H1: 단위근 없음 (= 정상)
    #   - p-value < 0.05  →  H0 기각 → 정상으로 본다
    #
    # ■ KPSS (Kwiatkowski-Phillips-Schmidt-Shin)
    #   - H0: 정상이다
    #   - H1: 비정상
    #   - 가설이 정반대!
    #
    # ■ 둘 다 보는 이유 — 4가지 조합:
    #   ADF stationary  +  KPSS stationary       → 정상
    #   ADF unit-root   +  KPSS non-stationary   → 비정상
    #   ADF stationary  +  KPSS non-stationary   → 트렌드 정상 (trend-stationary)
    #   ADF unit-root   +  KPSS stationary       → 정상이긴 한데 ARIMA 가 더 필요할 수도
    #
    # ■ 코드 (statsmodels):
    #     from statsmodels.tsa.stattools import adfuller, kpss
    #     adfuller(series)[1]  # p-value
    #     kpss(series)[1]
    print(" ADF.H0=비정상, KPSS.H0=정상.  두 검정의 가설이 정반대임을 꼭 기억!")
    print()


def lesson5_white_noise_random_walk():
    # =========================================================================
    #   레슨 5 — White Noise & Random Walk
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 5 : White Noise / Random Walk │")
    print("└──────────────────────────────────────┘")
    # ■ White Noise:  Y_t = ε_t,  ε_t ~ N(0, σ²) i.i.d.
    #   - 평균/분산 일정, 자기상관 모두 0
    #   - “예측 불가의 기준선”. ML 모델이 white noise 이상을 만들어내지 못하면 무의미.
    #
    # ■ Random Walk:  Y_t = Y_{t-1} + ε_t
    #   - 1차 차분 시 white noise
    #   - 주가가 보통 이 모델로 근사됨 → “주가 직접 예측은 어렵고, 수익률(차분) 만이 예측 가능”
    random.seed(7)
    wn = [random.gauss(0, 1) for _ in range(10)]
    rw = [0.0]
    for _ in range(9):
        rw.append(rw[-1] + random.gauss(0, 1))
    print(" White Noise :", [round(v, 2) for v in wn])
    print(" Random Walk :", [round(v, 2) for v in rw])
    print()


