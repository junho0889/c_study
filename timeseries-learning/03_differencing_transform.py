def lesson7_practice():
    # =========================================================================
    #   레슨 7 — 실전: 비정상 → 정상화
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 7 : 정상화 실습                │")
    print("└──────────────────────────────────────┘")
    random.seed(3)
    # 가짜 비정상 시리즈: 트렌드 + 분산 증가 + 잡음
    Y = []
    for t in range(40):
        y = 50 * math.exp(0.03 * t)                  # 분산이 점점 커지는 우상향
        y += random.gauss(0, 1 + 0.1 * t)             # 시간에 따라 잡음 분산 증가
        Y.append(y)

    # Step1: 로그 변환
    Z = [math.log(v) for v in Y]
    # Step2: 1차 차분
    dZ = [Z[t] - Z[t - 1] for t in range(1, len(Z))]

    print(f" 원본 Y      var = {variance(Y):.2f}")
    print(f" log Y       var = {variance(Z):.4f}")
    print(f" diff(log Y) var = {variance(dZ):.4f}  ← 평균 0 근처, 분산 안정")
    print()
    print(" 정상화 파이프라인: Y → log(Y) → Δ log(Y)  ↔  이는 “로그 수익률”과 동일.")


