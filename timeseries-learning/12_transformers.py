def lesson7_practice_attention_by_hand():
    # =========================================================================
    #   레슨 7 — 4 토큰 어텐션 가중치 손계산
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 7 : 어텐션 손계산              │")
    print("└──────────────────────────────────────┘")
    # 4 토큰, 차원 2 의 Q/K
    Q = [[1.0, 0.0], [0.0, 1.0], [1.0, 1.0], [0.5, 0.5]]
    K = [[1.0, 0.0], [0.0, 1.0], [1.0, 1.0], [0.5, 0.5]]
    V = [10.0, 20.0, 30.0, 40.0]   # 1 차원 V
    d = 2

    def dot(a, b):
        return sum(x * y for x, y in zip(a, b))

    def softmax(xs):
        m = max(xs)
        e = [math.exp(x - m) for x in xs]
        s = sum(e)
        return [v / s for v in e]

    print(" 토큰별 attention 출력 (causal mask 적용):")
    for t in range(4):
        scores = []
        for u in range(4):
            if u > t:
                scores.append(-1e9)        # mask future
            else:
                scores.append(dot(Q[t], K[u]) / math.sqrt(d))
        weights = softmax(scores)
        out = sum(w * v for w, v in zip(weights, V))
        weights_str = ", ".join(f"{w:.2f}" for w in weights)
        print(f" t={t}: weights=[{weights_str}]  →  out={out:.2f}")
    print()


