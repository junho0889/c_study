import math


# ─────────────────────────────────────────────────────────────────────────
# ■ 도우미 함수
# ─────────────────────────────────────────────────────────────────────────

def tanh(x):
    """하이퍼볼릭 탄젠트: -1 ~ 1 사이 값으로 만듦"""
    return math.tanh(x)


def sigmoid(x):
    """시그모이드: 0 ~ 1 사이 값으로 만듦 (게이트 역할)"""
    if x < -500:
        return 0.0
    return 1.0 / (1.0 + math.exp(-x))


def dot_product(a, b):
    """두 리스트의 내적"""
    return sum(x * y for x, y in zip(a, b))


