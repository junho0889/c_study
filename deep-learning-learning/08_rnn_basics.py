# ─────────────────────────────────────────────────────────────────────────

def lesson4_lstm_cell():
    """
    LSTM: 세 개의 게이트로 기억을 관리하는 RNN.

    비유: 독서 노트를 체계적으로 관리하기
      - 잊기 게이트(forget gate): "이 내용은 이제 잊어도 돼"
      - 입력 게이트(input gate):  "이 새 내용은 기억해야 해"
      - 출력 게이트(output gate): "지금 필요한 기억은 이것"

    일반 RNN은 모든 걸 섞어 기억하지만,
    LSTM은 뭘 잊고 뭘 기억할지 조절할 수 있어서
    먼 과거의 정보도 필요하면 유지할 수 있습니다.
    """
    print("=" * 70)
    print("[레슨 4] LSTM 셀 구현")
    print("=" * 70)
    print()
    print("  LSTM의 세 가지 게이트:")
    print("  ┌─────────────────────────────────────────────┐")
    print("  │  잊기 게이트 (f): 이전 기억을 얼마나 유지?  │")
    print("  │  입력 게이트 (i): 새 정보를 얼마나 추가?    │")
    print("  │  출력 게이트 (o): 기억 중 뭘 내보낼?        │")
    print("  └─────────────────────────────────────────────┘")
    print()

    # 입력 크기 1, 은닉 크기 1 (이해하기 쉽게 1차원)
    # 시퀀스: 중요한 정보(5.0) → 잡음(0.1, 0.1) → 다시 필요
    sequence = [5.0, 0.1, 0.1, 0.1]

    # 단순화된 가중치
    Wf_x, Wf_h, bf = 0.5, 0.5, 0.0   # 잊기 게이트
    Wi_x, Wi_h, bi = 0.5, 0.3, 0.0   # 입력 게이트
    Wo_x, Wo_h, bo = 0.4, 0.4, 0.0   # 출력 게이트
    Wc_x, Wc_h, bc = 0.8, 0.2, 0.0   # 셀 후보

    h = 0.0  # 은닉 상태
    c = 0.0  # 셀 상태 (장기 기억)

    print("  시퀀스 처리 과정:")
    print()

    for t, x_t in enumerate(sequence):
        # 잊기 게이트: 이전 기억을 얼마나 유지?
        f = sigmoid(Wf_x * x_t + Wf_h * h + bf)

        # 입력 게이트: 새 정보를 얼마나 기억?
        i = sigmoid(Wi_x * x_t + Wi_h * h + bi)

        # 셀 후보: 새로 기억할 수 있는 내용
        c_candidate = tanh(Wc_x * x_t + Wc_h * h + bc)

        # 셀 상태 업데이트: 이전 기억 × 유지율 + 새 기억 × 추가율
        c = f * c + i * c_candidate

        # 출력 게이트: 기억 중 뭘 내보낼?
        o = sigmoid(Wo_x * x_t + Wo_h * h + bo)
        h = o * tanh(c)

        print(f"    t={t}: 입력={x_t}")
        print(f"      잊기 게이트 f = {f:.3f} (1에 가까우면 기억 유지)")
        print(f"      입력 게이트 i = {i:.3f} (1에 가까우면 새 정보 추가)")
        print(f"      셀 상태 c = {c:.3f} (장기 기억)")
        print(f"      출력 h = {h:.3f}")
        print()

    print("  → 잡음(0.1)이 들어와도 셀 상태(c)가 중요한 정보를 유지합니다!")
    print("  → 이것이 LSTM이 장기 기억을 할 수 있는 비결입니다.")
    print()


