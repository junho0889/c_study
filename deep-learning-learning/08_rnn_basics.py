# ─────────────────────────────────────────────────────────────────────────

def lesson5_gru_cell():
    """
    GRU: LSTM을 더 단순하게 만든 구조.
    게이트가 2개(리셋, 업데이트)로 줄어서 계산이 빠릅니다.

    비유: LSTM이 3개의 잠금장치가 달린 금고라면,
          GRU는 2개의 잠금장치로 비슷한 보안을 유지하는 금고.
          더 간단하지만 성능은 비슷한 경우가 많습니다.
    """
    print("=" * 70)
    print("[레슨 5] GRU (Gated Recurrent Unit)")
    print("=" * 70)
    print()
    print("  GRU의 두 가지 게이트:")
    print("    리셋 게이트 (r): 이전 기억을 얼마나 무시?")
    print("    업데이트 게이트 (z): 이전 기억 vs 새 기억 비율?")
    print()
    print("  LSTM vs GRU:")
    print("  ┌──────────┬────────────┬──────────────┬─────────────┐")
    print("  │          │ 게이트 수  │   별도 셀    │   속도      │")
    print("  ├──────────┼────────────┼──────────────┼─────────────┤")
    print("  │ LSTM     │ 3개        │   있음 (c)   │   느림      │")
    print("  │ GRU      │ 2개        │   없음       │   빠름      │")
    print("  └──────────┴────────────┴──────────────┴─────────────┘")
    print()

    # 간단한 GRU 구현
    sequence = [1.0, 0.5, 0.2, 0.8]
    Wz_x, Wz_h, bz = 0.5, 0.3, 0.0
    Wr_x, Wr_h, br = 0.4, 0.4, 0.0
    Wh_x, Wh_h, bh = 0.6, 0.3, 0.0

    h = 0.0

    for t, x_t in enumerate(sequence):
        # 업데이트 게이트
        z = sigmoid(Wz_x * x_t + Wz_h * h + bz)
        # 리셋 게이트
        r = sigmoid(Wr_x * x_t + Wr_h * h + br)
        # 후보 은닉 상태 (리셋 게이트로 이전 기억 조절)
        h_candidate = tanh(Wh_x * x_t + Wh_h * (r * h) + bh)
        # 최종 은닉 상태: 이전과 새 후보의 가중 평균
        h = (1 - z) * h + z * h_candidate

        print(f"    t={t}: 입력={x_t:.1f}")
        print(f"      업데이트 게이트 z={z:.3f}, 리셋 게이트 r={r:.3f}")
        print(f"      새 은닉 상태 h={h:.3f}")

    print()
    print("  → GRU는 LSTM보다 파라미터가 적어 빠르고, 성능은 비슷합니다.")
    print()


