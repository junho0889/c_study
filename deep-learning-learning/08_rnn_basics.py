# ■ 레슨 2: 단순 RNN 셀 구현
# ─────────────────────────────────────────────────────────────────────────

def lesson2_simple_rnn_cell():
    """
    가장 기본적인 RNN 셀:
      h_t = tanh(W_xh * x_t + W_hh * h_{t-1} + b)

    비유: 독서 노트
      - x_t = 지금 읽는 문장
      - h_{t-1} = 지금까지의 독서 노트
      - h_t = 새 문장을 읽고 업데이트한 독서 노트
    """
    print("=" * 70)
    print("[레슨 2] 단순 RNN 셀 구현")
    print("=" * 70)
    print()
    print("  공식: h_t = tanh(W_xh × x_t + W_hh × h_{t-1} + b)")
    print()

    # 입력 크기 = 2, 은닉 크기 = 3
    # 간단한 숫자 시퀀스: [1,0], [0,1], [1,1]
    sequence = [[1.0, 0.0], [0.0, 1.0], [1.0, 1.0]]
    hidden_size = 3

    # 가중치 (간단한 고정값)
    W_xh = [[0.3, 0.1, 0.4],   # 입력→은닉 (2×3)
             [0.2, 0.5, 0.1]]
    W_hh = [[0.1, 0.2, 0.0],   # 은닉→은닉 (3×3)
             [0.3, 0.1, 0.2],
             [0.0, 0.4, 0.1]]
    bias = [0.0, 0.0, 0.0]

    # 초기 은닉 상태는 0
    h = [0.0, 0.0, 0.0]

    print("  시퀀스를 한 단계씩 처리:")
    print()

    for t, x_t in enumerate(sequence):
        # W_xh * x_t 계산
        wx = [0.0] * hidden_size
        for j in range(hidden_size):
            for i in range(len(x_t)):
                wx[j] += x_t[i] * W_xh[i][j]

        # W_hh * h 계산
        wh = [0.0] * hidden_size
        for j in range(hidden_size):
            for i in range(hidden_size):
                wh[j] += h[i] * W_hh[i][j]

        # h_new = tanh(wx + wh + bias)
        h_new = [0.0] * hidden_size
        for j in range(hidden_size):
            h_new[j] = tanh(wx[j] + wh[j] + bias[j])

        print(f"    시간 t={t}: 입력 x={x_t}")
        print(f"      W_xh×x = [{', '.join(f'{v:.3f}' for v in wx)}]")
        print(f"      W_hh×h = [{', '.join(f'{v:.3f}' for v in wh)}]")
        print(f"      새 은닉 상태 h = [{', '.join(f'{v:.3f}' for v in h_new)}]")
        print()

        h = h_new

    print("  → 각 단계마다 이전 은닉 상태(h)가 다음 계산에 영향을 줍니다!")
    print("  → 이것이 '기억'의 핵심 원리입니다.")
    print()


