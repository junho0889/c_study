def lesson3_vanishing_gradient_rnn():
    """
    RNN에서 시퀀스가 길어지면 먼 과거의 기억이 사라집니다.

    비유: 전화 게임(귓속말 전달)
      - 10명이 한 줄로 서서 메시지를 전달하면
        마지막 사람은 원래 메시지를 거의 기억 못 함
      - RNN도 마찬가지: 100단계 전의 정보는 거의 사라짐
    """
    print("=" * 70)
    print("[레슨 3] RNN의 기울기 소실 문제")
    print("=" * 70)
    print()
    print("  tanh 미분값은 최대 1.0이고 보통 1보다 작음")
    print("  이걸 여러 번 곱하면 기울기가 급격히 줄어듦")
    print()

    # tanh 미분을 반복 곱하기
    grad = 1.0
    typical_tanh_deriv = 0.5  # 일반적인 tanh 미분값

    print("  단계별 기울기 크기 (tanh 미분 ~= 0.5 가정):")
    print("  ┌──────────┬────────────────┬─────────────────────┐")
    print("  │  단계    │   기울기       │   막대              │")
    print("  ├──────────┼────────────────┼─────────────────────┤")

    for step in range(15):
        bar = "#" * max(1, int(grad * 50))
        print(f"  │  {step+1:>4}    │ {grad:>14.8f} │ {bar:<19} │")
        grad *= typical_tanh_deriv

    print("  └──────────┴────────────────┴─────────────────────┘")
    print()
    print("  → 15단계 후 기울기가 거의 0!")
    print("  → 해결책: LSTM, GRU 같은 게이트 구조 사용")
    print()


