def lesson5_retry():
    # =========================================================================
    #   레슨 5 — 재시도 정책
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 5 : 재시도                     │")
    print("└──────────────────────────────────────┘")
    # ■ 지수 백오프(Exponential backoff): 1s → 2s → 4s → 8s …
    # ■ Jitter: 동시 재시도 폭주 방지 → 랜덤 ±20%
    # ■ Circuit breaker: 일정 실패율 넘으면 ‘일정 시간 호출 중단’
    # ■ Dead Letter Queue(DLQ): 끝까지 실패한 메시지를 별도 저장 → 사람 검토
    #
    # ■ 멱등성과의 관계:
    #   - 재시도는 ‘같은 작업의 반복’ → 멱등하지 않으면 사고가 N 배 커진다.
    print(" 재시도 + 멱등 + DLQ 가 견고한 ETL 의 3종 세트.")
    print()


