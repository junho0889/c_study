def lesson7_practice_upsert_in_memory():
    # =========================================================================
    #   레슨 7 — 인메모리 UPSERT 시뮬레이션
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 7 : 인메모리 UPSERT            │")
    print("└──────────────────────────────────────┘")
    # 가짜 ‘DW 테이블’: dict
    target = {}

    def naive_insert(row):
        # 멱등성 X — 같은 id 가 와도 append 식 추가
        key = (row["id"], "v" + str(len(target)))
        target[key] = row

    def upsert(row):
        target[row["id"]] = row     # 덮어쓰기 → 멱등 OK

    src = [
        {"id": 1, "amt": 100},
        {"id": 2, "amt": 200},
        {"id": 1, "amt": 150},      # 같은 id, 업데이트
        {"id": 3, "amt": 300},
    ]

    print(" --- 잘못된 ETL: naive insert ---")
    naive_target = {}
    for r in src:
        naive_target[len(naive_target)] = r
        # 재실행 흉내
        naive_target[len(naive_target)] = r
    print(f"   행 수: {len(naive_target)}  (중복!)")

    print(" --- 옳은 ETL: upsert ---")
    target = {}
    for _retry in range(3):       # 재시도 3 회 흉내
        for r in src:
            upsert(r)
    print(f"   행 수: {len(target)}  (3 retries 후에도 정확)")
    for k, v in target.items():
        print("    ", v)
    print()


