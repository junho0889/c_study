def lesson3_upsert():
    # =========================================================================
    #   레슨 3 — UPSERT / MERGE
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 3 : UPSERT / MERGE             │")
    print("└──────────────────────────────────────┘")
    # ■ PostgreSQL:
    #     INSERT INTO sales(id, amt) VALUES (?, ?)
    #     ON CONFLICT (id) DO UPDATE SET amt = EXCLUDED.amt;
    #
    # ■ Snowflake/BigQuery:
    #     MERGE INTO target T USING src S ON T.id = S.id
    #     WHEN MATCHED THEN UPDATE SET T.amt = S.amt
    #     WHEN NOT MATCHED THEN INSERT (id, amt) VALUES (S.id, S.amt);
    #
    # ■ DataFrame 적재(스파크/dbt incremental):
    #     unique_key = "id"
    #     materialized = "incremental"
    print(" UPSERT = PK 가 분명할 때.  PK 가 없는 데이터는 dedup 후 적재.")
    print()


def lesson4_incremental():
    # =========================================================================
    #   레슨 4 — Incremental load
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 4 : 증분 적재                  │")
    print("└──────────────────────────────────────┘")
    # ■ High-watermark 방식:
    #   - 매 회차마다 “마지막으로 본 updated_at” 을 저장
    #   - 다음 회차: WHERE updated_at > :last_seen
    #
    # ■ CDC 방식 (07단계):
    #   - 로그 기반 → 더 신뢰성/저지연
    #
    # ■ 시간 기준의 함정:
    #   - 소스 DB 의 시스템 시간 ≠ 우리 ETL 시간 (시간대/지연)
    #   - 동시에 들어온 행이 한쪽만 잡혀 누락 가능 → ‘안전 마진’ 5분
    #   - WHERE updated_at >= :last_seen - 5min  + dedup
    print(" 증분 = ‘마지막 본 시간’ 의 정확한 저장 + 안전 마진 + 멱등 적재.")
