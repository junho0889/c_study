def lesson2_etl_vs_elt():
    # =========================================================================
    #   레슨 2 — ETL vs ELT
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 2 : ETL vs ELT                 │")
    print("└──────────────────────────────────────┘")
    # ■ ETL(Extract → Transform → Load):
    #   - 외부에서 변환 후 DW 에 적재
    #   - 자원이 비싼 DW 시대 (Oracle/Teradata) 의 표준
    #   - 변환 로직이 ‘파이프라인’에 집중
    #
    # ■ ELT(Extract → Load → Transform):
    #   - 일단 DW/Lake 에 ‘원본 가깝게’ 적재 후, SQL/Spark 로 변환
    #   - BigQuery/Snowflake/Databricks 시대의 표준
    #   - 변환 로직이 ‘DW 안 SQL/dbt’ 에 집중
    #
    #   ETL : src → [transform] → DW
    #   ELT : src → DW(raw) → [transform in DW] → DW(mart)
    print(" 현대 클라우드 DW = ELT 가 기본.  ETL 은 ‘민감정보 가공/필터’ 처럼 외부에서 처리해야 할 때 사용.")
    print()


def lesson3_batch_vs_stream():
    # =========================================================================
    #   레슨 3 — 배치 vs 스트림
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 3 : 배치 vs 스트림             │")
    print("└──────────────────────────────────────┘")
    # ■ Batch:
    #   - 시간(매일/매시) 단위 묶음 처리
    #   - 도구: Airflow + Spark/SQL
    #   - 장점: 단순, 디버깅 쉬움
    #   - 단점: latency 큼
    #
    # ■ Streaming:
    #   - 이벤트가 들어오는 순간 처리
    #   - 도구: Kafka + Flink/Spark Structured Streaming, Kafka Streams
    #   - 장점: 실시간 알림/추천/이상탐지
    #   - 단점: 운영 난이도↑, exactly-once 보장 어려움
    #
    # ■ 하이브리드 (Lambda / Kappa):
    #   - Lambda: 배치(정확) + 스트림(빠름) 두 길
    #   - Kappa : 스트림 한 길로 통일 (state store + replay)
    print(" 실무 흐름: ‘배치로 시작 → 필요한 일부만 스트림으로’ 점진 진화.")
    print()


def lesson4_lake_dw_lakehouse():
    # =========================================================================
    #   레슨 4 — Lake / DW / Lakehouse
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 4 : Lake / DW / Lakehouse      │")
    print("└──────────────────────────────────────┘")
    # ■ Data Warehouse (DW):
    #   - 정형화된 스키마, SQL 강점, BI 분석 친화
    #   - Snowflake / BigQuery / Redshift
    #
    # ■ Data Lake:
    #   - 원본/세미정형/비정형 모두 저장 (S3/GCS/HDFS)
    #   - 저장 싸지만 ‘바로 쓰기’는 어려움
    #
    # ■ Lakehouse:
    #   - Lake 위에 ACID 트랜잭션/스키마/시간여행
    #   - Delta Lake / Apache Iceberg / Hudi
    #   - “원본은 Lake, 분석은 DW 처럼” 한 시스템에서.
    print(" Lakehouse = Lake 의 비용 효율 + DW 의 신뢰성을 결합한 현대 아키텍처.")
    print()


def lesson5_data_mesh():
    # =========================================================================
    #   레슨 5 — Data Mesh
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 5 : Data Mesh                  │")
    print("└──────────────────────────────────────┘")
    # ■ 핵심 4 원칙:
    #   1) Domain ownership   : 도메인 팀이 데이터의 ‘제품’ 책임
    #   2) Data as a Product  : 데이터셋도 SLA / 카탈로그 / 문서를 갖춤
    #   3) Self-serve infra   : 도메인 팀이 직접 파이프라인을 만들 수 있는 플랫폼
    #   4) Federated governance: 중앙 거버넌스 + 도메인 자율
    #
    # ■ 적용 조건:
    #   - 회사 규모가 클수록 효과↑
    #   - 작은 조직은 ‘중앙 데이터팀’ 모델이 더 효율적일 수 있음
    print(" Data Mesh 는 ‘조직 구조’ 가 핵심.  기술만 도입해선 절대 동작하지 않는다.")
    print()


def lesson6_anti_patterns():
    # =========================================================================
    #   레슨 6 — 안티패턴
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 6 : 안티패턴                   │")
    print("└──────────────────────────────────────┘")
    # ■ 1) “모든 변환을 BI 툴 안에서” — 한 사람만 알고, 재사용 0
    # ■ 2) “DW 안 raw 테이블에 갑자기 ALTER” — 다운스트림 박살
    # ■ 3) 멱등성 없는 ETL — 재실행할 때마다 중복 적재
    # ■ 4) 스키마 없는 JSON 호수 — 시간 지나면 ‘아무도 모르는 데이터’
    # ■ 5) “스트림으로 다 바꾸자” — 작은 회사가 운영 부하로 무너짐
    print(" 안티패턴 회피 = 멱등성, 스키마 계약, 점진 진화, 문서화.")
    print()


