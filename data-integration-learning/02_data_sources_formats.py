def lesson3_formats():
    # =========================================================================
    #   레슨 3 — 포맷 비교
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 3 : 포맷 비교                  │")
    print("└──────────────────────────────────────┘")
    # ┌─────────┬───────┬───────┬───────┬─────────┬───────┐
    # │ 포맷    │ 행/열 │ 스키마 │ 압축 │ 분석속도 │ 진화 │
    # ├─────────┼───────┼───────┼───────┼─────────┼───────┤
    # │ CSV     │ 행     │ 없음   │ 약   │ 느림    │ 깨짐 │
    # │ JSON    │ 행     │ 유연   │ 약   │ 느림    │ 강함 │
    # │ Avro    │ 행     │ 강력   │ 강   │ 보통    │ 강력 │
    # │ Parquet │ 열     │ 강력   │ 강   │ 빠름    │ 보통 │
    # │ ORC     │ 열     │ 강력   │ 강   │ 빠름    │ 보통 │
    # └─────────┴───────┴───────┴───────┴─────────┴───────┘
    #
    # ■ 권장:
    #   - 데이터 호수 저장 = Parquet 또는 Delta/Iceberg
    #   - 스트림 직렬화 = Avro + Schema Registry
    #   - 사람 교환 = JSON / CSV
    print(" 분석은 Parquet, 스트림은 Avro, 디버깅 / 교환은 JSON. 흔한 매핑.")
    print()


def lesson4_why_columnar():
    # =========================================================================
    #   레슨 4 — 컬럼형이 분석에 강한 이유
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 4 : 컬럼형                     │")
    print("└──────────────────────────────────────┘")
    # ■ 행 기반:  Row1[a,b,c,d], Row2[a,b,c,d], …
    # ■ 컬럼 기반: ColA[a1,a2,…], ColB[b1,b2,…], ColC, ColD
    #
    # ■ 분석 쿼리 SELECT AVG(d) FROM t 의 경우:
    #   - 행 기반: 모든 컬럼 디스크에서 읽고 d 만 사용 → 4 배 낭비
    #   - 열 기반: d 컬럼만 읽음 → I/O 1/4
    #
    # ■ 추가 이점:
    #   - 같은 컬럼 = 비슷한 값 → 압축률 ↑ (RLE/Dictionary)
    #   - 통계(min/max) 메타데이터로 ‘pruning’ 가능
    print(" 분석 워크로드 = ‘일부 컬럼 + 많은 행’.  컬럼 포맷이 거의 항상 이긴다.")
    print()


def lesson5_schema_evolution():
    # =========================================================================
    #   레슨 5 — 스키마 진화 호환성
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 5 : 스키마 진화                │")
    print("└──────────────────────────────────────┘")
    # ■ Schema Registry 의 4 호환성 모드:
    #   1) BACKWARD     : 새 reader 가 ‘옛 데이터’ 를 읽을 수 있음
    #   2) FORWARD      : 옛 reader 가 ‘새 데이터’ 를 읽을 수 있음
    #   3) FULL         : 양방향 모두 가능
    #   4) NONE         : 호환성 미보장 (위험)
    #
    # ■ 안전한 변경:
    #   - 필드 추가: 기본값(default) 동반 → BACKWARD/FORWARD 보존
    #   - 필드 제거: 신중 — 옛 reader 가 못 찾으면 NPE
    #   - 타입 변경: int→long 같은 ‘widening’ 만 안전
    #
    # ■ 권고: 운영 토픽은 BACKWARD 또는 FULL 로 잠그기.
    print(" 스키마 진화는 ‘추가는 쉽고, 제거/변경은 비싸다’.")
    print()


def lesson6_partition_compress():
    # =========================================================================
    #   레슨 6 — 파티셔닝 / 압축 / 버킷팅
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 6 : 파티셔닝 / 압축 / 버킷팅   │")
    print("└──────────────────────────────────────┘")
    # ■ 파티셔닝:
    #   - dt=2026-05-13/  처럼 디렉터리로 시간/지역 분할
    #   - 쿼리에서 WHERE dt='...' 만 읽으면 됨 → 비용/속도 ↓
    # ■ 버킷팅:
    #   - 해시로 N 개 파일에 분산 → 조인 키 정렬에 유리
    # ■ 압축:
    #   - Snappy(빠름), Gzip(작음), Zstandard(균형)
    #
    # ■ 흔한 함정:
    #   - 파티션 너무 잘게 자르면 small-file 문제 → metastore 폭발
    print(" 파티션 = ‘비용/속도의 가장 효과적인 단일 결정’. 너무 잘지도, 너무 굵지도 않게.")
    print()


def lesson7_practice_csv_to_parquet():
    # =========================================================================
    #   레슨 7 — CSV → Parquet 효과 추정
    # =========================================================================
    print("┌──────────────────────────────────────┐")
    print("│  레슨 7 : CSV → Parquet 효과         │")
    print("└──────────────────────────────────────┘")
    # 시뮬레이션 — 실제 라이브러리 없이 ‘기대 효과’를 추산
    rows = 5_000_000
    cols = 20
    csv_bytes_per_cell = 8           # 문자열 평균 8 byte
    parquet_bytes_per_cell = 1.5     # 컬럼 압축 효과

    csv_mb = rows * cols * csv_bytes_per_cell / 1024 / 1024
    pq_mb = rows * cols * parquet_bytes_per_cell / 1024 / 1024

    print(f" CSV    예상 크기 ≈ {csv_mb:>8,.1f} MB")
    print(f" Parquet 예상 크기 ≈ {pq_mb:>8,.1f} MB")
    print(f" 절감률 ≈ {(1 - pq_mb / csv_mb) * 100:.1f}%")
    print()
    # 쿼리 비용도 분석 시 4~10 배 빨라지는 것이 일반적.

    # JSON 예시 한 줄
    record = {"user_id": 42, "event": "purchase", "ts": "2026-05-13T10:30:00Z", "amount": 9.99}
    print(" JSON 라인 예:", json.dumps(record, ensure_ascii=False))


