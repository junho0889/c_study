// 두 수 중 최솟값과 최댓값을 튜플로 반환하는 함수
// -> (i32, i32) : i32 두 개를 묶은 튜플을 반환한다는 뜻
fn 최솟값_최댓값(a: i32, b: i32) -> (i32, i32) {
    if a < b {
        (a, b)  // 세미콜론 없으면 이 값이 반환돼요!
    } else {
        (b, a)
    }
}
