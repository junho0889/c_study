// ─────────────────────────────────────────────────────────────────────────
// ■ Rust가 뭐야? 왜 배워야 해?
// ─────────────────────────────────────────────────────────────────────────
//
//   Rust는 2015년에 나온 프로그래밍 언어예요.
//
//   비유: 레고 블록
//     - C/C++ = 아주 빠르지만 위험한 레고 (날카로운 모서리가 있어요)
//     - Python = 느리지만 안전한 레고 (폼 블록이에요)
//     - Rust  = 빠르면서도 안전한 레고! (최신 안전 레고!)
//
//   Rust의 특징:
//   1. 빠르다! (C/C++만큼 빠른 속도)
//   2. 안전하다! (메모리 오류를 컴파일할 때 미리 잡아줘요)
//   3. 병렬 처리가 쉽다! (여러 작업을 동시에 해도 안전해요)
//
//   어디서 쓰이나?
//   - 운영체제 (Windows, Linux 일부)
//   - 웹 브라우저 (Firefox의 일부)
//   - 게임 엔진
//   - 로켓, 자동차, 드론 소프트웨어
//   - 블록체인
//
// ─────────────────────────────────────────────────────────────────────────

// ─────────────────────────────────────────────────────────────────────────
// ■ fn main() - 프로그램의 시작점
// ─────────────────────────────────────────────────────────────────────────
//
//   비유: 학교 운동회
//     - fn main()은 "운동회 시작!" 신호예요
//     - 모든 Rust 프로그램은 반드시 fn main()에서 시작해요
//     - main이 끝나면 프로그램도 끝나요
//
//   fn = function(함수)의 줄임말
//   main = 프로그램의 첫 번째로 실행되는 특별한 이름
//   () = 이 함수는 입력값이 없어요
//   { } = 실행할 코드들이 들어가는 공간
//
fn main() {
    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 1. println! 매크로 - 화면에 글자 출력하기                          │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   println! 은 함수가 아니라 "매크로"예요!
    //   매크로 = 마법 주문 같은 것 (!)로 끝나는 게 매크로예요
    //
    //   비유: 마이크
    //     - println!은 마이크로 소리를 내는 것처럼 화면에 글자를 보여줘요
    //     - print!는 줄바꿈 없이 출력해요
    //     - println!은 출력하고 줄을 바꿔줘요
    //
    println!("안녕하세요! Rust 세계에 오신 걸 환영해요! 🦀");
    println!("제 이름은 Rust예요. 빠르고 안전한 언어랍니다!");

    // 빈 줄 출력 (줄바꿈만)
    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 2. 변수 (Variables) - 정보를 담는 상자                             │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   비유: 학교 사물함
    //     - 변수 = 이름이 붙은 사물함
    //     - let = 사물함을 만드는 열쇠
    //     - 사물함에 물건(값)을 넣어요
    //
    //   Rust의 중요한 규칙:
    //   → 변수는 기본적으로 "불변(immutable)"이에요!
    //   → 즉, 한 번 값을 넣으면 바꿀 수 없어요
    //   → 이건 실수로 값을 바꾸는 버그를 막아줘요!
    //
    println!("=== 변수(Variables) 배우기 ===");

    // let으로 변수 만들기
    // 타입을 직접 안 써도 Rust가 자동으로 알아내요 (타입 추론!)
    let 나이 = 10;              // 정수형 (i32로 자동 추론)
    let 이름 = "철수";          // 문자열 슬라이스 (&str로 자동 추론)
    let 키 = 145.5;             // 실수형 (f64로 자동 추론)
    let 학생인가요 = true;       // 논리형 (bool로 자동 추론)

    println!("이름: {}", 이름);
    println!("나이: {}살", 나이);
    println!("키: {}cm", 키);
    println!("학생 여부: {}", 학생인가요);

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 3. 가변성(Mutability) - 변경 가능한 변수                           │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   비유: 잠금 사물함 vs 일반 사물함
    //     - let 변수 = 자물쇠가 잠긴 사물함 (값 변경 불가)
    //     - let mut 변수 = 자물쇠 없는 사물함 (값 변경 가능)
    //
    //   왜 기본이 불변일까요?
    //   → 실수로 값을 바꾸는 버그를 미리 막기 위해서예요!
    //   → 값이 바뀌는 게 필요할 때만 mut을 붙여요
    //
    println!("=== 가변성(Mutability) 배우기 ===");

    // mut을 붙이면 값을 나중에 바꿀 수 있어요
    let mut 점수 = 0;
    println!("처음 점수: {}", 점수);

    점수 = 100;  // mut이 있으니까 값을 바꿀 수 있어요!
    println!("수학 100점 맞은 후 점수: {}", 점수);

    점수 = 점수 + 50;  // 기존 값에 더하기
    println!("보너스 점수 50점 추가 후: {}", 점수);

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 4. 데이터 타입 (Data Types) - 변수의 종류                          │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   비유: 학교 물건들
    //     - 연필 통 = 정수 (개수를 세는 것들)
    //     - 자 = 실수 (소수점이 있는 길이)
    //     - 스위치 = 논리형 (켜짐/꺼짐, true/false)
    //     - 이름표 = 문자/문자열
    //
    println!("=== 데이터 타입 (Data Types) 배우기 ===");

    // ── 정수형 (Integer) ──────────────────────────────────────────────────
    // i = 부호 있는 정수 (음수도 됨), u = 부호 없는 정수 (양수만)
    // 숫자 = 저장 공간 크기 (8, 16, 32, 64, 128비트)
    let 작은수: i8 = 127;           // -128 ~ 127
    let 중간수: i32 = 1_000_000;    // 약 ±21억 (숫자에 _ 를 구분자로 써도 됨!)
    let 큰수: i64 = 9_000_000_000;  // 엄청 큰 수
    let 양수만: u32 = 4_294_967_295; // 0 ~ 약 43억 (음수 없음)

    println!("i8 최대값: {}", 작은수);
    println!("백만: {}", 중간수);
    println!("구십억: {}", 큰수);
    println!("u32 최대값: {}", 양수만);

    // ── 실수형 (Float) ────────────────────────────────────────────────────
    // f32 = 소수점 7자리까지, f64 = 소수점 15자리까지 (기본값)
    let 원주율: f64 = 3.14159265358979;
    let 온도: f32 = 36.5;

    println!("원주율: {}", 원주율);
    println!("체온: {}도", 온도);

    // ── 논리형 (Boolean) ──────────────────────────────────────────────────
    // true(참) 또는 false(거짓) 딱 두 가지 값만 가져요
    let 비가오나요: bool = false;
    let 숙제했나요: bool = true;

    println!("비가 오나요? {}", 비가오나요);
    println!("숙제 했나요? {}", 숙제했나요);

    // ── 문자형 (Character) ────────────────────────────────────────────────
    // 문자 하나를 저장해요. 작은따옴표('')를 사용해요
    // Rust의 char는 유니코드를 지원해서 한글, 이모지도 저장 가능해요!
    let 첫글자: char = '가';
    let 이모지: char = '🦀';
    let 영문자: char = 'A';

    println!("첫 글자: {}", 첫글자);
    println!("러스트 마스코트: {}", 이모지);
    println!("영문자: {}", 영문자);

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 5. 문자열 (String) - String vs &str                                │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   Rust에는 문자열이 두 종류 있어요. 헷갈리지 마세요!
    //
    //   비유: 메모장 vs 칠판
    //     - &str = 칠판에 새긴 글씨 (바꿀 수 없음, 프로그램 코드 안에 고정)
    //     - String = 메모장 (지우고 다시 쓸 수 있음, 실행 중에 만들어짐)
    //
    //   &str (string slice, 문자열 슬라이스):
    //   - 프로그램 코드 안에 직접 쓴 문자열
    //   - 크기가 고정되어 있어요
    //   - 변경 불가능해요
    //
    //   String:
    //   - 실행 중에 만들어지는 문자열
    //   - 크기를 늘리거나 줄일 수 있어요
    //   - 변경 가능해요
    //
    println!("=== 문자열(String) 배우기 ===");

    // &str - 문자열 슬라이스 (코드에 고정된 문자열)
    let 고정_인사: &str = "안녕하세요!";
    println!("고정 문자열: {}", 고정_인사);

    // String - 동적 문자열 (실행 중에 만들어지는 문자열)
    let mut 동적_문장 = String::from("안녕");
    동적_문장.push_str(", 세상아!"); // 문자열 뒤에 덧붙이기
    동적_문장.push('!');             // 문자 하나 추가
    println!("동적 문자열: {}", 동적_문장);

    // 문자열 연결하기
    let 성 = String::from("김");
    let 이름2 = String::from("철수");
    // + 연산자 사용 (성의 소유권을 넘겨줘요 - 나중에 소유권 단계에서 배워요!)
    let 전체이름 = 성 + &이름2;  // & 는 "빌려온다"는 뜻이에요
    println!("전체 이름: {}", 전체이름);

    // format! 매크로로 문자열 만들기 (소유권 문제 없음!)
    let 학교 = String::from("행복초등학교");
    let 학년 = 5;
    let 자기소개 = format!("저는 {} {}학년이에요!", 학교, 학년);
    println!("{}", 자기소개);

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 6. 타입 추론 (Type Inference) - Rust가 알아서 타입을 파악해요!     │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   비유: 선생님이 답 맞히기
    //     - "사과 3개" → 선생님이 "아, 숫자구나!" 라고 알아챠는 것처럼
    //     - Rust 컴파일러가 값을 보고 타입을 자동으로 알아내요
    //
    println!("=== 타입 추론 (Type Inference) ===");

    let 자동정수 = 42;         // Rust가 i32라고 알아내요
    let 자동실수 = 3.14;       // Rust가 f64라고 알아내요
    let 자동논리 = true;       // Rust가 bool이라고 알아내요
    let 자동문자열 = "hello";  // Rust가 &str이라고 알아내요

    // 타입을 명시적으로 쓸 수도 있어요
    let 명시정수: i32 = 42;
    let 명시실수: f64 = 3.14;

    println!("자동추론 정수: {}", 자동정수);
    println!("자동추론 실수: {}", 자동실수);
    println!("자동추론 논리: {}", 자동논리);
    println!("자동추론 문자열: {}", 자동문자열);
    println!("명시적 정수: {}", 명시정수);
    println!("명시적 실수: {}", 명시실수);

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 7. 상수 (Constants) - 절대 바뀌지 않는 값                          │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   비유: 학교 규칙
    //     - 변수 = 그날 날씨 (매일 바뀔 수 있어요)
    //     - 상수 = 학교 규칙 (절대 안 바뀌어요)
    //
    //   상수의 특징:
    //   1. const 키워드 사용
    //   2. 타입을 반드시 명시해야 해요
    //   3. 대문자와 밑줄(_)로 이름을 지어요 (관례)
    //   4. 함수 안이나 밖 어디서든 선언 가능
    //   5. 절대 mut 사용 불가!
    //
    println!("=== 상수 (Constants) ===");

    const 최대_점수: u32 = 100;
    const 학교_이름: &str = "행복초등학교";
    const PI: f64 = 3.14159265358979323846;

    println!("최대 점수: {}", 최대_점수);
    println!("학교 이름: {}", 학교_이름);
    println!("파이(π): {}", PI);

    // 상수를 이용한 계산
    let 반지름 = 5.0_f64;
    let 원의_넓이 = PI * 반지름 * 반지름;
    println!("반지름 {}인 원의 넓이: {:.2}", 반지름, 원의_넓이);
    // {:.2} = 소수점 두 번째 자리까지 출력

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 8. 섀도잉 (Shadowing) - 같은 이름으로 새 변수 만들기               │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   비유: 종이에 덮어쓰기
    //     - 기존 종이 위에 새 종이를 붙여 가리는 것처럼
    //     - 같은 이름의 변수를 다시 let으로 선언할 수 있어요
    //     - 이전 변수가 사라지는 게 아니라 "가려지는" 거예요
    //
    //   섀도잉 vs mut:
    //   - mut: 같은 타입의 값만 바꿀 수 있어요
    //   - 섀도잉: 타입도 바꿀 수 있어요! (새 변수니까요)
    //
    println!("=== 섀도잉 (Shadowing) ===");

    let x = 5;
    println!("처음 x: {}", x);

    let x = x + 1;  // 새로운 x (이전 x에 1을 더한 값)
    println!("x + 1 = {}", x);

    let x = x * 2;  // 또 새로운 x
    println!("x * 2 = {}", x);

    // 타입도 바꿀 수 있어요! (mut으로는 못 해요)
    let 공간 = "다섯 칸";           // &str 타입
    println!("공간 (문자열): {}", 공간);
    let 공간 = 5;                   // 이제 i32 타입으로 바뀌었어요
    println!("공간 (숫자): {}", 공간);

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 9. 산술 연산자 (Arithmetic Operators) - 계산하기                   │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   비유: 수학 시간
    //     - + 더하기
    //     - - 빼기
    //     - * 곱하기
    //     - / 나누기
    //     - % 나머지 (중요! 나누고 남은 것)
    //
    println!("=== 산술 연산자 ===");

    let a = 10;
    let b = 3;

    println!("{} + {} = {}", a, b, a + b);  // 덧셈: 13
    println!("{} - {} = {}", a, b, a - b);  // 뺄셈: 7
    println!("{} * {} = {}", a, b, a * b);  // 곱셈: 30
    println!("{} / {} = {}", a, b, a / b);  // 나눗셈: 3 (정수 나눗셈은 소수점 버려요!)
    println!("{} % {} = {}", a, b, a % b);  // 나머지: 1 (10 ÷ 3 = 3 나머지 1)

    // 실수 나눗셈
    let c = 10.0_f64;
    let d = 3.0_f64;
    println!("{} / {} = {:.4}", c, d, c / d);  // 3.3333...

    // 나머지 활용 예시: 짝수/홀수 구분
    let 숫자 = 7;
    if 숫자 % 2 == 0 {
        println!("{} 는 짝수예요", 숫자);
    } else {
        println!("{} 는 홀수예요", 숫자);
    }

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 10. 문자열 포매팅 (String Formatting) - 출력 형식 조절하기         │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   println!("{}", 값) 의 {} 안에 다양한 형식 지정자를 쓸 수 있어요
    //
    //   {}   = 기본 출력
    //   {:?} = 디버그 형식 출력 (개발자용, 더 자세한 정보)
    //   {:.2} = 소수점 2자리
    //   {:5} = 최소 5칸 (오른쪽 정렬)
    //   {:<5} = 최소 5칸 (왼쪽 정렬)
    //   {:0>5} = 0으로 채운 5칸
    //   {:b} = 2진수, {:o} = 8진수, {:x} = 16진수
    //
    println!("=== 문자열 포매팅 ===");

    let 값 = 42;
    let 실수값 = 3.14159;

    println!("기본 출력: {}", 값);
    println!("디버그 출력: {:?}", 값);
    println!("소수점 2자리: {:.2}", 실수값);
    println!("5칸 오른쪽 정렬: {:5}", 값);
    println!("5칸 왼쪽 정렬: {:<5}|", 값);
    println!("0으로 채우기: {:05}", 값);
    println!("2진수: {:b}", 값);
    println!("16진수: {:x}", 값);
    println!("16진수(대문자): {:X}", 값);

    // 여러 값 동시에 출력
    println!("{이름}는 {나이}살이에요!", 이름 = "영희", 나이 = 12);

    // 위치 지정
    println!("{0}는 {1}이고, {1}는 {0}의 친구예요", "철수", "영희");

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 11. 튜플 (Tuple) - 여러 값을 하나로 묶기                           │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   비유: 도시락
    //     - 도시락 = 튜플 (여러 다른 반찬을 하나에 담아요)
    //     - 밥, 김치, 계란 = 서로 다른 타입의 값들
    //
    println!("=== 튜플 (Tuple) ===");

    // 다른 타입의 값들을 묶을 수 있어요
    let 학생정보: (String, u32, f64) = (String::from("김철수"), 12, 156.5);

    // 점(.)으로 각 값에 접근해요 (0부터 시작)
    println!("이름: {}", 학생정보.0);
    println!("나이: {}", 학생정보.1);
    println!("키: {}cm", 학생정보.2);

    // 구조 분해 (destructuring) - 튜플을 여러 변수로 나눠서 받기
    let (이름3, 나이3, 키3) = 학생정보;
    println!("분해됨 - 이름: {}, 나이: {}살, 키: {}cm", 이름3, 나이3, 키3);

    // 함수가 여러 값을 반환할 때 유용해요
    let (최솟값, 최댓값) = 최솟값_최댓값(3, 7);
    println!("3과 7 중에 최솟값: {}, 최댓값: {}", 최솟값, 최댓값);

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 12. 배열 (Array) - 같은 타입의 값들을 순서대로 저장                │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   비유: 주차장
    //     - 배열 = 크기가 정해진 주차장 (공간이 미리 고정)
    //     - 각 자리(인덱스)에 같은 종류의 차(같은 타입)만 주차 가능
    //     - 인덱스는 0부터 시작해요!
    //
    //   배열 vs Vec:
    //   - 배열(array): 크기가 고정 (컴파일 때 크기를 알아야 함)
    //   - Vec: 크기가 변동 가능 (실행 중에 늘고 줄 수 있음)
    //   - 지금은 배열을 배우고, Vec는 07단계에서 배워요
    //
    println!("=== 배열 (Array) ===");

    // 배열 선언: [타입; 크기]
    let 요일: [&str; 7] = ["월", "화", "수", "목", "금", "토", "일"];

    // 인덱스로 접근 (0부터 시작!)
    println!("첫 번째 요일: {}", 요일[0]);  // 월
    println!("마지막 요일: {}", 요일[6]);  // 일

    // 배열 길이
    println!("요일 수: {}", 요일.len());

    // 같은 값으로 초기화
    let 영점_배열 = [0; 5];  // [0, 0, 0, 0, 0]
    println!("0으로 채운 배열: {:?}", 영점_배열);

    // for 반복문으로 배열 출력
    print!("모든 요일: ");
    for 요일이름 in &요일 {
        print!("{} ", 요일이름);
    }
    println!();

    println!();
    println!("╔══════════════════════════════════════╗");
    println!("║  1단계 완료! 정말 잘 했어요! 🎉      ║");
    println!("║  다음은 02_control_flow 단계예요!    ║");
    println!("╚══════════════════════════════════════╝");
}

