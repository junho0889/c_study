// 반환값 없는 함수 (기본 인사)
// -> () 를 쓸 수도 있고, 아예 생략할 수도 있어요 (둘 다 같은 의미)
fn 인사하기() {
    println!("안녕하세요! 저는 Rust 프로그램이에요!");
}

// 매개변수가 있는 함수
// 이름: &str  → 이름이라는 변수는 &str 타입이에요
fn 개인_인사하기(이름: &str) {
    println!("안녕하세요, {}님! 반가워요!", 이름);
}

// 여러 매개변수
fn 두수_더하기(a: i32, b: i32) {
    println!("{} + {} = {}", a, b, a + b);
}

// 반환값이 있는 함수
// -> i32  →  i32 타입의 값을 반환해요
fn 더하기(a: i32, b: i32) -> i32 {
    a + b  // 세미콜론 없음! 이 값이 자동으로 반환돼요
    // return a + b;  ← 이렇게 써도 같아요
}

fn 곱하기(a: i32, b: i32) -> i32 {
    a * b  // 마지막 표현식 = 반환값
}

fn 제곱(x: i32) -> i32 {
    // 중간에 return으로 조기 반환도 가능해요
    if x == 0 {
        return 0;  // 0이면 바로 0 반환
    }
    x * x  // 그 외에는 제곱을 반환
}

// 여러 값 반환 (튜플 사용)
fn 최솟값_최댓값(숫자들: Vec<i32>) -> (i32, i32) {
    let mut 최솟 = 숫자들[0];
    let mut 최댓 = 숫자들[0];

    for &n in &숫자들 {
        if n < 최솟 { 최솟 = n; }
        if n > 최댓 { 최댓 = n; }
    }

    (최솟, 최댓)  // 튜플로 두 값을 한번에 반환
}

fn 평균_합계(숫자들: Vec<i32>) -> (i32, f64) {
    let 합: i32 = 숫자들.iter().sum();
    let 평균 = 합 as f64 / 숫자들.len() as f64;
    (합, 평균)
}

// 재귀 함수: 팩토리얼
// n! = n × (n-1) × (n-2) × ... × 1
// 기저 조건: 0! = 1, 1! = 1
fn 팩토리얼(n: u64) -> u64 {
    match n {
        0 | 1 => 1,                  // 기저 조건 (멈추는 조건)
        _ => n * 팩토리얼(n - 1),    // 재귀 호출!
    }
}

// 재귀 함수: 피보나치
// 0, 1, 1, 2, 3, 5, 8, 13, 21, ...
fn 피보나치(n: u32) -> u32 {
    match n {
        0 => 0,                                    // 첫 번째: 0
        1 => 1,                                    // 두 번째: 1
        _ => 피보나치(n - 1) + 피보나치(n - 2),   // 앞 두 수의 합
    }
}

// 클로저를 매개변수로 받는 함수
// F: Fn(i32) -> i32  → F는 i32를 받아서 i32를 반환하는 클로저 타입
fn 변환_후_합계(숫자들: &[i32], 변환함수: impl Fn(i32) -> i32) -> i32 {
    숫자들.iter().map(|&x| 변환함수(x)).sum()
}
