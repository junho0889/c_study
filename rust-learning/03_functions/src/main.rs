// ─────────────────────────────────────────────────────────────────────────
// ■ 함수(Function)란?
// ─────────────────────────────────────────────────────────────────────────
//
//   비유: 레시피 카드
//     - 함수 = 요리 레시피 카드
//     - 재료(매개변수) = 함수에 넣는 입력값
//     - 완성된 요리(반환값) = 함수에서 나오는 결과
//     - 함수 이름 = 레시피 이름 (예: "김치찌개 만들기")
//
//   함수를 왜 써야 할까요?
//   1. 코드 재사용: 같은 코드를 여러 번 작성할 필요 없어요
//   2. 읽기 쉬움: 함수 이름만 보면 무엇을 하는지 알 수 있어요
//   3. 유지보수: 수정할 때 함수 안만 바꾸면 돼요
//   4. 테스트: 각 함수를 따로 테스트할 수 있어요
//
// ─────────────────────────────────────────────────────────────────────────

fn main() {
    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 1. 기본 함수 호출                                                   │
    // └────────────────────────────────────────────────────────────────────┘

    println!("=== 기본 함수 호출 ===");

    // 함수 이름 뒤에 ()를 붙여서 호출해요
    인사하기();
    인사하기();  // 같은 함수를 여러 번 쓸 수 있어요!

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 2. 매개변수가 있는 함수                                             │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   비유: 자판기
    //     - 매개변수 = 자판기에 넣는 버튼/동전
    //     - 함수 = 자판기
    //     - 반환값 = 나오는 음료
    //
    //   Rust에서 중요한 점:
    //   → 매개변수에는 반드시 타입을 써야 해요!
    //   → Rust는 함수 매개변수의 타입을 추론하지 않아요
    //
    println!("=== 매개변수가 있는 함수 ===");

    개인_인사하기("철수");
    개인_인사하기("영희");

    // 여러 매개변수
    두수_더하기(3, 5);
    두수_더하기(10, 20);

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 3. 반환값이 있는 함수                                               │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   비유: 계산기
    //     - 숫자를 넣으면 → 계산 결과가 나와요
    //
    //   Rust의 반환값 규칙:
    //   1. -> 타입 으로 반환 타입을 명시해요
    //   2. 마지막 표현식(세미콜론 없음)이 자동으로 반환돼요
    //   3. return 키워드로 중간에 반환할 수도 있어요
    //
    //   ┌ 중요! 표현식 vs 문장 ────────────────────────────────────────┐
    //   │ 표현식(Expression): 값을 만들어내요 (세미콜론 없음)           │
    //   │   예: 5 + 3  →  8이라는 값                                   │
    //   │   예: { let x = 5; x + 1 }  →  6이라는 값                   │
    //   │                                                               │
    //   │ 문장(Statement): 값을 만들지 않아요 (세미콜론 있음)           │
    //   │   예: let x = 5;  →  값이 없어요, 그냥 실행                  │
    //   │   예: println!("hi");  →  값이 없어요                        │
    //   └──────────────────────────────────────────────────────────────┘
    //
    println!("=== 반환값이 있는 함수 ===");

    let 합 = 더하기(3, 5);
    println!("3 + 5 = {}", 합);

    let 곱 = 곱하기(4, 7);
    println!("4 × 7 = {}", 곱);

    // 함수 반환값을 바로 다른 함수에 사용하기
    println!("(3 + 5) × 2 = {}", 곱하기(더하기(3, 5), 2));

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 4. 표현식 vs 문장 깊이 이해하기                                    │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   Rust는 표현식 기반 언어예요 (Expression-based language)
    //   거의 모든 것이 값을 반환하는 표현식이에요!
    //
    println!("=== 표현식 vs 문장 ===");

    // 블록 자체도 표현식이에요!
    // 블록 안의 마지막 표현식이 전체 블록의 값이 됩니다
    let y = {
        let x = 3;
        x * x + 1  // 세미콜론 없음 → 이 값(10)이 y에 대입돼요
    };
    println!("y = {}", y);  // 10

    // if도 표현식!
    let 최댓값 = if 10 > 5 { 10 } else { 5 };
    println!("최댓값: {}", 최댓값);

    // 함수 마지막 줄에 return 없이 값 반환
    println!("5의 제곱: {}", 제곱(5));

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 5. 여러 값 반환하기 (튜플 사용)                                    │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   Rust 함수는 하나의 값만 반환할 수 있어요
    //   하지만 튜플을 쓰면 여러 값을 묶어서 반환할 수 있어요!
    //
    println!("=== 여러 값 반환하기 ===");

    let (최솟, 최댓) = 최솟값_최댓값(vec![3, 1, 4, 1, 5, 9, 2, 6]);
    println!("배열의 최솟값: {}, 최댓값: {}", 최솟, 최댓);

    let 통계 = 평균_합계(vec![10, 20, 30, 40, 50]);
    println!("합계: {}, 평균: {:.2}", 통계.0, 통계.1);

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 6. 재귀 함수 (Recursion) - 함수가 자기 자신을 부르는 것           │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   비유: 러시아 마트료시카 인형
    //     - 인형 안에 인형이 있고, 그 안에 또 인형이 있어요
    //     - 재귀 = 함수 안에서 같은 함수를 또 부르는 것
    //
    //   주의: 반드시 멈추는 조건(기저 조건, base case)이 있어야 해요!
    //   → 없으면 무한 반복 → 스택 오버플로(stack overflow) 오류!
    //
    println!("=== 재귀 함수 ===");

    // 팩토리얼 계산 (n! = n × (n-1) × ... × 1)
    // 5! = 5 × 4 × 3 × 2 × 1 = 120
    for i in 0..=7 {
        println!("{}! = {}", i, 팩토리얼(i));
    }

    // 피보나치 수열 (1, 1, 2, 3, 5, 8, 13, 21, ...)
    // 앞의 두 수를 더하면 다음 수가 나와요
    println!("\n피보나치 수열 (처음 10개):");
    for i in 0..10 {
        print!("{} ", 피보나치(i));
    }
    println!();

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 7. 클로저 미리보기 (Closures Preview)                              │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   클로저 = 이름 없는 함수 (익명 함수)
    //   자세한 내용은 09_closures_iterators에서 배워요!
    //   지금은 간단히 맛보기만 해요.
    //
    //   비유: 메모지에 적은 작은 함수
    //     - 정식 함수 = 교과서에 있는 공식
    //     - 클로저 = 메모지에 빠르게 적은 공식
    //
    println!("=== 클로저 미리보기 ===");

    // |매개변수| 표현식  ← 이게 클로저예요!
    let 두배_만들기 = |x: i32| x * 2;
    let 세배_만들기 = |x: i32| x * 3;

    println!("5의 두 배: {}", 두배_만들기(5));
    println!("5의 세 배: {}", 세배_만들기(5));

    // 클로저는 변수에 저장할 수 있어요
    let 인사_클로저 = |이름: &str| {
        format!("안녕하세요, {}님!", 이름)
    };

    println!("{}", 인사_클로저("선생님"));

    // 클로저는 주변 변수를 "캡처"할 수 있어요 (함수는 못 해요!)
    let 더할_값 = 10;
    let 더하기_클로저 = |x| x + 더할_값;  // 더할_값을 "캡처"했어요

    println!("5 + {} = {}", 더할_값, 더하기_클로저(5));
    println!("20 + {} = {}", 더할_값, 더하기_클로저(20));

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 8. 함수를 매개변수로 전달하기                                       │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   비유: 요리사 부르기
    //     - "중국 요리사를 불러서 요리를 맡겨요"
    //     - "한국 요리사를 불러서 요리를 맡겨요"
    //     - 요리사(함수)를 바꾸면 결과가 달라져요!
    //
    println!("=== 함수를 매개변수로 전달하기 ===");

    // 함수를 인자로 받는 함수
    let 숫자들 = vec![1, 2, 3, 4, 5];

    // 함수 포인터로 전달
    let 합계 = 변환_후_합계(&숫자들, |x| x * x);  // 제곱의 합
    println!("1²+2²+3²+4²+5² = {}", 합계);

    let 합계2 = 변환_후_합계(&숫자들, |x| x * 2);  // 두 배의 합
    println!("2+4+6+8+10 = {}", 합계2);

    println!();
    println!("╔══════════════════════════════════════╗");
    println!("║  3단계 완료! 함수 마스터! 🎉          ║");
    println!("║  다음은 04_ownership 단계예요!        ║");
    println!("╚══════════════════════════════════════╝");
}

