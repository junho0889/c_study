// ─────────────────────────────────────────────────────────────────────────
// ■ 소유권(Ownership)이란?
// ─────────────────────────────────────────────────────────────────────────
//
//   Rust의 가장 특별한 기능! 다른 언어에는 없는 개념입니다.
//
//   비유: 도서관 책
//     - 책(값)은 한 번에 한 명만 소유할 수 있어요
//     - 책을 다른 사람에게 주면(move), 원래 주인은 더 이상 못 써요
//     - 잠깐 빌려줄 수도 있어요 (borrow/reference)
//     - 여러 명이 읽을 수는 있지만 (불변 참조, &T)
//     - 한 번에 한 명만 수정할 수 있어요 (가변 참조, &mut T)
//
//   왜 이렇게 만들었나?
//   → 프로그램이 실행될 때 메모리 문제(버그)를 컴파일 시점에 미리 잡기 위해!
//   → C/C++에서 자주 발생하는 메모리 버그를 원천 차단!
//
// ─────────────────────────────────────────────────────────────────────────
// ■ 스택(Stack) vs 힙(Heap) - 메모리 저장 방식
// ─────────────────────────────────────────────────────────────────────────
//
//   비유: 식당
//     ┌─────────────────────────────────────────────────────────────┐
//     │ 스택(Stack) = 쟁반 쌓기                                      │
//     │   - 항상 맨 위에 올리고, 맨 위에서 꺼내요 (LIFO)             │
//     │   - 크기를 미리 알아야 해요                                   │
//     │   - 아주 빨라요!                                              │
//     │   - 정수(i32), 실수(f64), bool 등 크기가 고정된 값들         │
//     └─────────────────────────────────────────────────────────────┘
//
//     ┌─────────────────────────────────────────────────────────────┐
//     │ 힙(Heap) = 창고                                              │
//     │   - 빈 공간 어디든 저장 가능                                  │
//     │   - 크기를 실행 중에 결정할 수 있어요                         │
//     │   - 스택보다 느려요 (위치를 찾아야 하니까)                    │
//     │   - String, Vec, Box 등 크기가 변동하는 값들                 │
//     └─────────────────────────────────────────────────────────────┘
//
// ─────────────────────────────────────────────────────────────────────────

fn main() {
    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 1. 소유권의 3가지 규칙                                              │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   규칙 1: 모든 값은 "소유자(owner)"라고 불리는 변수를 가져요
    //   규칙 2: 한 번에 딱 하나의 소유자만 있을 수 있어요
    //   규칙 3: 소유자가 범위(scope)를 벗어나면, 값은 사라져요 (메모리 해제)
    //
    println!("=== 소유권의 3가지 규칙 ===");

    {
        // 규칙 1, 2: s1은 String "hello"의 소유자
        let s1 = String::from("안녕하세요");
        println!("s1: {}", s1);
        // 규칙 3: 이 중괄호 블록이 끝나면 s1은 사라져요
        // Rust가 자동으로 메모리를 해제해요! (drop 함수 호출)
    }
    // 여기서는 s1을 쓸 수 없어요! (이미 범위를 벗어남)
    // println!("{}", s1);  ← 오류!

    println!("블록이 끝나면 변수는 사라져요!");

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 2. 이동(Move) - 소유권이 다른 변수로 넘어가는 것                   │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   비유: 선물 주기
    //     - 친구에게 내 장난감을 주면 (Move)
    //     - 이제 친구가 소유자예요
    //     - 나는 더 이상 그 장난감을 쓸 수 없어요!
    //
    println!("=== 이동(Move) ===");

    let s1 = String::from("안녕!");
    println!("이동 전 s1: {}", s1);

    let s2 = s1;  // s1의 소유권이 s2로 이동(Move)!
    // 이제 s1은 사용할 수 없어요!
    // println!("{}", s1);  ← 컴파일 오류! s1은 이미 이동됨

    println!("이동 후 s2: {}", s2);  // s2만 쓸 수 있어요
    println!("s1은 이제 사용할 수 없어요 (이동됨)");

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 3. 복사(Copy) - 스택 데이터는 자동으로 복사돼요                    │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   비유: 레시피 복사하기
    //     - 레시피(값)를 친구에게 복사해서 줄 수 있어요
    //     - 나도 원본을 여전히 갖고 있어요!
    //
    //   Copy 트레이트를 구현한 타입들은 자동으로 복사돼요:
    //   - 모든 정수형 (i32, u64, ...)
    //   - 모든 실수형 (f32, f64)
    //   - bool
    //   - char
    //   - 위 타입들로만 이루어진 튜플
    //
    //   String, Vec 등은 Copy가 없어요 → 이동(Move)됨
    //
    println!("=== 복사(Copy) ===");

    let x = 5;      // 정수는 스택에 저장, Copy 트레이트가 있어요
    let y = x;      // x를 복사해서 y에 대입 (이동이 아니라 복사!)

    // x와 y 둘 다 사용 가능!
    println!("x = {}, y = {}", x, y);
    println!("둘 다 쓸 수 있어요! (스택 데이터는 자동 복사)");

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 4. 클론(Clone) - 힙 데이터를 명시적으로 복사하기                   │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   비유: 책 복사본 만들기
    //     - 원본 책은 그대로 두고
    //     - 복사기로 같은 내용의 새 책을 만드는 것
    //     - 비용이 들어요 (복사하는 시간과 메모리)
    //
    //   .clone() 메서드를 호출하면 깊은 복사(deep copy)가 됩니다
    //
    println!("=== 클론(Clone) ===");

    let s1 = String::from("안녕하세요!");
    let s2 = s1.clone();  // s1을 깊은 복사 → s2

    // 이제 s1과 s2 둘 다 쓸 수 있어요!
    println!("s1: {}", s1);  // 원본
    println!("s2: {}", s2);  // 복사본
    println!("둘 다 쓸 수 있어요! (clone으로 복사했으니까요)");

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 5. 참조와 빌리기 (References & Borrowing)                          │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   비유: 책 빌리기
    //     - 친구에게 책을 빌려주는 것
    //     - 친구가 다 읽으면 돌려줘야 해요
    //     - 나는 여전히 책의 주인이에요!
    //     - & 기호가 "참조(reference)" = 빌리기
    //
    //   참조의 규칙:
    //   1. 불변 참조(&T): 여러 명이 동시에 읽을 수 있어요
    //   2. 가변 참조(&mut T): 한 번에 한 명만 수정 가능
    //   3. 불변 참조와 가변 참조는 동시에 존재할 수 없어요!
    //
    println!("=== 참조와 빌리기 ===");

    let s1 = String::from("안녕하세요!");

    // &s1 = s1의 참조 (소유권을 넘기지 않고 빌려줘요)
    let 길이 = 문자열_길이(&s1);  // s1을 빌려줌

    // s1은 여전히 사용 가능!
    println!("문자열: {}", s1);
    println!("길이: {} 글자", 길이);

    // 여러 불변 참조 동시에 가능
    let r1 = &s1;
    let r2 = &s1;
    let r3 = &s1;
    println!("세 참조 동시 사용: {}, {}, {}", r1, r2, r3);

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 6. 가변 참조 (Mutable References)                                  │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   비유: 화이트보드
    //     - 여러 명이 동시에 화이트보드를 읽는 건 괜찮아요
    //     - 하지만 여러 명이 동시에 쓰면 내용이 뒤죽박죽!
    //     - 그래서 쓸 때는 한 명만!
    //
    println!("=== 가변 참조 (Mutable References) ===");

    let mut s = String::from("안녕");
    println!("변경 전: {}", s);

    // &mut s = 가변 참조 (내용을 바꿀 수 있어요)
    문자열_추가(&mut s);
    println!("변경 후: {}", s);

    // 규칙: 가변 참조는 한 번에 하나만!
    // let r1 = &mut s;
    // let r2 = &mut s;  ← 오류! 가변 참조 두 개 동시 불가
    // println!("{}, {}", r1, r2);

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 7. 매달린 참조 방지 (Dangling References Prevention)               │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   비유: 이미 없어진 사물함 열쇠
    //     - 사물함이 없어졌는데 그 열쇠를 갖고 있는 상황
    //     - C/C++에서는 이런 버그가 자주 발생해요!
    //     - Rust는 컴파일 때 이런 상황을 막아줘요!
    //
    println!("=== 매달린 참조 방지 ===");

    // 이런 코드는 Rust에서 컴파일 오류가 나요:
    // fn 매달린_참조() -> &String {
    //     let s = String::from("hello");
    //     &s  // s는 이 함수가 끝나면 사라지는데, 그 참조를 반환?
    // }       // ← 오류! 사라질 값의 참조를 반환하면 안 돼요

    // 올바른 방법: 소유권을 반환해요
    let s = 안전한_문자열();
    println!("안전하게 반환된 문자열: {}", s);

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 8. 슬라이스 (Slices) - 일부분만 참조하기                           │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   비유: 책의 특정 페이지
    //     - 책 전체가 아니라 특정 페이지(범위)만 빌리는 것
    //     - 슬라이스 = 연속된 데이터의 일부를 참조
    //
    //   &str 문자열 슬라이스
    //   &[T] 배열 슬라이스
    //
    println!("=== 슬라이스 (Slices) ===");

    // 문자열 슬라이스
    let 전체_문장 = String::from("안녕 러스트");
    let 첫단어 = &전체_문장[0..6];   // 인덱스는 바이트 단위! (한글은 3바이트)
    println!("전체 문장: {}", 전체_문장);
    println!("첫 2글자(바이트 0..6): {}", 첫단어);

    // 문자열 슬라이스로 첫 번째 단어 찾기
    let 문장 = "안녕 세상아 반가워";
    let 첫번째단어 = 첫번째_단어(문장);
    println!("첫 번째 단어: '{}'", 첫번째단어);

    // 배열 슬라이스
    let 배열 = [1, 2, 3, 4, 5];
    let 슬라이스 = &배열[1..4];  // 인덱스 1, 2, 3 (4는 미포함)
    println!("배열 슬라이스 [1..4]: {:?}", 슬라이스);

    // 슬라이스 함수에 전달
    let 합 = 배열_합(&배열);
    println!("배열 합계: {}", 합);

    let 합_일부 = 배열_합(&배열[1..4]);  // 일부만 전달
    println!("부분 합계 [1..4]: {}", 합_일부);

    println!();

    // ┌────────────────────────────────────────────────────────────────────┐
    // │ 9. 함수로 소유권 이동/반환 이해하기                                 │
    // └────────────────────────────────────────────────────────────────────┘
    //
    //   함수에 값을 전달하면:
    //   - 이동(Move)이 일어나거나 (String, Vec 등)
    //   - 복사(Copy)가 일어나요 (i32, f64 등)
    //
    println!("=== 함수로 소유권 이동 ===");

    let s = String::from("소유권 테스트");
    println!("함수 호출 전 s: {}", s);

    소유권_받기(s);  // s의 소유권이 함수로 이동!
    // println!("{}", s);  ← 오류! s는 이미 함수로 이동됨

    // 소유권을 돌려받는 방법
    let s2 = String::from("소유권 반환 테스트");
    let s3 = 소유권_받고_반환(s2);  // s2는 이동됐지만 s3로 돌아와요
    println!("소유권을 돌려받은 s3: {}", s3);

    // 참조로 전달하면 소유권 이동 없음!
    let s4 = String::from("참조 테스트");
    참조_받기(&s4);  // s4를 빌려줌 (소유권 이동 없음)
    println!("참조 전달 후에도 s4 사용 가능: {}", s4);

    println!();
    println!("╔══════════════════════════════════════════════╗");
    println!("║  4단계 완료! 소유권 마스터! 🎉               ║");
    println!("║  Rust의 핵심 개념을 이해했어요!              ║");
    println!("║  다음은 05_structs_enums 단계예요!           ║");
    println!("╚══════════════════════════════════════════════╝");
}

