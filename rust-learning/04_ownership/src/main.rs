// 참조를 받아서 문자열 길이 반환
// &String → 소유권을 받지 않고 빌리기만 해요
fn 문자열_길이(s: &String) -> usize {
    s.chars().count()  // 글자 수 반환 (바이트가 아닌 문자 기준)
}

// 가변 참조를 받아서 문자열 수정
fn 문자열_추가(s: &mut String) {
    s.push_str(", 세상아!");
}

// 소유권을 받고 아무것도 반환 안 하면 → 값이 사라져요
fn 소유권_받기(s: String) {
    println!("함수 안에서 사용: {}", s);
    // 함수 끝나면 s가 사라져요 (drop)
}

// 소유권을 받고 다시 반환하기
fn 소유권_받고_반환(s: String) -> String {
    println!("함수 안에서: {}", s);
    s  // 소유권을 반환!
}

// 참조만 받기 (소유권 이동 없음)
fn 참조_받기(s: &String) {
    println!("빌려서 사용: {}", s);
    // 여기서는 s를 수정할 수 없어요 (&mut이 아니니까)
}

// 소유권을 반환하는 안전한 함수
fn 안전한_문자열() -> String {
    let s = String::from("안전하게 반환됨");
    s  // 소유권을 반환 (참조가 아닌 값 자체)
}

// 문자열에서 첫 번째 단어 찾기 (문자열 슬라이스 사용)
fn 첫번째_단어(s: &str) -> &str {
    let 바이트들 = s.as_bytes();

    for (i, &item) in 바이트들.iter().enumerate() {
        if item == b' ' {  // 공백을 만나면
            return &s[0..i];  // 처음부터 공백 전까지 반환
        }
    }

    &s[..]  // 공백이 없으면 전체 반환
}

// 배열 슬라이스를 받아서 합계 반환
fn 배열_합(배열: &[i32]) -> i32 {
    let mut 합 = 0;
    for &n in 배열 {
        합 += n;
    }
    합
}
