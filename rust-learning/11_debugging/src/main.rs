// =====================================================================
// 레슨 1 — println! 디버깅: 가장 기본이자 강력한 방법
// =====================================================================
/*
★ 출력 포맷 종류

  ┌──────────────┬──────────────────────────────────────┐
  │ {}           │ Display 트레이트 (사용자 친화적)      │
  │ {:?}         │ Debug 트레이트 (개발자용)            │
  │ {:#?}        │ Debug 이쁘게 (줄바꿈 포함)           │
  │ {:b}         │ 2진수                                │
  │ {:o}         │ 8진수                                │
  │ {:x}         │ 16진수 (소문자)                      │
  │ {:X}         │ 16진수 (대문자)                      │
  │ {:p}         │ 포인터 주소                          │
  │ {:.2}        │ 소수점 2자리                         │
  │ {:>10}       │ 오른쪽 정렬 (폭 10)                  │
  │ {:<10}       │ 왼쪽 정렬 (폭 10)                    │
  │ {:^10}       │ 가운데 정렬 (폭 10)                  │
  └──────────────┴──────────────────────────────────────┘
*/

#[derive(Debug)]
struct Student {
    name: String,
    scores: Vec<i32>,
}

fn lesson1_println_debugging() {
    println!("═══════════════════════════════════════════");
    println!(" 레슨 1: println! 디버깅");
    println!("═══════════════════════════════════════════");

    let student = Student {
        name: String::from("철수"),
        scores: vec![90, 85, 92, 78],
    };

    // ── {:?} 와 {:#?} ──
    println!("  Debug:    {:?}", student);
    println!("  Pretty:   {:#?}", student);

    // ── 여러 값 한 줄에 ──
    let (x, y, z) = (10, 20, 30);
    println!("  x={}, y={}, z={}", x, y, z);
    println!("  이진수: {:b}, 16진수: {:x}", 255, 255);

    // ── 정렬과 패딩 ──
    for (name, score) in [("철수", 92), ("영희", 88), ("민수", 75)] {
        println!("  {:>6} | {:>3}점 | {}", name, score,
            if score >= 90 { "우수" } else if score >= 80 { "통과" } else { "노력" });
    }

    // ── 포인터 주소 ──
    let val = 42;
    let ptr = &val;
    println!("  값: {}, 주소: {:p}", val, ptr);
    println!();
}

