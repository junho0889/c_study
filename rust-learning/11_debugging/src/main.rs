// 레슨 3 — assert! : 불변 조건 검증
// =====================================================================
/*
★ assert 매크로 종류

  ┌─────────────────────┬──────────────────────────────────────┐
  │ assert!(조건)       │ 조건이 false 면 panic!               │
  │ assert_eq!(a, b)    │ a != b 면 panic! (두 값 모두 표시)   │
  │ assert_ne!(a, b)    │ a == b 면 panic!                     │
  │ debug_assert!(조건) │ 디버그 빌드에서만 검사 (릴리스 무시) │
  └─────────────────────┴──────────────────────────────────────┘

★ 사용 시점:
  - assert! → "이 조건은 반드시 참이어야 한다" (버그 발견용)
  - 일반 에러 처리에는 Result 사용! (08단계 참고)
*/

fn calculate_average(scores: &[i32]) -> f64 {
    assert!(!scores.is_empty(), "점수 배열이 비어있으면 안 됩니다!");
    let total: i32 = scores.iter().sum();
    total as f64 / scores.len() as f64
}

fn lesson3_assert() {
    println!("═══════════════════════════════════════════");
    println!(" 레슨 3: assert! 로 불변 조건 검증");
    println!("═══════════════════════════════════════════");

    let scores = [80, 90, 100];
    let avg = calculate_average(&scores);
    println!("  평균: {:.1}", avg);

    // assert_eq! / assert_ne!
    assert_eq!(2 + 2, 4, "기본 산술이 틀렸습니다!");
    assert_ne!(2 + 2, 5);
    println!("  assert_eq!(2+2, 4) 통과!");

    // 커스텀 메시지
    let port = 8080;
    assert!(port > 1024, "포트 {}는 예약 포트입니다!", port);
    println!("  포트 {} 는 유효합니다", port);

    // ★ 빈 배열로 호출하면 panic!
    // calculate_average(&[]);  // ← panic!
    println!("  ★ assert 는 프로그래머 실수를 잡는 용도입니다");
    println!("    사용자 입력 검증에는 Result 를 사용하세요!");
    println!();
}

