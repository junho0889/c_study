// 레슨 2 — dbg! 매크로: 더 편리한 디버깅
// =====================================================================
/*
★ dbg! = println! 보다 편리한 디버깅 도구

  ┌──────────────────────────────────────────────────────────┐
  │ 장점:                                                    │
  │ 1. 파일명, 줄 번호를 자동으로 표시                       │
  │ 2. 표현식을 보여준 뒤 그 값을 그대로 반환                │
  │ 3. stderr 로 출력 (stdout 과 섞이지 않음)               │
  │                                                          │
  │ 주의:                                                    │
  │ → dbg! 는 소유권을 가져갑니다! (값을 반환하긴 하지만)   │
  │ → 참조를 넘기려면 dbg!(&value) 로 쓰세요                │
  └──────────────────────────────────────────────────────────┘

  비유:
  ┌────────────────────────────────────────────────────────┐
  │ println! = "이 값은 {}입니다" 를 직접 작성              │
  │ dbg!     = "이 시점에서 이 변수 = 이 값" 자동 기록     │
  └────────────────────────────────────────────────────────┘
*/

fn lesson2_dbg_macro() {
    println!("═══════════════════════════════════════════");
    println!(" 레슨 2: dbg! 매크로");
    println!("═══════════════════════════════════════════");

    // dbg! 는 값을 반환하면서 동시에 디버그 출력
    let a = 5;
    let b = dbg!(a * 2);   // stderr: [파일:줄] a * 2 = 10
    let c = dbg!(b + 3);   // stderr: [파일:줄] b + 3 = 13
    println!("  최종값 c = {}", c);

    // ── 체이닝 중간에 끼워넣기 ──
    let scores = vec![55, 72, 88, 91, 64];
    let count = scores.iter()
        .filter(|&&s| s >= 70)
        .inspect(|s| println!("    통과: {}", s))  // inspect 은 디버그용
        .count();
    println!("  통과 인원: {}", count);

    println!();
    println!("  ★ dbg! 는 stderr 로 출력됩니다 (위에 보이는 [파일:줄] 형식)");
    println!("  ★ 실전에서는 커밋 전에 dbg! 를 모두 제거하세요!");
    println!("    → cargo clippy 가 남은 dbg! 를 경고해줍니다");
    println!();
}

