// 레슨 5 — 흔한 버그 패턴과 해결법
// =====================================================================
/*
★ Rust 에서 자주 만나는 버그 패턴들

  1. Off-by-one 에러 (하나 차이 실수)
  2. 정수 오버플로우
  3. 부동소수점 비교
  4. 인덱스 범위 초과
  5. 문자열 바이트 vs 문자 혼동
*/

fn wrong_average(scores: &[i32]) -> i32 {
    let total: i32 = scores.iter().sum();
    // ★ 버그: scores.len() - 1 은 "n개 중 n-1개" 로 나누는 실수
    total / (scores.len() as i32 - 1)
}

fn correct_average(scores: &[i32]) -> f64 {
    let total: i32 = scores.iter().sum();
    total as f64 / scores.len() as f64
}

fn lesson5_common_bugs() {
    println!("═══════════════════════════════════════════");
    println!(" 레슨 5: 흔한 버그 패턴");
    println!("═══════════════════════════════════════════");

    // ── 1. Off-by-one ──
    let scores = [80, 90, 100];
    println!("  잘못된 평균: {} (분모가 2)", wrong_average(&scores));
    println!("  올바른 평균: {:.1}", correct_average(&scores));

    // ── 2. 정수 오버플로우 ──
    // let x: u8 = 255;
    // let y = x + 1;  // 디버그: panic!, 릴리스: 0 으로 감김
    let x: u8 = 200;
    let y: u8 = 100;
    // 안전한 방법: checked_add
    match x.checked_add(y) {
        Some(sum) => println!("  {}+{} = {}", x, y, sum),
        None      => println!("  {}+{} = 오버플로우!", x, y),
    }
    // wrapping / saturating 연산
    println!("  wrapping: {} + {} = {}", x, y, x.wrapping_add(y));
    println!("  saturating: {} + {} = {}", x, y, x.saturating_add(y));

    // ── 3. 부동소수점 비교 ──
    let a: f64 = 0.1 + 0.2;
    let b: f64 = 0.3;
    println!("  0.1 + 0.2 == 0.3 ? {} (직접 비교 위험!)", a == b);
    println!("  차이: {}", (a - b).abs());
    println!("  안전 비교: {}", (a - b).abs() < f64::EPSILON * 10.0);

    // ── 4. 안전한 인덱스 접근 ──
    let data = vec![10, 20, 30];
    // data[5];  // panic!
    match data.get(5) {
        Some(v) => println!("  data[5] = {}", v),
        None    => println!("  data[5] = 범위 밖! (.get 으로 안전하게 확인)"),
    }

    // ── 5. 중간값 추적으로 버그 찾기 ──
    println!();
    println!("  ★ 디버깅 팁: 의심 구간의 중간값을 출력하세요!");
    let scores2 = [80, 90, 100];
    let total: i32 = scores2.iter().sum();
    let count = scores2.len();
    println!("    total = {}", total);
    println!("    count = {}", count);
    println!("    avg = total/count = {:.1}", total as f64 / count as f64);
    println!();
}

