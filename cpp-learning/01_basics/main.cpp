// =========================================================================
//
//  레슨 4 — 산술 연산자
//
// =========================================================================
void lesson4_arithmetic_operators() {
    cout << "┌──────────────────────────────────────┐" << endl;
    cout << "│  레슨 4 : 산술 연산자                │" << endl;
    cout << "└──────────────────────────────────────┘" << endl;
    cout << endl;

    // ─────────────────────────────────────────────
    // ■ 사칙연산 (+, -, *, /, %)
    // ─────────────────────────────────────────────

    int a = 17;
    int b = 5;

    cout << "  ■ 사칙연산  (a = " << a << ", b = " << b << ")" << endl;
    cout << "  ─────────────────────────────────────" << endl;
    cout << "  a + b  = " << (a + b)  << "    덧셈" << endl;
    cout << "  a - b  = " << (a - b)  << "   뺄셈" << endl;
    cout << "  a * b  = " << (a * b)  << "   곱셈" << endl;
    cout << "  a / b  = " << (a / b)  << "    나눗셈 (몫만!)" << endl;
    cout << "  a % b  = " << (a % b)  << "    나머지 (모듈로)" << endl;
    cout << endl;

    // ─────────────────────────────────────────────
    // ★★★ 핵심 함정: 정수 ÷ 정수 = 정수! ★★★
    // ─────────────────────────────────────────────
    //
    //   17 / 5 = 3   (3.4가 아니라 3!  소수점이 버려짐!)
    //
    //   이유: 양쪽이 모두 정수(int)이면 결과도 정수
    //
    //   해결법: 한쪽이라도 실수(double)로 만들기
    //   ─────────────────────────────────
    //   17.0 / 5    → 3.4  (앞을 실수로)
    //   17 / 5.0    → 3.4  (뒤를 실수로)
    //   (double)17 / 5 → 3.4  (캐스팅)

    cout << "  ★ 정수 나눗셈 함정!" << endl;
    cout << "  ─────────────────────────────────────" << endl;
    cout << "  17 / 5     = " << (17 / 5)     << "    ← 틀림! (소수점 버려짐)" << endl;
    cout << "  17.0 / 5   = " << (17.0 / 5)   << "  ← 맞음!" << endl;
    cout << "  17 / 5.0   = " << (17 / 5.0)   << "  ← 맞음!" << endl;
    cout << endl;

    // ─────────────────────────────────────────────
    // ■ 증감 연산자 (++, --)
    // ─────────────────────────────────────────────
    //
    //   ++x (전위): 먼저 증가시키고, 그 값을 사용
    //   x++ (후위): 현재 값을 먼저 사용하고, 그 다음 증가
    //
    //   예시:
    //     int x = 5;
    //     int a = ++x;  // x를 6으로 만들고 → a = 6,  x = 6
    //     int b = x++;  // b에 6을 넣고 → x를 7로   b = 6,  x = 7

    cout << "  ■ 증감 연산자" << endl;
    cout << "  ─────────────────────────────────────" << endl;

    int c = 10;
    cout << "  c = " << c << endl;
    cout << "  ++c (전위) = " << (++c) << "  ← 먼저 증가, 그 값 사용" << endl;
    cout << "  c++ (후위) = " << (c++) << "  ← 현재 값 사용, 그 다음 증가" << endl;
    cout << "  현재 c     = " << c << endl;
    cout << endl;

    // ─────────────────────────────────────────────
    // ■ 복합 대입 연산자 (+=, -=, *=, /=, %=)
    // ─────────────────────────────────────────────
    //
    //   x += 10  은  x = x + 10  과 같은 뜻 (줄여 쓴 것)

    cout << "  ■ 복합 대입 연산자" << endl;
    cout << "  ─────────────────────────────────────" << endl;

    int n = 100;
    cout << "  n = " << n << endl;

    n += 50;    cout << "  n += 50  → n = " << n << "  (n = n + 50)" << endl;
    n -= 30;    cout << "  n -= 30  → n = " << n << "  (n = n - 30)" << endl;
    n *= 2;     cout << "  n *= 2   → n = " << n << "  (n = n * 2)" << endl;
    n /= 4;     cout << "  n /= 4   → n = " << n << "   (n = n / 4)" << endl;
    n %= 7;     cout << "  n %= 7   → n = " << n << "    (n = n % 7)" << endl;
    cout << endl;
}


// =========================================================================
//
//  레슨 5 — 비교 연산자와 논리 연산자
//
// =========================================================================
void lesson5_comparison_and_logic() {
    cout << "┌──────────────────────────────────────┐" << endl;
    cout << "│  레슨 5 : 비교 & 논리 연산자         │" << endl;
    cout << "└──────────────────────────────────────┘" << endl;
    cout << endl;

    // ─────────────────────────────────────────────
    // ■ 비교 연산자 (결과: true=1 또는 false=0)
    // ─────────────────────────────────────────────
    //
    //   ==  같다      (= 와 혼동 주의!)
    //   !=  다르다
    //   <   작다
    //   >   크다
    //   <=  작거나 같다
    //   >=  크거나 같다

    int x = 10, y = 20;

    cout << "  ■ 비교 연산자  (x = " << x << ", y = " << y << ")" << endl;
    cout << "  ─────────────────────────────────────" << endl;
    cout << "  x == y  → " << (x == y)  << "  같은가?" << endl;
    cout << "  x != y  → " << (x != y)  << "  다른가?" << endl;
    cout << "  x < y   → " << (x < y)   << "  작은가?" << endl;
    cout << "  x > y   → " << (x > y)   << "  큰가?" << endl;
    cout << "  x <= y  → " << (x <= y)  << "  작거나 같은가?" << endl;
    cout << "  x >= y  → " << (x >= y)  << "  크거나 같은가?" << endl;
    cout << endl;

    // ★★★ 가장 흔한 실수: = 와 == 혼동 ★★★
    //
    //   if (x = 5)   ← 대입!  x에 5를 넣는 것!  항상 true! (버그!)
    //   if (x == 5)  ← 비교!  x가 5인지 확인!  올바른 코드!
    //
    //   외우는 법: "같다"는 = 가 두 개! (==)

    cout << "  ★ 주의: = (대입) ≠ == (비교)" << endl;
    cout << "  if (x = 5)  → 대입! 항상 true! (버그)" << endl;
    cout << "  if (x == 5) → 비교! 올바름!" << endl;
    cout << endl;

    // ─────────────────────────────────────────────
    // ■ 논리 연산자
    // ─────────────────────────────────────────────
    //
    //   &&  그리고 (AND) : 둘 다 참이어야 참
    //   ||  또는   (OR)  : 하나만 참이어도 참
    //   !   아닌   (NOT) : 참↔거짓 반전
    //
    //   진리표:
    //   ┌───┬───┬──────┬──────┬─────┐
    //   │ A │ B │ A&&B │ A||B │ !A  │
    //   ├───┼───┼──────┼──────┼─────┤
    //   │ T │ T │  T   │  T   │  F  │
    //   │ T │ F │  F   │  T   │  F  │
    //   │ F │ T │  F   │  T   │  T  │
    //   │ F │ F │  F   │  F   │  T  │
    //   └───┴───┴──────┴──────┴─────┘

    bool a = true, b = false;

    cout << "  ■ 논리 연산자  (a = true, b = false)" << endl;
    cout << "  ─────────────────────────────────────" << endl;
    cout << "  a && b (AND) = " << (a && b) << "  둘 다 참?" << endl;
    cout << "  a || b (OR)  = " << (a || b) << "  하나라도 참?" << endl;
    cout << "  !a     (NOT) = " << (!a)     << "  반전" << endl;
    cout << endl;

    // 실용 예제
    int age = 20;
    bool has_id = true;

    cout << "  ■ 실용 예제" << endl;
    cout << "  ─────────────────────────────────────" << endl;
    cout << "  나이: " << age << ", 신분증: " << (has_id ? "있음" : "없음") << endl;

    bool can_enter = (age >= 18) && has_id;
    cout << "  입장 가능? (18세 이상 AND 신분증) → "
         << (can_enter ? "가능" : "불가") << endl;

    bool is_discount = (age < 13) || (age >= 65);
    cout << "  할인 대상? (13세 미만 OR 65세 이상) → "
         << (is_discount ? "대상" : "비대상") << endl;
    cout << endl;
}


// =========================================================================
//
//  레슨 6 — 형 변환 (Type Conversion / Casting)
//
// =========================================================================
void lesson6_type_conversion() {
    cout << "┌──────────────────────────────────────┐" << endl;
    cout << "│  레슨 6 : 형 변환 (캐스팅)           │" << endl;
    cout << "└──────────────────────────────────────┘" << endl;
    cout << endl;

    // ─── 형 변환이란? ───
    //
    //   한 자료형의 값을 다른 자료형으로 바꾸는 것.
    //
    //   비유: 달러를 원화로 환전하는 것
    //         → 때로는 정보가 사라질 수 있음 (동전 단위 반올림)

    // ─────────────────────────────────────────────
    // ■ 암시적 변환 (자동으로 일어남)
    // ─────────────────────────────────────────────
    //
    //   컴파일러가 알아서 바꿔줌.
    //   작은 타입 → 큰 타입 = 안전 (데이터 손실 없음)
    //   큰 타입 → 작은 타입 = 위험! (데이터 잘릴 수 있음!)

    cout << "  ■ 암시적 변환 (자동)" << endl;
    cout << "  ─────────────────────────────────────" << endl;

    int    i = 42;
    double d = i;       // int → double (안전, 정보 손실 없음)
    cout << "  int 42 → double = " << d << "  (안전)" << endl;

    double pi = 3.99;
    int    t  = pi;     // double → int  (위험! 소수점이 버려짐!)
    cout << "  double 3.99 → int = " << t << "    (소수점 잘림!)" << endl;

    char ch = 'A';
    int  ascii = ch;    // char → int  (문자의 ASCII 코드값)
    cout << "  char 'A' → int = " << ascii << "  (ASCII 코드)" << endl;

    int  num = 65;
    char letter = num;  // int → char  (ASCII 코드 → 문자)
    cout << "  int 65 → char = '" << letter << "' (문자로 변환)" << endl;
    cout << endl;

    // ─────────────────────────────────────────────
    // ■ 명시적 변환 (프로그래머가 직접 지정)
    // ─────────────────────────────────────────────
    //
    //   "나는 이걸 의도적으로 바꾸는 거야" 라고 표시하는 것.
    //
    //   C 스타일:    (int)3.14          ← 오래된 방식 (비추천)
    //   C++ 스타일:  static_cast<int>(3.14)  ← 현대 방식 (추천!)
    //
    //   왜 C++ 스타일이 좋은가?
    //   → 코드에서 검색하기 쉬움 (grep으로 "static_cast" 검색)
    //   → 의도가 명확 (어떤 종류의 변환인지 알 수 있음)
    //   → 잘못된 변환을 컴파일러가 잡아줌

    cout << "  ■ 명시적 변환 (캐스팅)" << endl;
    cout << "  ─────────────────────────────────────" << endl;

    double value = 9.87;

    int c_style   = (int)value;                  // C 스타일 (비추천)
    int cpp_style = static_cast<int>(value);     // C++ 스타일 (추천!)

    cout << "  C 스타일:   (int)9.87         = " << c_style << endl;
    cout << "  C++ 스타일: static_cast<int>  = " << cpp_style << endl;
    cout << endl;

    // ─────────────────────────────────────────────
    // ■ 실전 활용: 정수 나눗셈에서 소수점 얻기
    // ─────────────────────────────────────────────
    //
    //   가장 흔한 사용 상황!

    cout << "  ■ 실전 활용" << endl;
    cout << "  ─────────────────────────────────────" << endl;

    int total = 17;
    int count = 5;

    // 틀린 방법: 17/5 = 3 (정수끼리 나눈 후 double에 넣어도 3.0)
    double wrong = total / count;
    cout << "  틀림: 17 / 5              = " << wrong << endl;

    // 맞는 방법: 한쪽을 double로 캐스팅
    double correct = static_cast<double>(total) / count;
    cout << "  맞음: static_cast(17) / 5 = " << correct << endl;
    cout << endl;

    // ─── C++ 캐스팅 4종류 (참고) ───
    //
    //   static_cast<T>(x)      일반적 변환 (이것만 알면 됨!)
    //   dynamic_cast<T>(x)     상속 관계에서 안전한 변환 (06단계)
    //   const_cast<T>(x)       const 속성 제거
    //   reinterpret_cast<T>(x) 메모리 비트 재해석 (위험!)
    //
    //   초보 단계: static_cast 하나만 기억하세요!
}


