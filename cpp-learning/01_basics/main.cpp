// ─────────────────────────────────────────────────────────────────────────
// ■ #include 란?
// ─────────────────────────────────────────────────────────────────────────
//
//   "다른 파일에 미리 만들어둔 기능을 가져다 쓰겠다" 라는 뜻입니다.
//
//   비유: 요리할 때 "냉장고에서 재료를 꺼내는 것"
//         → #include는 "도구 상자에서 도구를 꺼내는 것"
//
//   <iostream> : 화면 출력(cout)과 키보드 입력(cin) 도구
