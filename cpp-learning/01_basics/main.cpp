// =========================================================================
//
//  레슨 1 — Hello, World!  (프로그램의 기본 구조)
//
// =========================================================================
void lesson1_hello_world() {
    cout << "┌──────────────────────────────────────┐" << endl;
    cout << "│  레슨 1 : Hello, World!              │" << endl;
    cout << "└──────────────────────────────────────┘" << endl;
    cout << endl;

    // ─── cout 이란? ───
    //
    //   cout = 화면에 글자를 출력하는 도구
    //   <<   = "이것을 출력해라" 라는 뜻 (화살표 방향으로 데이터가 흘러감)
    //   endl = 줄바꿈 (다음 줄로 넘어감)
    //   "\n" = 줄바꿈 (endl과 같지만 더 빠름)
    //
    //   비유: cout은 "방송 마이크",  << 는 "여기에 말해!"

    cout << "  Hello, World!" << endl;        // 가장 기본적인 출력
    cout << "  안녕하세요, C++ 세계!" << endl;  // 한글도 됩니다
    cout << "  숫자 출력: " << 42 << endl;     // 숫자도 출력 가능
    cout << "  계산 결과: " << 3 + 5 << endl;  // 계산도 가능!

    // 여러 값을 << 로 연결해서 한번에 출력
    cout << "  이름: " << "홍길동" << ", 나이: " << 25 << "세" << endl;

    cout << endl;

    // ─── C++ 프로그램의 뼈대 ───
    //
    //   ┌──────────────────────────────────────────┐
    //   │  #include <iostream>     ← 1. 도구 가져오기│
    //   │  using namespace std;    ← 2. 이름표 생략  │
    //   │                                           │
    //   │  int main() {            ← 3. 시작점       │
    //   │      cout << "Hello";   ← 4. 코드 작성    │
    //   │      return 0;           ← 5. 끝           │
    //   │  }                                        │
    //   └──────────────────────────────────────────┘
    //
    //   ★ 초보자 실수 TOP 3
    //   ────────────────────
    //   1. 문장 끝에 세미콜론(;) 빠뜨림  ← 가장 흔한 실수!
    //   2. 중괄호 { } 짝이 안 맞음
    //   3. 대소문자 구분 안 함  (Main ≠ main,  Cout ≠ cout)
    //
    //   에러가 나면 이 3가지를 먼저 확인하세요!
}


// =========================================================================
//
//  레슨 2 — 변수와 자료형
//
// =========================================================================
void lesson2_variables() {
    cout << "┌──────────────────────────────────────┐" << endl;
    cout << "│  레슨 2 : 변수와 자료형              │" << endl;
    cout << "└──────────────────────────────────────┘" << endl;
    cout << endl;

    // ─── 변수란? ───
    //
    //   변수 = 값을 담는 상자  (상자에 이름표를 붙여서 구분)
    //
    //   비유:
    //     서랍장의 서랍 하나하나가 "변수"
    //     서랍에 이름표("age", "name")를 붙이고
    //     그 안에 값(25, "홍길동")을 넣는 것
    //
    //   선언 형식:
    //     자료형  변수이름 = 초기값;
    //     int     age     = 25;
    //     ↑타입   ↑이름    ↑값
    //
    //   ★ 변수 이름 규칙
    //   ─────────────────
    //   - 영문자, 숫자, 밑줄(_)만 사용 가능
    //   - 숫자로 시작할 수 없음  (2nd → 안됨,  second → 됨)
    //   - 예약어 사용 불가       (int, for, class 등)
    //   - 대소문자 구분           (age ≠ Age ≠ AGE)
    //   - 관례: snake_case(my_score) 또는 camelCase(myScore)

    // ─────────────────────────────────────────────
    // ■ 정수형 (소수점이 없는 숫자)
    // ─────────────────────────────────────────────
    //
    //   ┌────────────┬──────────┬───────────────────────────┐
    //   │  자료형     │ 크기     │ 범위                       │
    //   ├────────────┼──────────┼───────────────────────────┤
    //   │ short      │ 2바이트  │ -32,768 ~ 32,767          │
    //   │ int        │ 4바이트  │ 약 -21억 ~ 21억 (기본!)    │
    //   │ long long  │ 8바이트  │ 약 -920경 ~ 920경          │
    //   │ unsigned   │ (양수만) │ 음수 불가, 양수 범위 2배    │
    //   └────────────┴──────────┴───────────────────────────┘
    //
    //   보통 정수는 int를 쓰면 됩니다.
    //   21억이 넘는 큰 수는 long long을 씁니다.

    int         age          = 25;               // 나이 → int면 충분
    short       temperature  = -10;              // 작은 정수
    long long   world_pop    = 8000000000LL;     // 세계 인구 (LL = long long)
    unsigned int item_count  = 150;              // 양수만 (음수 불가)

    cout << "  ■ 정수형" << endl;
    cout << "  ─────────────────────────────────────" << endl;
    cout << "  int         age         = " << age << endl;
    cout << "  short       temperature = " << temperature << endl;
    cout << "  long long   world_pop   = " << world_pop << endl;
    cout << "  unsigned    item_count  = " << item_count << endl;
    cout << endl;

    // ─────────────────────────────────────────────
    // ■ 실수형 (소수점이 있는 숫자)
    // ─────────────────────────────────────────────
    //
    //   ┌────────────┬──────────┬───────────────────────────┐
    //   │  자료형     │ 크기     │ 정밀도 (유효 자릿수)       │
    //   ├────────────┼──────────┼───────────────────────────┤
    //   │ float      │ 4바이트  │ 약 6~7자리                 │
    //   │ double     │ 8바이트  │ 약 15~16자리 (기본! 추천!) │
    //   └────────────┴──────────┴───────────────────────────┘
    //
    //   실수는 보통 double을 씁니다.
    //   float는 메모리 절약이 필요할 때만 씁니다 (게임 등).

    float  pi_f = 3.14159f;             // f를 붙여야 float (안 붙이면 double)
    double pi_d = 3.14159265358979;     // double = 기본 실수형

    cout << "  ■ 실수형" << endl;
    cout << "  ─────────────────────────────────────" << endl;
    cout << "  float  pi = " << pi_f << endl;
    cout << "  double pi = " << pi_d << endl;

    // ★★★ 부동소수점 오차 — 매우 중요! ★★★
    //
    //   컴퓨터는 소수를 2진수로 저장합니다.
    //   그래서 0.1을 정확히 표현할 수 없어, 미세한 오차가 생깁니다.
    //
    //   결론: 소수끼리 == 로 비교하면 안 됩니다!
    //         (나중에 비교할 때는 오차 범위를 두고 비교)
    //
    float test = 0.1f + 0.2f;
    cout << endl;
    cout << "  ★ 부동소수점 오차 주의!" << endl;
    cout << "  0.1 + 0.2 = " << fixed << setprecision(20) << test << endl;
    cout << "  (정확히 0.3이 아닙니다!)" << endl;
    cout << defaultfloat;  // 출력 형식 원래대로
    cout << endl;

    // ─────────────────────────────────────────────
    // ■ 문자형 / 문자열
    // ─────────────────────────────────────────────
    //
    //   char   = 글자 1개  → 작은따옴표 'A'
    //   string = 글자 여러 개 → 큰따옴표 "Hello"
    //
    //   ★ 작은따옴표와 큰따옴표를 절대 혼동하지 마세요!
    //      'A'   → char (글자 1개)
    //      "A"   → string (문자열)
    //      'AB'  → 에러!  (char에 2글자 불가)

    char   grade   = 'A';           // 글자 1개
    char   newline = '\n';          // 특수 문자 (줄바꿈)
    string name    = "홍길동";       // 문자열
    string empty   = "";            // 빈 문자열

    cout << "  ■ 문자/문자열" << endl;
    cout << "  ─────────────────────────────────────" << endl;
    cout << "  char   grade = '" << grade << "'" << endl;
    cout << "  string name  = \"" << name << "\"" << endl;
    cout << "  string empty = \"" << empty << "\" (빈 문자열, 길이="
         << empty.length() << ")" << endl;
    cout << endl;

    //   특수 문자 (이스케이프 시퀀스)
    //   ─────────────────────────────
    //   \n  줄바꿈
    //   \t  탭 (들여쓰기)
    //   \\  역슬래시 자체
    //   \"  큰따옴표 자체
    //   \'  작은따옴표 자체

    // ─────────────────────────────────────────────
    // ■ 논리형 (bool)
    // ─────────────────────────────────────────────
    //
    //   true  = 참  (출력하면 1)
    //   false = 거짓 (출력하면 0)
    //
    //   0         → false
    //   0이 아닌 수 → true  (1, -1, 42 모두 true)

    bool is_student = true;
    bool is_sleeping = false;

    cout << "  ■ 논리형 (bool)" << endl;
    cout << "  ─────────────────────────────────────" << endl;
    cout << "  is_student  = " << is_student  << "  (1 = true)" << endl;
    cout << "  is_sleeping = " << is_sleeping << "  (0 = false)" << endl;
    cout << "  boolalpha   = " << boolalpha << is_student << ", "
         << is_sleeping << noboolalpha << endl;
    cout << endl;

    // ─────────────────────────────────────────────
    // ■ auto (C++11) — 타입 자동 추론
    // ─────────────────────────────────────────────
    //
    //   컴파일러가 값을 보고 자동으로 타입을 결정합니다.
    //   편리하지만, 가독성을 위해 타입이 불분명할 때는
    //   명시적으로 쓰는 것이 좋습니다.

    auto number  = 100;                 // → int
    auto decimal = 3.14;                // → double
    auto letter  = 'X';                 // → char
    auto text    = string("자동 추론"); // → string (string() 명시 필요)

    cout << "  ■ auto (타입 자동 추론)" << endl;
    cout << "  ─────────────────────────────────────" << endl;
    cout << "  auto number  = " << number << endl;
    cout << "  auto decimal = " << decimal << endl;
    cout << "  auto letter  = " << letter << endl;
    cout << "  auto text    = " << text << endl;
    cout << endl;

    // ─────────────────────────────────────────────
    // ■ sizeof — 메모리 크기 확인
    // ─────────────────────────────────────────────
    //
    //   sizeof(타입) = 그 타입이 메모리에서 차지하는 바이트 수
    //
    //   1 바이트 = 8 비트 = 256가지 값 표현 가능

    cout << "  ■ sizeof (바이트 크기)" << endl;
    cout << "  ─────────────────────────────────────" << endl;
    cout << "  bool      = " << sizeof(bool)      << " 바이트" << endl;
    cout << "  char      = " << sizeof(char)      << " 바이트" << endl;
    cout << "  short     = " << sizeof(short)     << " 바이트" << endl;
    cout << "  int       = " << sizeof(int)       << " 바이트" << endl;
    cout << "  long long = " << sizeof(long long) << " 바이트" << endl;
    cout << "  float     = " << sizeof(float)     << " 바이트" << endl;
    cout << "  double    = " << sizeof(double)    << " 바이트" << endl;
    cout << endl;
}


// =========================================================================
