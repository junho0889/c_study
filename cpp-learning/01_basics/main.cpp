void lesson7_math_functions() {
    cout << "┌──────────────────────────────────────┐" << endl;
    cout << "│  레슨 7 : 수학 함수 (<cmath>)        │" << endl;
    cout << "└──────────────────────────────────────┘" << endl;
    cout << endl;

    // ─── <cmath> 헤더 ───
    //
    //   #include <cmath> 를 하면 사용할 수 있는 수학 함수들
    //
    //   ┌───────────────────┬────────────────────────────────┐
    //   │  함수              │  설명                          │
    //   ├───────────────────┼────────────────────────────────┤
    //   │  sqrt(x)          │  제곱근 (√x)                   │
    //   │  pow(x, y)        │  거듭제곱 (x의 y승)            │
    //   │  abs(x)           │  절대값 |x|                    │
    //   │  ceil(x)          │  올림 (3.2 → 4)               │
    //   │  floor(x)         │  내림 (3.8 → 3)               │
    //   │  round(x)         │  반올림 (3.5 → 4)             │
    //   │  sin(x), cos(x)   │  삼각함수 (라디안 단위)        │
    //   │  log(x)           │  자연로그 (ln)                 │
    //   │  log10(x)         │  상용로그                      │
    //   │  fmod(x, y)       │  실수 나머지                   │
    //   └───────────────────┴────────────────────────────────┘

    cout << "  ■ 주요 수학 함수" << endl;
    cout << "  ─────────────────────────────────────" << endl;
    cout << "  sqrt(16)    = " << sqrt(16)     << "   제곱근" << endl;
    cout << "  pow(2, 10)  = " << pow(2, 10)   << "  2의 10승" << endl;
    cout << "  abs(-7)     = " << abs(-7)      << "    절대값" << endl;
    cout << "  ceil(3.2)   = " << ceil(3.2)    << "    올림" << endl;
    cout << "  floor(3.8)  = " << floor(3.8)   << "    내림" << endl;
    cout << "  round(3.5)  = " << round(3.5)   << "    반올림" << endl;
    cout << "  fmod(7, 3)  = " << fmod(7, 3)   << "    실수 나머지" << endl;
    cout << endl;

    // 실용 예제: 원의 넓이
    const double PI = 3.14159265358979;
    double radius = 5.0;
    double area = PI * pow(radius, 2);   // π × r²

    cout << "  ■ 실용 예제: 원의 넓이" << endl;
    cout << "  ─────────────────────────────────────" << endl;
    cout << "  반지름 = " << radius << endl;
    cout << "  넓이   = PI * r^2 = " << area << endl;

    // 실용 예제: 두 점 사이의 거리
    double x1 = 1, y1 = 2;
    double x2 = 4, y2 = 6;
    double distance = sqrt(pow(x2 - x1, 2) + pow(y2 - y1, 2));

    cout << endl;
    cout << "  ■ 실용 예제: 두 점 사이 거리" << endl;
    cout << "  ─────────────────────────────────────" << endl;
    cout << "  점1 = (" << x1 << ", " << y1 << ")" << endl;
    cout << "  점2 = (" << x2 << ", " << y2 << ")" << endl;
    cout << "  거리 = " << distance << endl;
    cout << endl;
}


