// 레슨 3 — 포인터와 배열의 관계
// =====================================================================
void lesson3_pointer_and_array() {
    cout << "[레슨 3] 포인터와 배열\n\n";

    /*
    ★ 배열 이름 = 첫 번째 요소의 주소 (포인터처럼 동작)
       arr    == &arr[0]
       arr[i] == *(arr + i)    ← 포인터 산술

    ★ 포인터 산술:
       ptr + 1 → "다음 요소의 주소" (바이트가 아니라 요소 단위!)
       int 배열이면 ptr + 1 = 4바이트 뒤
    */

    int arr[] = {10, 20, 30, 40, 50};
    int* ptr = arr;   // 배열 이름 = 첫 번째 요소의 주소

    cout << "  --- 포인터로 배열 접근 ---\n";
    for (int i = 0; i < 5; i++) {
        // 3가지 모두 같은 결과!
        cout << "  arr[" << i << "]=" << arr[i]
             << "  *(ptr+" << i << ")=" << *(ptr + i)
             << "  *(arr+" << i << ")=" << *(arr + i) << "\n";
    }

    // 포인터 증가로 순회
    cout << "\n  포인터 이동으로 순회: ";
    int* p = arr;
    for (int i = 0; i < 5; i++) {
        cout << *p << " ";
        p++;   // 다음 요소로 이동
    }
    cout << "\n";
    cout << endl;
}


