// 레슨 1 — 배열
// =====================================================================
void lesson1_arrays() {
    cout << "[레슨 1] 배열\n\n";

    /*
    ★ 배열 = 같은 타입의 값을 연속으로 저장하는 공간

    선언:  타입 이름[크기];
    초기화: int arr[5] = {1, 2, 3, 4, 5};

    ★ 인덱스는 0부터 시작!
       arr[0] = 첫 번째,  arr[4] = 다섯 번째

    ★ 핵심 함정:  배열 범위를 넘으면 (arr[5] 등)
      → 컴파일 에러가 안 남!  쓰레기 값이 나오거나 크래시!
      → C++에서 가장 위험한 버그 중 하나
    */

    // 선언과 초기화
    int scores[5] = {95, 82, 71, 88, 63};

    cout << "  --- 배열 기본 ---\n";
    cout << "  scores[0] = " << scores[0] << "  (첫 번째)\n";
    cout << "  scores[4] = " << scores[4] << "  (마지막)\n";

    // 배열 크기 구하기
    int size = sizeof(scores) / sizeof(scores[0]);
    cout << "  배열 크기  = " << size << "\n\n";

    // 배열 순회
    cout << "  전체 출력: ";
    for (int i = 0; i < size; i++) {
        cout << scores[i] << " ";
    }
    cout << "\n";

    // 범위 기반 for (더 안전)
    cout << "  범위 기반 : ";
    for (int s : scores) {
        cout << s << " ";
    }
    cout << "\n";

    // 합계 & 평균
    int sum = 0;
    for (int s : scores) sum += s;
    cout << "  합계=" << sum << "  평균=" << (sum / size) << "\n";

    // 2차원 배열
    cout << "\n  --- 2차원 배열 ---\n";
    int matrix[2][3] = {
        {1, 2, 3},
        {4, 5, 6}
    };
    for (int row = 0; row < 2; row++) {
        cout << "  ";
        for (int col = 0; col < 3; col++) {
            cout << matrix[row][col] << " ";
        }
        cout << "\n";
    }
    cout << endl;
}


