// 레슨 2 — 포인터
// =====================================================================
void lesson2_pointers() {
    cout << "[레슨 2] 포인터\n\n";

    /*
    ★ 포인터 = 메모리 주소를 저장하는 변수

    핵심 연산자 2개만 기억하면 됨:
      &변수  → 그 변수의 주소를 알려줌  ("어디에 있니?")
      *포인터 → 그 주소에 있는 값에 접근 ("거기 뭐 있니?")

    선언:
      int x = 42;
      int* ptr = &x;    // ptr에 x의 주소를 저장

    그림으로 이해:
    ┌──────────┐          ┌──────────┐
    │  x = 42  │ ←──────  │ ptr      │
    │ 주소:100 │          │ 값: 100  │
    └──────────┘          └──────────┘
      실제 변수            포인터 변수
                          (주소를 저장)
    */

    int x = 42;
    int* ptr = &x;   // ptr은 x의 주소를 가리킨다

    cout << "  --- 포인터 기본 ---\n";
    cout << "  x의 값      = " << x << "\n";
    cout << "  x의 주소 (&x)  = " << &x << "\n";
    cout << "  ptr의 값     = " << ptr << "  (x의 주소와 같음)\n";
    cout << "  *ptr (역참조) = " << *ptr << "  (x의 값과 같음)\n\n";

    // 포인터를 통해 원본 값 변경
    *ptr = 100;
    cout << "  *ptr = 100 실행 후\n";
    cout << "  x = " << x << "  (원본도 바뀜!)\n\n";

    // nullptr: 아무것도 가리키지 않는 포인터
    int* null_ptr = nullptr;
    cout << "  nullptr = " << null_ptr << "  (아무것도 안 가리킴)\n";

    /*
    ★ 절대 하면 안 되는 것
    1. 초기화 안 된 포인터 사용 → 쓰레기 주소 접근 → 크래시
       int* bad_ptr;
       *bad_ptr = 10;   // 위험!

    2. nullptr 역참조 → 크래시
       int* p = nullptr;
       *p = 10;   // 크래시!

    3. 이미 해제된 메모리 접근 (dangling pointer)
    */
    cout << endl;
}


