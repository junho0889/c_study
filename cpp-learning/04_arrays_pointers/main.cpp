// 레슨 4 — 참조 (Reference)
// =====================================================================
void lesson4_references() {
    cout << "[레슨 4] 참조\n\n";

    /*
    ★ 참조 = 기존 변수의 '별명'  (포인터보다 안전하고 쉬움)

    int x = 10;
    int& ref = x;    // ref는 x의 별명 (같은 메모리)

    ★ 참조 vs 포인터
    ┌──────────────┬──────────────┬──────────────┐
    │              │  참조 (&)    │  포인터 (*)   │
    ├──────────────┼──────────────┼──────────────┤
    │ 초기화       │ 반드시 필요  │ 나중에 가능   │
    │ nullptr      │ 불가능       │ 가능         │
    │ 재지정       │ 불가능       │ 가능         │
    │ 문법         │ 깔끔 (ref)   │ 복잡 (*ptr)  │
    │ 안전성       │ 더 안전      │ 위험할 수 있음│
    └──────────────┴──────────────┴──────────────┘

    결론: 가능하면 참조를 쓰고, 꼭 필요할 때만 포인터를 쓴다
    */

    int x = 42;
    int& ref = x;    // ref는 x의 별명

    cout << "  x   = " << x << "\n";
    cout << "  ref = " << ref << "  (같은 값)\n";
    cout << "  &x  = " << &x << "\n";
    cout << "  &ref= " << &ref << "  (같은 주소!)\n\n";

    ref = 100;       // ref를 바꾸면 x도 바뀜
    cout << "  ref = 100 실행 후\n";
    cout << "  x = " << x << "  ref = " << ref << "\n";
    cout << endl;
}


